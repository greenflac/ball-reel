def read_meminfo() -> dict:
    """Прочитать `/proc/meminfo`. ТОЧКА ВНЕДРЕНИЯ: тест подменяет её целиком (Т4).

    Сделано симметрично `read_smi`: возвращает `{"text": str|None, "why": str}`,
    и `text is None` означает РОВНО ОДНО — спросить нечем. Что памяти мало,
    отсюда не следует НИКОГДА. Без этой точки внедрения тест зеленел бы или
    краснел от того, на какой машине его запустили, а не от кода.
    """
    p = Path(MEMINFO_PATH)
    try:
        return {"text": p.read_text(encoding="utf-8", errors="replace"), "why": ""}
    except OSError as exc:
        return {"text": None,
                "why": (f"{MEMINFO_PATH} не прочитан ({str(exc)[:80]}): спросить "
                        f"нечем. Это НЕ «памяти нет» — так выглядит не-Linux или "
                        f"контейнер с урезанным /proc")}


def parse_meminfo(text: str) -> dict:
    """Разбор `/proc/meminfo` в байты. Нужны ровно две строки, и вторая важнее.

    `MemFree` — это страницы, которых ядро не касалось вовсе. `MemAvailable` —
    оценка САМОГО ЯДРА, сколько можно занять БЕЗ СВОПА, то есть free плюс
    отдаваемая часть страничного кэша и возвратных плит. Разница между ними на
    работающей машине — гигабайты в любую сторону: сервер, который час качал
    18 ГиБ весов, показывает почти нулевой `MemFree` при полностью свободной
    памяти, потому что весь кэш забит этими весами. Мерить по `MemFree` значило
    бы забраковать годную машину сразу после загрузки весов — то есть ровно ту,
    что мы и арендовали.

    `MemAvailable` появился в ядре 3.14. Его отсутствие — «не смогли», а не
    повод подставить `MemFree`: подстановка вернула бы число, которое меряет
    не то (И5).
    """
    vals = {}
    for line in text.splitlines():
        key, _, rest = line.partition(":")
        parts = rest.split()
        if not parts:
            continue
        try:
            n = int(parts[0])
        except ValueError:
            continue
        # Единица в /proc/meminfo — «kB», и это кибибайты (1024), а не 1000:
        # ядро печатает страницы, делённые на 1024. Подпись врёт, число нет.
        vals[key.strip()] = n * 1024 if len(parts) > 1 else n
    return vals


def ram(*, meminfo=read_meminfo, step: str | None = None,
        blocks: int | None = None) -> dict:
    """Хватит ли ОПЕРАТИВНОЙ памяти под то, что блоксвоп из карты вынес.

    ТРЕБУЕМОЕ ЧИСЛО ЗДЕСЬ НЕ ЖИВЁТ. Оно считается
    `fork_preflight.blockswap_weights(step_gb, blocks)`, число блоков берётся
    из `fork_comfy.BLOCKS_TO_SWAP`, ступень весов — из `fork_preflight.STEPS_GB`
    по имени ступени, как это делает соседняя ступень карты. Вписать 9.51 сюда
    значило бы завести второй источник истины (Е1): при смене `blocks_to_swap`
    в графе приёмка молча проверяла бы вчерашнее требование.

    Три исхода (Р1):

        годно        доступно >= требуется блоксвопу + запас
        негодно      доступно меньше — прогон уйдёт в своп или не стартует
        не смогли    /proc/meminfo нет, MemAvailable нет, ступень неизвестна

    Отсутствие `/proc/meminfo` — это НЕ «памяти нет»: так выглядит macOS,
    Windows и контейнер с урезанным /proc. Свести это к «негодно» значило бы
    вернуть исправную машину.
    """
    # Умолчания разрешаются В ТЕЛЕ, а не в сигнатуре: значение в сигнатуре
    # привязывается на момент определения функции, и мутация константы после
    # импорта до вызова не доезжает — тест мутации молча зеленеет (поймано на
    # ступени карты, см. `card`).
    step = DEFAULT_STEP if step is None else step
    blocks = _fc.BLOCKS_TO_SWAP if blocks is None else blocks

    step_gb = _fp.STEPS_GB.get(step)
    if step_gb is None:
        return {"outcome": UNMEASURED, "total_gib": None, "available_gib": None,
                "need_gib": None, "left_gib": None, "margin_gib": RAM_MARGIN_GIB,
                "step": step, "blocks": blocks,
                "note": (f"ступени {step} нет в модели памяти "
                         f"({sorted(_fp.STEPS_GB)}) — СКОЛЬКО ТРЕБУЕТСЯ, "
                         f"посчитать нечем. Это «не смогли», а не «хватает»")}
    swap = _fp.blockswap_weights(step_gb, blocks)
    if swap["outcome"] != PASS or swap["ram_gb"] is None:
        return {"outcome": UNMEASURED, "total_gib": None, "available_gib": None,
                "need_gib": None, "left_gib": None, "margin_gib": RAM_MARGIN_GIB,
                "step": step, "blocks": blocks,
                "note": f"требование блоксвопа не посчитано: {swap['note']}"}
    need = swap["ram_gb"]

    got = meminfo()
    if got.get("text") is None:
        return {"outcome": UNMEASURED, "total_gib": None, "available_gib": None,
                "need_gib": need, "left_gib": None, "margin_gib": RAM_MARGIN_GIB,
                "step": step, "blocks": blocks,
                "note": (f"блоксвоп требует {need} ГиБ ОЗУ, а спросить машину "
                         f"нечем: " + (got.get("why") or "меминфо не прочитан"))}
    vals = parse_meminfo(got["text"])
    total = vals.get("MemTotal")
    avail = vals.get("MemAvailable")
    if avail is None or total is None:
        return {"outcome": UNMEASURED, "total_gib": _gib(total),
                "available_gib": None, "need_gib": need, "left_gib": None,
                "margin_gib": RAM_MARGIN_GIB, "step": step, "blocks": blocks,
                "note": (f"в {MEMINFO_PATH} нет "
                         + ("MemTotal" if total is None else "MemAvailable")
                         + f". MemFree ПОДСТАВЛЯТЬ НЕЛЬЗЯ: он меряет другое "
                           f"(кэш весов в него не входит). Требуется {need} ГиБ")}

    avail_gib = _gib(avail)
    need_total = round(need + RAM_MARGIN_GIB, 3)
    left = round(avail_gib - need, 3)
    ok = avail_gib >= need_total
    swapped_note = (f"свопится {blocks} из {_fp.BLOCKS_TOTAL} блоков"
                    if blocks else "БЛОКСВОП ВЫКЛЮЧЕН (blocks_to_swap=0): "
                                   "вся модель остаётся на карте")
    return {
        "outcome": PASS if ok else FAIL,
        "total_gib": _gib(total), "available_gib": avail_gib,
        "need_gib": need, "need_total_gib": need_total, "left_gib": left,
        "margin_gib": RAM_MARGIN_GIB, "step": step, "blocks": blocks,
        "note": (f"ОЗУ всего {_gib(total)} ГиБ, доступно СЕЙЧАС {avail_gib} ГиБ "
                 f"(MemAvailable, а не MemFree). Блоксвоп на ступени {step} "
                 f"переносит в ОЗУ {need} ГиБ ({swapped_note}), с запасом "
                 f"{RAM_MARGIN_GIB} ГиБ нужно {need_total} ГиБ; остаётся "
                 f"{left} ГиБ"
                 + ("" if ok else " — НЕ ХВАТАЕТ, и нехватка здесь даёт не "
                                  "отказ, а своп на диск: блоки поедут на "
                                  "карту через блочное устройство")
                 + f". Запас {RAM_MARGIN_GIB} ГиБ ВЫБРАН, не измерен"),
    }


