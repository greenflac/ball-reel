def read_smi() -> dict:
    """Опросить карту. ТОЧКА ВНЕДРЕНИЯ: тест подменяет её целиком (Т4).

    Возвращает `{"text": str|None, "why": str}`. `text is None` означает
    РОВНО ОДНО: спросить нечем. Что карты нет, отсюда не следует.

    НЕПРОВЕРЕНО (Ц4, Ц10): имена полей запроса —
    `name,memory.total,compute_cap,driver_version` — и то, что вывод CSV
    выглядит как «NVIDIA A16, 16376 MiB, 8.6, 550.90.07», НИ РАЗУ НЕ ПОЛУЧЕНЫ
    КОМАНДОЙ: утилиты в этой среде нет. Разбор проверен на строке, сочинённой
    тестом, — то есть проверен разбор, а не контракт утилиты. Первый же прогон
    на машине либо подтвердит имена полей, либо вернёт «Field ... is not a
    valid field», и это будет находкой, а не поломкой.
    """
    if shutil.which(SMI_BIN) is None:
        return {"text": None,
                "why": (f"{SMI_BIN} не найден: спросить нечем. Это НЕ «карты "
                        f"нет» — утилита ставится вместе с драйвером")}
    try:
        raw = subprocess.run(
            [SMI_BIN, "--query-gpu=name,memory.total,compute_cap,driver_version",
             "--format=csv,noheader"],
            capture_output=True, text=True, timeout=SMI_TIMEOUT_S)
    except (OSError, subprocess.SubprocessError) as exc:
        return {"text": None, "why": f"{SMI_BIN} не отработал: {str(exc)[:120]}"}
    if raw.returncode != 0:
        return {"text": None,
                "why": f"{SMI_BIN} вернул {raw.returncode}: {raw.stderr[:120]}"}
    return {"text": raw.stdout, "why": ""}


def card(*, smi=read_smi, length: int | None = None,
         step: str | None = None, blocks: int | None = None) -> dict:
    """Что за карты стоят и сколько ГиБ запаса остаётся на выбранной ступени.

    Разбор CSV берётся из `fork_preflight.parse_smi`, бюджет памяти — из
    `fork_preflight.budget` (Е1). Своей модели памяти здесь НЕТ и быть не
    должно: вторая модель разошлась бы с первой молча.

    ОГОВОРКА ПРО ЕДИНИЦЫ. `parse_smi` делит MiB на 1024 и называет результат
    «ГБ». Арифметически это ГиБ, и ступени в `STEPS_GB` пришли из тех же
    гибибайтов лок-файла — то есть числа сравнимы, а подпись у них неточная.
    Здесь они печатаются как ГиБ.

    ЗАПАС СЧИТАЕТСЯ ПРИ ТОМ БЛОКСВОПЕ, КОТОРЫЙ СТОИТ В ГРАФЕ (`blocks`), а не
    при нулевом. Исправлено 18.08.2026: до этого ступень звала `budget` без
    `blocks_to_swap`, то есть мерила конфигурацию, КОТОРУЮ МЫ НЕ ЗАПУСКАЕМ, —
    ровно тот дефект, который на этом проекте уже находили у самого `budget`.
    Приёмка из-за него браковала утверждённую карту на умолчании проекта
    (Q4_K_M, 77 кадров): 15.97 из 15.99, запас 0.02. Со свопом 38 на карте
    лежит 6.71 ГиБ, и это тот же расчёт, из которого ступень ОЗУ берёт своё
    требование (Е1) — два числа одного переноса перестали считаться порознь.

    ТРИ ИСХОДА У ОБЪЁМА ПАМЯТИ (Р1). Ниже `GPU_MEMORY_DOUBT_GIB` — «не та
    карта». Выше `MIN_GPU_MEMORY_GIB` — «та». МЕЖДУ НИМИ — «не смогли
    отличить», потому что раскладку памяти A16 никто не наблюдал (см. планку).

    ИМЯ СВЕРЯЕТСЯ У КАЖДОЙ КАРТЫ, И НЕСОВПАВШЕЕ ИМЯ — ЭТО «НЕ ГОДНО», А НЕ
    «НЕ СМОГЛИ». Решено осознанно, вот из чего. «Не смогли» — исход про
    НЕЗНАНИЕ прибора: он про то, что мы не наблюдали (раскладка памяти A16) или
    не получили (`nvidia-smi` не отработал). Здесь незнания нет: имя печатает
    ДРАЙВЕР той карты, что стоит в машине, — это прямое свидетельство (Е2),
    полученное на этой самой машине, и «Tesla T4» означает Tesla T4 при любой
    раскладке памяти. Арендовано не то, что утверждено и оплачено, — это
    НАХОДКА ПРИЁМКИ, ровно как `count < EXPECTED_GPU_COUNT`, и сводить её к
    «не смогли» значило бы предъявить владельцу сомнение вместо факта.
    Обратное свернуло бы Р1 в другую сторону: код возврата 2 читается как
    «проверьте руками», а тут проверять нечего — карту привезли не ту.

    ТРЕТИЙ ИСХОД У ИМЕНИ ВСЁ-ТАКИ ЕСТЬ, и он ровно там, где кончается
    свидетельство: имя в строке ПУСТОЕ. Тогда сверять нечем — это «не смогли»,
    и назвать пустое поле подменой было бы враньём про железо, выведенным из
    вывода утилиты. Прежняя редакция ловила имена через `any(...)` по всем
    картам сразу и на четырёх безымянных строках отвечала «привезли не ту
    карту», не имея ни одного имени на руках.

    ЧТО СЧИТАЕТСЯ СОВПАДЕНИЕМ — вхождение `EXPECTED_GPU_NAME`, см. комментарий
    у самой константы: vGPU-профиль A16 зовётся «NVIDIA A16-16Q» и это ТА
    САМАЯ карта, ломоть которой ловит уже не имя, а ступень памяти.
    """
    # Умолчания разрешаются В ТЕЛЕ, а не в сигнатуре, и это не стиль.
    # `def card(step=DEFAULT_STEP)` привязывает значение НА МОМЕНТ ОПРЕДЕЛЕНИЯ
    # функции: подмена константы после импорта не доезжает до вызова, и тест
    # мутации молча зеленеет. Поймано мутацией (Т1) на первом же прогоне.
    length = DEFAULT_LENGTH if length is None else length
    step = DEFAULT_STEP if step is None else step
    blocks = _fc.BLOCKS_TO_SWAP if blocks is None else blocks
    got = smi()
    if got.get("text") is None:
        return {"outcome": UNMEASURED, "count": None, "gpus": [],
                "note": got.get("why") or "карта не опрошена"}
    parsed = _fp.parse_smi(got["text"])
    if parsed["outcome"] != PASS:
        return {"outcome": UNMEASURED, "count": None, "gpus": [],
                "note": f"{SMI_BIN} ответил, но разобрать нечего: {parsed['note']}"}

    cards = parsed["gpus"]
    count = len(cards)
    mems = [g["memory_gb"] for g in cards if g["memory_gb"] is not None]
    lines = [f"{g['name']} {g['memory_gb']} ГиБ cc{g['compute_cap']} "
             f"драйвер {g['driver']}" for g in cards]
    if not mems:
        return {"outcome": UNMEASURED, "count": count, "gpus": cards,
                "note": (f"карт {count} ({'; '.join(lines)}), но объём памяти "
                         f"ни у одной не разобран — запас считать не от чего")}

    smallest = min(mems)
    # Источник числа памяти называется вызову (Е2, И4): здесь это ЗАМЕР
    # утилитой на этой самой машине, а не допущение — в отличие от всех
    # таблиц проекта, посчитанных до 18.08 через выдуманное 15.99.
    plan = _fp.budget(smallest, length=length, blocks_to_swap=blocks,
                      memory_source=f"{SMI_BIN} на этой машине")
    row = next((r for r in plan.get("rows", []) if r["step"] == step), None)
    headroom = row["headroom_gb"] if row else None

    beefs = []
    doubts = []
    # ИМЯ СВЕРЯЕТСЯ У КАЖДОЙ КАРТЫ ПООТДЕЛЬНОСТИ, А НЕ ЧЕРЕЗ `any`.
    # Прежняя редакция считала находкой только случай, когда НИ ОДНА карта не
    # похожа на утверждённую. Наблюдалось: три A16 плюс чужая RTX 3090 давали
    # «годно, карт 4» — то есть одной правильной карты из четырёх хватало,
    # чтобы прибор промолчал про три остальные. Разнородная машина — это и
    # есть типичная подмена: докладывают недостающее тем, что нашлось.
    wrong = [(i, g["name"]) for i, g in enumerate(cards, 1)
             if (g["name"] or "").strip()
             and EXPECTED_GPU_NAME.lower() not in g["name"].lower()]
    nameless = [i for i, g in enumerate(cards, 1)
                if not (g["name"] or "").strip()]
    matched = count - len(wrong) - len(nameless)
    if wrong:
        beefs.append("утверждена " + EXPECTED_GPU_NAME + ", а nvidia-smi "
                     "называет иначе " + str(len(wrong)) + " из "
                     + str(count) + ": "
                     + "; ".join(f"карта {i} — {nm}" for i, nm in wrong)
                     + " — привезли не ту карту (это ИМЯ ОТ ДРАЙВЕРА, а не "
                       "вывод по объёму памяти)")
    if nameless:
        doubts.append("у " + str(len(nameless)) + " карт из " + str(count)
                      + " (" + ", ".join(str(i) for i in nameless) + ") имя в "
                      "выводе nvidia-smi пустое — СВЕРИТЬ ПО ИМЕНИ НЕЧЕМ. Это "
                      "не «не та карта»: пустое поле говорит про вывод "
                      "утилиты, а не про железо")
    if count < EXPECTED_GPU_COUNT:
        beefs.append(f"карт {count}, а утверждено {EXPECTED_GPU_COUNT} "
                     f"(A16 — четыре независимых GPU, память НЕ складывается)")
    if smallest < GPU_MEMORY_DOUBT_GIB:
        beefs.append(f"наименьшая карта {smallest} ГиБ — ниже "
                     f"{GPU_MEMORY_DOUBT_GIB}, столько не печатает ни одна "
                     f"карта класса 16 ГБ")
    elif smallest < MIN_GPU_MEMORY_GIB:
        doubts.append(f"наименьшая карта {smallest} ГиБ — между "
                      f"{GPU_MEMORY_DOUBT_GIB} и {MIN_GPU_MEMORY_GIB}. НЕ "
                      f"СМОГЛИ ОТЛИЧИТЬ утверждённую карту от подмены ПО "
                      f"ОБЪЁМУ: сколько печатает A16 на самом деле, никто не "
                      f"наблюдал (nvidia.com закрыт, карты не было). Судите "
                      f"по имени и по запасу, а число пришлите владельцу")
    if row is None:
        beefs.append(f"ступени {step} нет в модели памяти "
                     f"({sorted(_fp.STEPS_GB)}) — запас считать нечем")
    elif headroom is not None and headroom < _fp.MIN_HEADROOM_GB:
        beefs.append(f"на ступени {step} запас {headroom} ГиБ при требуемых "
                     f"{_fp.MIN_HEADROOM_GB} — впритык или не влезает")

    return {
        "outcome": FAIL if beefs else (UNMEASURED if doubts else PASS),
        "count": count, "gpus": cards, "driver": cards[0]["driver"],
        "name_matched": matched, "name_wrong": len(wrong),
        "name_unreadable": len(nameless),
        "wrong_names": [nm for _, nm in wrong],
        "smallest_gib": smallest, "step": step, "length": length,
        "blocks": blocks, "headroom_gib": headroom, "doubts": doubts,
        "need_gib": row["total_gb"] if row else None,
        "note": (f"карт {count}: {'; '.join(lines)}. На ступени {step} при "
                 f"блоксвопе {blocks} нужно "
                 f"{row['total_gb'] if row else '?'} ГиБ из {smallest}, "
                 f"ЗАПАС {headroom} ГиБ при {length} кадрах. ИМЕНА: сверено "
                 f"{count}, совпало с {EXPECTED_GPU_NAME} {matched}, не "
                 f"совпало {len(wrong)}, сверить нечем {len(nameless)}"
                 + (". " + "; ".join(beefs) if beefs else "")
                 + (". " + "; ".join(doubts) if doubts else "")
                 + ". Объём памяти ЗАМЕРЕН здесь утилитой, а бюджет — РАСЧЁТ "
                   "по fork_preflight; про ECC без карты не известно ничего"),
    }


