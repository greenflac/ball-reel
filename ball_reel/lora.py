@dataclass
class Trial:
    """Один замер гейта на одном промте.

    `key` — то, что ОБЩЕЕ у пары: промт и сид. По нему пара и собирается.
    Сравнивать средние по двум разным наборам промтов нельзя: разница между
    «в спортзале» и «под стеклянной крышей» больше, чем весь измеряемый эффект.

    `distance` — дистанция ArcFace до РЕАЛЬНОГО фото. `None` — гейт не смог
    судить (лицо мельче порога, не найдено): это не «плохо», это «не измерено»,
    и дальше оно так и едет.
    """

    key: str
    distance: float | None
    judged: bool = True


def probe_prompts(trigger: str, *, limit: int | None = None) -> list:
    """Промты для проверки ОБОБЩЕНИЯ. Не пересекаются с обучающими.

    Непересечение не декларируется, а ВЫЧИСЛЯЕТСЯ: сцены сверяются со всеми
    значениями `dataset.VARIATIONS`. Спрашивать модель о том, на чём её учили, —
    это спросить генератор, получилось ли у него; правило проекта запрещает это
    прямо, и здесь оно исполняется кодом.
    """
    from .dataset import VARIATIONS

    trained = {v.lower() for values in VARIATIONS.values() for v in values}
    rows = []
    for scene in PROBE_SCENES:
        if scene.lower() in trained:
            continue
        rows.append({"key": scene, "prompt": f"{trigger}, {scene}, photographic"})
    return rows[:limit] if limit else rows


def _mean(xs: list) -> float:
    return sum(xs) / len(xs)


def _stdev(xs: list) -> float:
    """Выборочное отклонение. Одна точка -> 0.0, а не деление на ноль."""
    if len(xs) < 2:
        return 0.0
    m = _mean(xs)
    return (sum((x - m) ** 2 for x in xs) / (len(xs) - 1)) ** 0.5


def accept(baseline: list, candidate: list, *, generator: str, selector: str,
           judge: str, min_pairs: int = MIN_PAIRS,
           min_effect: float = MIN_EFFECT,
           trained_keys: set | None = None) -> dict:
    """Стало лучше, стало хуже, или не смогли измерить. РОВНО ТРИ исхода.

    `baseline` — замеры БЕЗ LoRA, `candidate` — С LoRA, на тех же промтах и
    сидах. Меньшая дистанция лучше, поэтому эффект считается как
    `base - cand`: положительный эффект = приблизились к человеку.

    ПОЧЕМУ СРАВНЕНИЕ ПАРНОЕ. Разброс между промтами больше измеряемого эффекта.
    Сравнив средние по двум наборам, мы измерим, какие сцены попались, а не что
    сделала LoRA. Парная разность убирает сцену из уравнения целиком.

    ПОЧЕМУ «НЕРАЗЛИЧИМО» ОТНЕСЕНО К «НЕ ИЗМЕРЕНО», А НЕ К ТРЕТЬЕМУ ИСХОДУ.
    Прибор с известным собственным разбросом (0.18-0.22 на одной и той же
    личности, ИЗМЕРЕНО) не различает разницу мельче половины этого разброса.
    Сказать в такой ситуации «не стало лучше» — значит выдать предел прибора за
    свойство модели. Мы измеряли и не различили: это «не измерено», и причина
    названа отдельной строкой.

    ПОРЯДОК ПРОВЕРОК тот же, что в предполёте: сначала то, что обесценивает
    сравнение целиком (замкнутый круг, утечка обучающих промтов), потом то, что
    делает его слабым (мало пар, низкое покрытие), и только потом арифметика.
    """
    from .dataset import independence_report
    from .identity_arcface import MIN_COVERAGE

    out: dict = {
        "verdict": "НЕ ИЗМЕРЕНО", "reason": "", "effect": None,
        "pairs": 0, "coverage": None, "wins": 0, "losses": 0,
        "baseline_median": None, "candidate_median": None,
        "predicted": PREDICTED_NO_ARCFACE_GAIN, "matches_prediction": None,
        "independence": None, "notes": [],
    }

    # 1. ЗАМЫСЕЛ. Замкнутый круг обесценивает любую цифру ниже.
    ind = independence_report(generator=generator, selector=selector,
                              judge=judge)
    out["independence"] = ind
    if not ind["independent"]:
        out["reason"] = ("круг замкнут на судью, сравнивать нечего: "
                         + ind["note"])
        return out

    by_key = {t.key: t for t in baseline}
    keys = [t.key for t in candidate if t.key in by_key]
    if not keys:
        out["reason"] = ("нет ни одной общей пары: `baseline` и `candidate` "
                         "сняты на разных промтах, и разница между сценами "
                         "больше измеряемого эффекта")
        return out

    # 2. УТЕЧКА. Промт из обучения проверяет память, а не обобщение.
    if trained_keys:
        leaked = sorted(set(keys) & set(trained_keys))
        if leaked:
            out["reason"] = (
                f"утечка обучающих промтов в проверочный набор "
                f"({len(leaked)} из {len(keys)}): {leaked[0]!r} и подобные. "
                f"Так измеряется запоминание, а не перенос личности на новые "
                f"сцены. Проверочный набор строится `probe_prompts`")
            return out

    # 3. ПОКРЫТИЕ. «Нечего было судить» — не то же, что «прошло».
    pairs = [(by_key[k].distance, next(t for t in candidate if t.key == k).distance)
             for k in keys]
    usable = [(b, c) for b, c in pairs if b is not None and c is not None]
    coverage = len(usable) / len(pairs)
    out["coverage"] = round(coverage, 3)
    out["pairs"] = len(usable)

    if coverage < MIN_COVERAGE:
        out["reason"] = (
            f"судимых пар {coverage:.0%} при нижней границе {MIN_COVERAGE:.0%}: "
            f"гейт не смог судить большинство кадров. Лечится не обучением, а "
            f"кадрировкой и разрешением — лицо должно быть крупнее порога")
        return out
    if len(usable) < min_pairs:
        out["reason"] = (f"пар всего {len(usable)} при нижней границе "
                         f"{min_pairs}: средняя разница на таком числе "
                         f"определяется одним неудачным кадром")
        return out

    # 4. АРИФМЕТИКА. Только теперь.
    deltas = [b - c for b, c in usable]          # >0 = кандидат ближе к человеку
    effect = _mean(deltas)
    spread = _stdev(deltas)
    stderr = spread / (len(deltas) ** 0.5) if deltas else 0.0
    resolution = max(min_effect, RESOLUTION_SIGMAS * stderr)

    out["effect"] = round(effect, 4)
    out["spread"] = round(spread, 4)
    out["resolution"] = round(resolution, 4)
    out["wins"] = sum(1 for d in deltas if d > 0)
    out["losses"] = sum(1 for d in deltas if d < 0)
    out["baseline_median"] = round(_median([b for b, _ in usable]), 4)
    out["candidate_median"] = round(_median([c for _, c in usable]), 4)

    if abs(effect) < resolution:
        out["reason"] = (
            f"разница {effect:+.4f} мельче разрешающей способности "
            f"{resolution:.4f}. Прибор столько не различает: на одной и той же "
            f"личности он сам гуляет в полосе 0.18-0.22 (ИЗМЕРЕНО). Это не "
            f"«не стало лучше» — это «не смогли отличить»")
    elif effect > 0:
        out["verdict"] = "ЛУЧШЕ"
    else:
        out["verdict"] = "ХУЖЕ"

    # Совпало ли с тем, что было предсказано ДО обучения. Предсказание записано
    # в константе, а не дописано сюда после прогона.
    out["matches_prediction"] = (out["verdict"] != "ЛУЧШЕ")

    # Знаковая проверка, не зависящая от среднего: одна выпавшая пара может
    # утащить среднее, но не может перевернуть счёт побед.
    if out["verdict"] in ("ЛУЧШЕ", "ХУЖЕ"):
        majority = out["wins"] > out["losses"]
        if majority != (out["verdict"] == "ЛУЧШЕ"):
            out["notes"].append(
                f"среднее и счёт пар расходятся: вердикт «{out['verdict']}», "
                f"а пар выиграно {out['wins']} против {out['losses']}. Значит "
                f"эффект держится на нескольких выбросах, а не на всём наборе — "
                f"смотреть на эти кадры ГЛАЗАМИ прежде, чем верить числу")
    return out


def _median(xs: list) -> float:
    ys = sorted(xs)
    n = len(ys)
    if not n:
        return 0.0
    mid = n // 2
    return ys[mid] if n % 2 else (ys[mid - 1] + ys[mid]) / 2


def render_acceptance(result: dict) -> str:
    """Отчёт приёмки. Отрицательный исход подаётся как РЕЗУЛЬТАТ.

    Это не смягчение формулировок. Проигрыш по дистанции ArcFace был ПРЕДСКАЗАН
    до обучения и записан в `PREDICTED_NO_ARCFACE_GAIN` — с основанием и с
    числами. Предсказание, которое сбылось, — это работающая модель явления, и
    подавать её как неудачу было бы просто неверно.

    Неудачей здесь было бы другое: не суметь измерить, измерить замкнутым
    кругом, или получить выигрыш и не заметить, что он куплен утечкой.
    """
    v = result["verdict"]
    lines = [f"ПРИЁМКА LoRA: {v}"]

    if v == "НЕ ИЗМЕРЕНО":
        lines += [
            f"  причина: {result['reason']}",
            "",
            "  Это отдельный исход, а не разновидность «плохо». Он говорит о",
            "  ПРИБОРЕ, а не о модели: пока он держится, ни «лучше», ни «хуже»",
            "  произнести нельзя, и подавать что-либо из этого как вывод —",
            "  значит выдать желаемое за измеренное.",
        ]
        return "\n".join(lines)

    lines += [
        f"  дистанция ArcFace: {result['baseline_median']} без LoRA -> "
        f"{result['candidate_median']} с LoRA",
        f"  парный эффект: {result['effect']:+.4f} "
        f"(разрешающая способность {result['resolution']:.4f})",
        f"  пар {result['pairs']}, выиграно {result['wins']}, "
        f"проиграно {result['losses']}, покрытие {result['coverage']:.0%}",
        f"  независимость судьи: {result['independence']['note']}",
    ]

    if v == "ХУЖЕ":
        lines += [
            "",
            "  ЭТО ОТРИЦАТЕЛЬНЫЙ РЕЗУЛЬТАТ, И ОН БЫЛ ПРЕДСКАЗАН ДО ОБУЧЕНИЯ.",
            f"  Предсказание: {result['predicted']}.",
            "",
            "  Основание предсказания — измерение, а не осторожность: материал",
            "  набора порождён шлюзом, у которого дрейф до оригинала 0.345 и",
            "  0.367 при баре «тот же человек» 0.35. Обученная на таком наборе",
            "  LoRA не может оказаться ближе к человеку, чем её материал.",
            "",
            "  ЧТО КУПЛЕНО ВМЕСТО МЕТРИКИ. До LoRA лицо обусловливалось",
            "  эмбеддингом ArcFace и им же проверялось: судья был частью",
            "  судимого, и любая цифра идентичности была цифрой о самой себе.",
            "  Теперь порождение, отбор и суд разведены, и НАСТОЯЩАЯ величина",
            "  дистанции стала наблюдаемой — включая то, что она выросла.",
            "",
            "  Иначе говоря: не метрика ухудшилась, а прибор перестал врать.",
            "  Число, которое видно сейчас, честнее прежнего вне зависимости",
            "  от того, в какую сторону оно сдвинулось.",
            "",
            "  ЧТО ДЕЛАТЬ ДАЛЬШЕ, по убыванию ожидаемой отдачи:",
            "   1. поднять качество МАТЕРИАЛА — потолок здесь ставит он, а не",
            "      обучение: ни ранг, ни шаги не поднимут набор выше 0.345;",
            "   2. пройти лестницу рангов (`RANK_LADDER`) и промежуточные",
            "      чекпоинты — сравнивать этой же функцией, а не глазами;",
            "   3. проверить, не утекли ли обучающие промты в проверочные:",
            "      выигрыш от утечки выглядит убедительнее честного проигрыша.",
        ]
    else:
        lines += [
            "",
            "  Выигрыш получен на промтах, которых в обучении не было, и на",
            "  судье, который не участвовал ни в порождении, ни в отборе.",
            "  Прежде чем радоваться — посмотреть кадры ГЛАЗАМИ: на этом",
            "  проекте лучший результат дня по метрикам изображал человека",
            "  в бальном платье вместо упражнения.",
        ]
        if not result["matches_prediction"]:
            lines += [
                "",
                "  Исход НЕ СОВПАЛ с предсказанием, сделанным до обучения.",
                f"  Предсказывалось: {result['predicted']}.",
                "  Расхождение предсказания с измерением — повод перепроверить",
                "  измерение, а не праздновать: первым делом искать утечку.",
            ]
    for n in result.get("notes", []):
        lines.append(f"  ! {n}")
    return "\n".join(lines)


