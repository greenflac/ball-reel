def layout(samples: list) -> list:
    """Как разложить кадры по папкам. Тренер задаёт повторы ПАПКОЙ, не файлом.

    Отсюда следствие, о которое спотыкаются: реальный якорь с весом
    `dataset.REAL_ANCHOR_REPEATS` обязан лежать в ОТДЕЛЬНОЙ папке. Свалив всё в
    одну, вес якоря теряется молча — обучение пройдёт, а набор окажется тем
    самым «уплывшим от целевого человека», от которого якорь и защищает.
    """
    groups: dict = {}
    for s in samples:
        if s.kept is False:
            continue
        groups.setdefault(s.repeats, []).append(s)
    return [{"dir": f"{r}_subject", "num_repeats": r,
             "count": len(rows), "paths": [s.path for s in rows],
             "origins": sorted({s.origin for s in rows})}
            for r, rows in sorted(groups.items(), reverse=True)]


def dataset_toml(samples: list, *, root: str, cfg: TrainConfig,
                 trigger: str) -> str:
    """Конфиг набора для тренера. Ключи сверены с живым `docs/config_README-en.md`.

    `class_tokens` намеренно НЕ задаётся: подписи лежат в `.txt` рядом с
    кадрами, и их пишет `dataset.caption_for` по своему правилу — описывать то,
    что меняется, и молчать о том, что должно прилипнуть к триггеру. Задав
    `class_tokens`, мы завели бы второй источник подписи, и разошлись бы они
    незаметно.
    """
    lines = [
        "# Сгенерировано ball_reel.lora — править руками не нужно.",
        f"# Триггер: {trigger}. Подписи — в .txt рядом с кадрами.",
        "[general]",
        "shuffle_caption = false",
        "  # порядок в подписи несёт смысл: триггер стоит первым и должен там",
        "  # остаться, иначе к нему прилипнет не человек, а случайная ось",
        "caption_extension = '.txt'",
        "keep_tokens = 1",
        "  # первый токен (триггер) не перемешивается никогда",
        "",
        "[[datasets]]",
        f"resolution = {cfg.resolution}",
        f"batch_size = {cfg.batch_size}",
        "enable_bucket = true",
        "bucket_no_upscale = true",
        "  # кадры не растягиваются вверх: апскейл добавляет пикселей, но не",
        "  # информации, а лицо от него мылится",
        "flip_aug = false",
        "  # ЗЕРКАЛО ЗАПРЕЩЕНО: приметы меняют сторону. Объяснение целиком —",
        "  # в `dataset.augmentations`. Это не настройка, а условие продукта",
        "color_aug = false",
        "  # несовместимо с кэшем латентов, и не нужно: свет варьируется",
        "  # самим набором",
    ]
    for group in layout(samples):
        lines += [
            "",
            "  [[datasets.subsets]]",
            f"  image_dir = '{root.rstrip('/')}/{group['dir']}'",
            f"  num_repeats = {group['num_repeats']}",
            f"  # {group['count']} кадров, происхождение: "
            f"{', '.join(group['origins'])}",
        ]
    return "\n".join(lines) + "\n"


def command(cfg: TrainConfig, *, trainer_dir: str, base_model: str | None = None,
            dataset_config: str, output_dir: str, output_name: str) -> list:
    """Команда запуска тренера. Список аргументов, а не строка.

    Список — потому что строку нужно экранировать, а экранирование пути с
    пробелом («C:\\Program Files») — классический способ запустить обучение не
    на том наборе и узнать об этом через полчаса.

    Все имена флагов сверены с живым разборщиком аргументов апстрима.

    **НЕПРОВЕРЕНО, И ЭТО ЕДИНСТВЕННОЕ МЕСТО МОДУЛЯ, ГДЕ МЫ ПИШЕМ ПРОТИВ
    НЕСВЕРЕННОГО ПОВЕДЕНИЯ.** Справка тренера описывает
    `--pretrained_model_name_or_path` как «директорию модели в формате diffusers
    ИЛИ файл чекпоинта StableDiffusion» — про идентификатор репозитория HF там
    не сказано ничего. Мы по умолчанию передаём именно идентификатор, потому что
    он один и тот же с генерацией, а расхождение базы между обучением и
    применением проявляется только тем, что «что-то не то с лицом».

    Если тренер его не примет — это видно СРАЗУ, на первой секунде, и лечится
    одной строкой: скачать снапшот заранее и передать локальный путь
    (`huggingface-cli download <repo> --local-dir <dir>`), либо указать локальный
    `.safetensors`. Порядок действий — в `LORA_RUNBOOK.md`, шаг 5.
    """
    if base_model is None:
        # База — та же, что у генерации. Второе объявление здесь означало бы,
        # что LoRA обучена для одной модели, а применяется к другой, и понять
        # это можно было бы только по тому, что «что-то не то с лицом».
        from .animate import BASE_MODEL

        base_model = BASE_MODEL

    args = [
        "accelerate", "launch",
        f"{trainer_dir.rstrip('/')}/{TRAINER['script']}",
        "--pretrained_model_name_or_path", base_model,
        "--dataset_config", dataset_config,
        "--output_dir", output_dir,
        "--output_name", output_name,
        "--network_module", TRAINER["network_module"],
        "--network_dim", str(cfg.rank),
        # Задаётся ВСЕГДА и явно: умолчание тренера — 1, см. TRAINER_TRAPS.
        "--network_alpha", str(cfg.alpha),
        "--learning_rate", f"{cfg.learning_rate:g}",
        "--optimizer_type", cfg.optimizer,
        "--lr_scheduler", cfg.lr_scheduler,
        "--lr_warmup_steps", str(cfg.lr_warmup_steps),
        "--max_train_steps", str(cfg.max_train_steps),
        "--train_batch_size", str(cfg.batch_size),
        "--mixed_precision", cfg.mixed_precision,
        "--save_precision", cfg.save_precision,
        "--save_model_as", "safetensors",
        "--save_every_n_epochs", str(SAVE_EVERY_N_EPOCHS),
        "--clip_skip", str(cfg.clip_skip),
        "--seed", str(cfg.seed),
        "--sdpa",
        "--max_data_loader_n_workers", "1",
    ]
    if cfg.cache_latents:
        args += ["--cache_latents", "--cache_latents_to_disk"]
    if cfg.gradient_checkpointing:
        args += ["--gradient_checkpointing"]
    if cfg.train_text_encoder:
        args += ["--text_encoder_lr", f"{cfg.text_encoder_lr:g}"]
    else:
        args += ["--network_train_unet_only"]
    return args


