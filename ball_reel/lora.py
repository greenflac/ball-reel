def trainable_params(rank: int, *, train_text_encoder: bool = True) -> int:
    """Сколько параметров реально обучается. РАСЧЁТ, не оценка."""
    n = rank * LORA_PARAMS_PER_RANK_UNET
    if train_text_encoder:
        n += rank * LORA_PARAMS_PER_RANK_TE
    return n


def lora_file_mb(rank: int, *, train_text_encoder: bool = True) -> float:
    """Размер выходного файла в fp16. Сходится с наблюдаемым: ранг 32 -> ~37 МБ."""
    return round(trainable_params(rank, train_text_encoder=train_text_encoder)
                 * 2 / 1e6, 1)


