def main(argv: list) -> int:
    import argparse

    ap = argparse.ArgumentParser(
        prog="ball_reel.lora",
        description="LoRA личности: план по памяти, расписание, предполёт")
    ap.add_argument("--vram", type=float, default=None,
                    help="гигабайт видеопамяти (по умолчанию спросить у карты)")
    ap.add_argument("--rank", type=int, default=RANK)
    ap.add_argument("--dataset-steps", type=int, default=None,
                    help="steps_equivalent из манифеста набора")
    ap.add_argument("--trainer-dir", default=None)
    ap.add_argument("--headless", action="store_true",
                    help="карта не рисует рабочий стол")
    args = ap.parse_args(argv)

    rep = preflight(trainer_dir=args.trainer_dir, vram_gb=args.vram)
    for c in rep["checks"]:
        mark = {None: "ПРОПУСК", True: "PASS", False: "FAIL"}[c["ok"]]
        print(f"{mark:<7} {c['name']:<16} {c['detail']}")
    for n in rep["notes"]:
        print(f"\nЛЕЧЕНИЕ: {n}")

    cfg = config(rep.get("vram_gb") or args.vram, rank=args.rank,
                 drives_display=not args.headless)
    print("\n" + cfg.render())

    if args.dataset_steps:
        s = schedule(args.dataset_steps,
                     gradient_checkpointing=cfg.gradient_checkpointing)
        print("\n" + s["note"])
        for n in s["notes"]:
            print(f"  - {n}")

    print("\nЛОВУШКИ ТРЕНЕРА (каждая молчаливая — обучение идёт, толку нет):")
    for name, why in TRAINER_TRAPS:
        print(f"  {name}: {why}")
    return 0 if rep["ok"] else 1


if __name__ == "__main__":
    import sys

    raise SystemExit(main(sys.argv[1:]))
