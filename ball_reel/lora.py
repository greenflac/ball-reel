def preflight(manifest: dict | None = None, *, trainer_dir: str | None = None,
              vram_gb: float | None = None) -> dict:
    """Всё ли на месте ДО обучения. Отказ РАНО и с названным лечением.

    ПОРЯДОК ПРОВЕРОК — ПО СТОИМОСТИ ОТКАЗА, и первая из них не техническая.
    Независимость судьи стоит первой не для красоты: если ArcFace участвовал в
    порождении или отборе, обучение бессмысленно при любом состоянии железа, и
    узнать это надо до того, как человек полчаса ставил bitsandbytes.
    """
    report: dict = {"ok": True, "checks": [], "notes": []}

    def add(name: str, ok, detail: str, cure: str = ""):
        report["checks"].append({"name": name, "ok": ok, "detail": detail,
                                 "cure": cure})
        if ok is False:
            report["ok"] = False
            if cure:
                report["notes"].append(f"{name}: {cure}")

    # 1. ЗАМЫСЕЛ. Дороже всего ошибиться здесь.
    if manifest is None:
        add("независимость", None,
            "манифест не передан — проверить нечем",
            "собрать набор через `dataset`, он кладёт независимость в манифест")
    else:
        ind = manifest.get("independence") or {}
        add("независимость", bool(ind.get("independent")),
            ind.get("note", "в манифесте нет раздела независимости"),
            "развести роли: порождение — шлюз, отбор — facenet/deepface, "
            "суд — ArcFace. Пока круг замкнут, обучать нечего")

    # 2. РАЗМЕР НАБОРА. Порог берётся из `dataset`, а не копией.
    from .dataset import MIN_DATASET

    if manifest is None:
        add("размер набора", None, "манифест не передан", "")
    else:
        size = manifest.get("size", 0)
        add("размер набора", size >= MIN_DATASET,
            f"{size} кадров при нижней границе {MIN_DATASET}",
            f"добрать до {MIN_DATASET}: `dataset.plan` считает, сколько "
            f"генерировать с запасом на отбор")

    # 3. ТРЕНЕР. Обучать нечем — самый дешёвый в лечении отказ, но и самый
    #    обидный, если о нём узнать после часа сборов.
    if trainer_dir is None:
        add("тренер", None, "путь к тренеру не задан",
            f"склонировать: git clone {TRAINER['repo']}")
    else:
        from pathlib import Path

        script = Path(trainer_dir) / TRAINER["script"]
        module = Path(trainer_dir) / "networks" / "lora.py"
        ok = script.is_file() and module.is_file()
        add("тренер", ok,
            f"{TRAINER['name']}: {script}"
            + ("" if ok else " — не найден"),
            f"git clone {TRAINER['repo']} {trainer_dir}")

    # 4. ЖЕЛЕЗО И БИБЛИОТЕКИ.
    got = vram_gb
    try:
        import torch

        cuda = torch.cuda.is_available()
        if cuda and got is None:
            got = torch.cuda.get_device_properties(0).total_memory / 1e9
        # CPU-сборка определяется по `torch.version.cuda`, а не по суффиксу в
        # номере версии: колесо с PyPI суффикса не несёт. Тот же разбор, что в
        # `animate.preflight` — и именно поэтому проверка здесь такая же.
        built = getattr(torch.version, "cuda", None)
        add("torch", cuda,
            f"{torch.__version__}, cuda={cuda}, собран с CUDA {built or 'НЕТ'}"
            + (f", {got:.1f} ГБ" if got else ""),
            "pip uninstall -y torch torchvision && pip install torch "
            "torchvision --index-url https://download.pytorch.org/whl/cu124")
    except ImportError:
        add("torch", False, "не установлен",
            "pip install torch --index-url "
            "https://download.pytorch.org/whl/cu124")

    try:
        import bitsandbytes  # noqa: F401

        add("bitsandbytes", True, f"{OPTIMIZER} доступен")
    except ImportError:
        add("bitsandbytes", False,
            f"не установлен — {OPTIMIZER} не заработает",
            "pip install bitsandbytes. Без него — `--optimizer_type AdamW`: "
            "на LoRA разница по памяти десятки мегабайт, обучение поедет")

    for mod, why in (("accelerate", "им запускается тренер"),
                     ("safetensors", "формат весов на выходе"),
                     ("toml", "тренер читает конфиг набора в TOML")):
        try:
            __import__(mod)
            add(mod, True, why)
        except ImportError:
            add(mod, False, f"не установлен — {why}", f"pip install {mod}")

    # 5. ПАМЯТЬ. Считается последней: до неё уже известно, есть ли карта.
    mem = memory_plan(vram_gb=got)
    add("память", mem.fits, mem.render().splitlines()[0],
        "снимать по `reduction_ladder()` сверху вниз")
    report["memory"] = mem
    report["vram_gb"] = got
    return report


