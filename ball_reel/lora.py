def schedule(steps_equivalent: int, *, target_steps: int = TARGET_STEPS,
             batch_size: int = BATCH_SIZE,
             sec_per_step: float | None = None,
             gradient_checkpointing: bool = True,
             max_repeats: int = 1) -> dict:
    """Размер набора с повторами -> эпохи, шаги, время.

    `steps_equivalent` — это `sum(s.repeats)` по оставленным кадрам, ровно то,
    что кладёт в манифест `dataset.manifest`. Считать его здесь заново значит
    завести второй способ узнать одно и то же.

    ПОЧЕМУ ЭПОХИ ВЫВОДЯТСЯ, А НЕ ЗАДАЮТСЯ. Задать эпохи — значит получить число
    шагов, зависящее от размера набора, то есть менять длительность обучения,
    трогая датасет. Мы задаём бюджет шагов и выводим эпохи; тогда набор можно
    менять, не переставая сравнивать прогоны между собой.

    `max_repeats` — наибольший вес кадра в наборе, то есть `repeats` реального
    якоря. Он нужен, потому что «сколько раз кадр увидят» считается как
    `repeats * epochs`, а не как `epochs`: якорь с весом 5 при 36 эпохах будет
    показан 180 раз, и именно он переобучается первым. Считая по эпохам, эту
    границу не увидишь никогда — а перейдена она будет раньше всех.

    Время выводится из `sec_per_step`. По умолчанию оно ВЫБРАНО и НЕПРОВЕРЕНО —
    подставьте измеренное, тренер печатает его сам после полусотни шагов.
    """
    per_epoch = max(1, steps_equivalent // max(1, batch_size))
    epochs = max(1, round(target_steps / per_epoch))
    steps = per_epoch * epochs

    guessed = sec_per_step is None
    if guessed:
        sec_per_step = SEC_PER_STEP_GUESS
        if gradient_checkpointing:
            sec_per_step *= CHECKPOINT_SLOWDOWN
    minutes = round(steps * sec_per_step / 60 + SETUP_MINUTES, 1)

    # Показов у САМОГО ТЯЖЁЛОГО кадра, а не у среднего. Переобучение начинается
    # с него, и мерить надо его.
    views = epochs * max(1, max_repeats)
    notes = []
    if steps < STEPS_MIN:
        notes.append(f"шагов {steps} — меньше {STEPS_MIN}: персонаж не успеет "
                     f"выучиться. Поднять повторы или бюджет шагов")
    if steps > STEPS_MAX:
        notes.append(f"шагов {steps} — больше {STEPS_MAX}: на наборе такого "
                     f"размера это уже запоминание кадров, а не человека")
    if views > MAX_VIEWS_PER_IMAGE:
        notes.append(f"самый тяжёлый кадр (вес {max_repeats}) показывается "
                     f"{views} раз за {epochs} эпох. Выше "
                     f"{MAX_VIEWS_PER_IMAGE} набор перестаёт быть набором: это "
                     f"один кадр, показанный много раз, — то же переобучение на "
                     f"один ракурс, от которого сторожит `dataset.MIN_DATASET`, "
                     f"только с другой стороны. Лечится не шагами, а размером "
                     f"набора")
    if guessed:
        notes.append(f"время ОЦЕНОЧНОЕ и НЕПРОВЕРЕНО: взято "
                     f"{sec_per_step:.2f} с/шаг. Тренер печатает it/s сам — "
                     f"после 50 шагов подставить сюда измеренное")
    return {
        "steps_per_epoch": per_epoch,
        "epochs": epochs,
        "steps": steps,
        "sec_per_step": round(sec_per_step, 3),
        "sec_per_step_measured": not guessed,
        "views_of_heaviest": views,
        "minutes": minutes,
        "save_every_n_epochs": SAVE_EVERY_N_EPOCHS,
        "checkpoints": max(1, epochs // SAVE_EVERY_N_EPOCHS),
        "notes": notes,
        "note": (f"{steps} шагов = {per_epoch} на эпоху x {epochs} эпох; "
                 f"~{minutes} мин"
                 + ("" if not guessed else " (ОЦЕНКА, НЕПРОВЕРЕНО)")),
    }


