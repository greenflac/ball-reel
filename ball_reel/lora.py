@dataclass
class TrainConfig:
    """Режим обучения, посчитанный ДО запуска тренера."""

    rank: int
    alpha: int
    learning_rate: float
    text_encoder_lr: float
    optimizer: str
    resolution: int
    batch_size: int
    max_train_steps: int
    gradient_checkpointing: bool
    cache_latents: bool
    train_text_encoder: bool
    mixed_precision: str = "fp16"
    save_precision: str = "fp16"
    lr_scheduler: str = LR_SCHEDULER
    lr_warmup_steps: int = LR_WARMUP_STEPS
    clip_skip: int = CLIP_SKIP
    seed: int = 0
    memory: Memory | None = None
    notes: list = field(default_factory=list)

    def render(self) -> str:
        size = lora_file_mb(self.rank,
                            train_text_encoder=self.train_text_encoder)
        ck = "да" if self.gradient_checkpointing else "нет"
        lines = [
            f"ранг {self.rank} / alpha {self.alpha} (масштаб "
            f"{self.alpha / self.rank:.2f}), файл на выходе ~{size} МБ",
            f"lr {self.learning_rate:g} (U-Net) / "
            + (f"{self.text_encoder_lr:g} (текст)" if self.train_text_encoder
               else "текстовый энкодер НЕ обучается"),
            f"{self.resolution}x{self.resolution}, батч {self.batch_size}, "
            f"{self.max_train_steps} шагов, {self.optimizer}, "
            f"{self.mixed_precision}",
            f"чекпоинты градиентов: {ck}, "
            f"кэш латентов: {'да' if self.cache_latents else 'нет'}",
        ]
        if self.memory is not None:
            lines.append(self.memory.render())
        return "\n".join(lines + [f"  - {n}" for n in self.notes])


def config(vram_gb: float | None = None, *, rank: int = RANK,
           steps: int = TARGET_STEPS, drives_display: bool = True) -> TrainConfig:
    """Гигабайты видеопамяти -> режим обучения. Чистая функция, без весов.

    Лестница из `reduction_ladder` не советуется в примечании, а ПРИМЕНЯЕТСЯ:
    режим спускается по ней ровно до первой ступени, на которой расчёт сходится.
    Совет, который надо исполнять руками, исполняется не всегда и не так.

    Ранг режется до `MAX_RANK` по ПЕРЕОБУЧЕНИЮ, а не по памяти: памяти на 6 ГБ
    хватает и на 128, и в этом весь фокус — ограничение здесь не то, которое
    ожидаешь, и потому его легко поставить не туда.
    """
    notes = []
    if rank > MAX_RANK:
        notes.append(f"ранг {rank} срезан до {MAX_RANK}: ограничение по "
                     f"ПЕРЕОБУЧЕНИЮ на наборе в несколько десятков кадров, "
                     f"а не по памяти — памяти хватило бы и на больший")
        rank = MAX_RANK

    # Alpha всегда следует за рангом: масштаб поправки alpha/rank остаётся 1.0,
    # то есть тем, из которого взята скорость обучения. Разъехавшись, эти два
    # числа молча меняют эффективную скорость — см. TRAINER_TRAPS.
    alpha = rank

    steps = max(STEPS_MIN, min(STEPS_MAX, steps))

    # Ступени лестницы, сверху вниз. Кэш латентов включён с самого начала: он
    # бесплатен именно у нас, потому что аугментации запечены в файлы.
    ladder = [
        dict(gradient_checkpointing=False, train_text_encoder=True,
             resolution=BASE_TRAIN_RESOLUTION),
        dict(gradient_checkpointing=True, train_text_encoder=True,
             resolution=BASE_TRAIN_RESOLUTION),
        dict(gradient_checkpointing=True, train_text_encoder=False,
             resolution=BASE_TRAIN_RESOLUTION),
    ]
    for res in RESOLUTION_LADDER[1:]:
        ladder.append(dict(gradient_checkpointing=True,
                           train_text_encoder=False, resolution=res))

    chosen, mem = ladder[-1], None
    for step in ladder:
        mem = memory_plan(rank=rank, batch_size=BATCH_SIZE, cache_latents=True,
                          optimizer_8bit=True, vram_gb=vram_gb,
                          drives_display=drives_display, **step)
        # «Влезает» и «влезает с запасом» — разные утверждения, и брать первое
        # за второе здесь нельзя: половина слагаемых расчёта помечена
        # НЕПРОВЕРЕНО. Запас — это место для ошибки собственной оценки.
        if mem.fits is not False and mem.roomy is not False:
            chosen = step
            break
        if mem.fits is not False:
            ck = "да" if step["gradient_checkpointing"] else "нет"
            notes.append(
                f"ступень «чекпоинты {ck}, {step['resolution']}» формально "
                f"влезает (остаток {mem.headroom_gb} ГБ), но запас меньше "
                f"{MIN_HEADROOM_GB} ГБ — при оценённых активациях это не запас. "
                f"Спускаемся ниже")
    else:
        notes.append("не сошлось даже на нижней ступени лестницы: расчёт "
                     "говорит, что этой карте обучение не по силам. Проверить "
                     "`drives_display` — headless-режим возвращает "
                     f"{DISPLAY_RESERVE_GB} ГБ")

    if not chosen["train_text_encoder"]:
        notes.append("текстовый энкодер снят ради памяти: слово-триггер будет "
                     "держаться слабее, и это надо проверить `accept`, а не "
                     "предполагать")
    if chosen["resolution"] < BASE_TRAIN_RESOLUTION:
        notes.append(f"разрешение опущено до {chosen['resolution']}: база "
                     f"обучена на {BASE_TRAIN_RESOLUTION}, и ниже мы учим её на "
                     f"том, чего она не видела. Последняя ступень не зря "
                     f"последняя")

    return TrainConfig(
        rank=rank, alpha=alpha, learning_rate=LEARNING_RATE,
        text_encoder_lr=TEXT_ENCODER_LR, optimizer=OPTIMIZER,
        resolution=chosen["resolution"], batch_size=BATCH_SIZE,
        max_train_steps=steps,
        gradient_checkpointing=chosen["gradient_checkpointing"],
        cache_latents=True,
        train_text_encoder=chosen["train_text_encoder"],
        memory=mem, notes=notes)


