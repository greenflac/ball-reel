@dataclass
class Memory:
    """Разбор памяти по потребителям. Три исхода, а не два."""

    fits: bool | None                 # None = не смогли сказать
    total_gb: float
    vram_gb: float | None
    parts: dict = field(default_factory=dict)
    measured: dict = field(default_factory=dict)
    estimated: dict = field(default_factory=dict)
    notes: list = field(default_factory=list)

    @property
    def headroom_gb(self) -> float | None:
        if self.vram_gb is None:
            return None
        return round(self.vram_gb - self.total_gb, 2)

    @property
    def roomy(self) -> bool | None:
        """Влезает ли С ЗАПАСОМ — это ДРУГОЕ утверждение, чем «влезает».

        Разделены они потому, что половина слагаемых расчёта помечена
        НЕПРОВЕРЕНО. «Влезает впритык» на оценённых числах означает «влезет,
        если мы угадали активации точно», а угадывать точно мы не умеем.
        """
        if self.headroom_gb is None:
            return None
        return self.headroom_gb >= MIN_HEADROOM_GB

    def render(self) -> str:
        head = {True: "ВЛЕЗАЕТ", False: "НЕ ВЛЕЗАЕТ",
                None: "НЕ СМОГЛИ СКАЗАТЬ"}[self.fits]
        if self.fits and self.roomy is False:
            head = (f"ВЛЕЗАЕТ ВПРИТЫК (запас меньше {MIN_HEADROOM_GB} ГБ, а "
                    f"половина расчёта — оценки)")
        lines = [f"{head}: нужно ~{self.total_gb} ГБ"
                 + (f" из {self.vram_gb} ГБ, запас {self.headroom_gb} ГБ"
                    if self.vram_gb is not None else ", объём карты не задан")]
        lines.append("  РАСЧЁТ (по числу параметров, воспроизводится офлайн):")
        for k, v in self.measured.items():
            lines.append(f"    {k:<28} {v:>6.3f} ГБ")
        lines.append("  ОЦЕНКА (НЕПРОВЕРЕНО на карте):")
        for k, v in self.estimated.items():
            lines.append(f"    {k:<28} {v:>6.3f} ГБ")
        return "\n".join(lines + [f"  - {n}" for n in self.notes])


def memory_plan(*, rank: int = RANK, resolution: int = BASE_TRAIN_RESOLUTION,
                batch_size: int = BATCH_SIZE,
                gradient_checkpointing: bool = True,
                train_text_encoder: bool = True,
                cache_latents: bool = True,
                optimizer_8bit: bool = True,
                vram_gb: float | None = None,
                drives_display: bool = True) -> Memory:
    """Влезет ли обучение — посчитано ДО запуска, как `animate.plan`.

    Отделяет ПОСЧИТАННОЕ от ОЦЕНЁННОГО и печатает это разными списками. Смысл
    разделения тот же, что в `animate.plan`: приёмы экономии бьют по разным
    потребителям, и знать заранее, какой из них велик, полезнее, чем узнать это
    отказом по памяти через минуту после начала загрузки.

    Третий исход — `fits is None` — не украшение: не зная объёма карты, сказать
    «влезет» нельзя, а сказать «не влезет» тем более. Это ровно то же правило,
    по которому гейт отличает «не смогли измерить» от «плохо».
    """
    measured: dict = {}
    estimated: dict = {}
    notes: list = []

    measured["unet fp16"] = round(UNET_PARAMS * 2 / 1e9, 3)
    measured["text_encoder fp16"] = round(TEXT_ENCODER_PARAMS * 2 / 1e9, 3)
    if cache_latents:
        notes.append("латенты кэшируются: VAE уходит с карты после кэширования "
                     "и в пике не участвует. Нам это ничего не стоит — "
                     "аугментации у нас уже запечены в файлы "
                     "(`dataset.augmentations`), а тренер отключает только СВОИ")
    else:
        measured["vae fp16"] = round(_vae_gb(), 3)

    n = trainable_params(rank, train_text_encoder=train_text_encoder)
    opt_bytes = BYTES_OPTIMIZER_8BIT if optimizer_8bit else BYTES_OPTIMIZER_32BIT
    measured["обучаемое + оптимизатор"] = round(
        n * (BYTES_MASTER + BYTES_GRAD + opt_bytes) / 1e9, 3)

    act = (ACTIVATION_GB_AT_512
           * (resolution * resolution) / (BASE_TRAIN_RESOLUTION ** 2)
           * batch_size)
    if not gradient_checkpointing:
        act *= NO_CHECKPOINT_FACTOR
    estimated["активации"] = round(act, 3)
    estimated["контекст CUDA"] = CUDA_CONTEXT_GB
    if drives_display:
        estimated["рабочий стол"] = DISPLAY_RESERVE_GB
    estimated["запас на фрагментацию"] = SAFETY_MARGIN_GB

    total = round(sum(measured.values()) + sum(estimated.values()), 2)

    # ГЛАВНЫЙ ВЫВОД РАСЧЁТА, и он неочевиден до того, как посчитаешь.
    share = measured["обучаемое + оптимизатор"] / total if total else 0.0
    if share < 0.1:
        notes.append(
            f"ранг {rank} стоит {measured['обучаемое + оптимизатор']} ГБ — "
            f"{share:.0%} от общего. РАНГ ЗДЕСЬ НЕ РЕШАЕТ: решают разрешение и "
            f"градиентные чекпоинты. Значит ранг выбирается ёмкостью против "
            f"переобучения, а не памятью, и выбирается через `accept`")
    if not gradient_checkpointing:
        notes.append("градиентные чекпоинты выключены: активации дороже в "
                     f"{NO_CHECKPOINT_FACTOR} раза. Это первое, что включают")
    if train_text_encoder:
        notes.append("текстовый энкодер обучается: снять его "
                     "(`--network_train_unet_only`) дешевле, чем ронять "
                     "разрешение, но триггер станет держаться слабее")

    if vram_gb is None:
        notes.append("объём карты не задан — вердикт по памяти НЕ ВЫНЕСЕН. "
                     "Спросить у карты: torch.cuda.get_device_properties(0)")
        fits = None
    else:
        fits = total <= vram_gb
        if not fits:
            notes.append(f"не хватает {round(total - vram_gb, 2)} ГБ. Порядок "
                         f"снятия — в `reduction_ladder()`, сверху вниз")

    notes.append("ОЦЕНКИ выше НЕПРОВЕРЕНЫ на карте. Первый живой прогон "
                 "заменяет их замером: `animate.peak_memory()`")
    return Memory(fits=fits, total_gb=total, vram_gb=vram_gb,
                  parts={**measured, **estimated},
                  measured=measured, estimated=estimated, notes=notes)


def reduction_ladder() -> list:
    """Что снимать первым, если не влезло. Порядок — по цене, а не по привычке.

    Наверху то, что не стоит ничего или стоит только времени; внизу то, что
    портит результат. Разрешение ниже базовых 512 стоит последним намеренно:
    оно бьёт по тому самому лицу, ради которого всё затевается, и вдобавок
    уводит обучение с распределения, на котором училась база.
    """
    return [
        ("cache_latents", "бесплатно",
         "VAE уходит с карты после кэширования. Тренер при этом отключает свои "
         "аугментации — нам всё равно, наши запечены в файлы"),
        ("gradient_checkpointing", f"~{int((CHECKPOINT_SLOWDOWN - 1) * 100)}% "
         f"времени",
         f"блоки пересчитываются вместо хранения: активации дешевле в "
         f"{NO_CHECKPOINT_FACTOR} раза. Лучшая сделка в списке"),
        ("optimizer AdamW8bit", "почти бесплатно",
         "состояние оптимизатора вчетверо меньше. На LoRA это десятки мегабайт, "
         "а не гигабайты: параметров мало. Берём как штатный, не как спасение"),
        ("network_train_unet_only", "триггер держится слабее",
         "текстовый энкодер не обучается: минус его градиенты и минус часть "
         "обучаемых параметров"),
        ("resolution 448", "лицо мельче",
         "активации падают как квадрат стороны: 448 против 512 — это -23%"),
        ("resolution 384", "лицо ещё мельче, и это уже видно",
         "-44% активаций. Ниже 384 обучать SD1.5 бессмысленно: база не видела "
         "такого распределения"),
    ]


