def check_caption(caption: str | None, *, subject_names=()) -> dict:
    """Не называет ли подпись ПОСТОЯННОЕ. Три исхода, и третий обязателен.

    Возвращает `verdict` — одно из `CAPTION_OK`, `CAPTION_NAMES_CONSTANT`,
    `CAPTION_UNCHECKED`, — и, когда поймано, САМО СЛОВО и категорию. Слово
    важнее вердикта: «подпись плохая» нечинимо, «поймано `blonde`» чинимо.

    Булева поля здесь НЕТ намеренно. Флаг `ok` рядом с трёхзначным вердиктом
    схлопнул бы «не смогли проверить» либо в «годна», либо в «плохая», и
    схлопнул бы молча — тот же дефект, от которого в `select` заведён отдельный
    список `unscored`.

    «Не смогли проверить» — это подпись пустая (проверять нечего) или подпись,
    в которой есть буквы не латиницы и не кириллицы: словарь двуязычный, и на
    третьем языке он пропускает всё подряд не потому, что там чисто.

    `subject_names` — имена субъекта; их знает только вызывающий. Если триггером
    сделали настоящее имя человека, поймается и оно — это не ложное срабатывание,
    а ровно та ошибка, ради которой триггер и берут бессмысленным.
    """
    import re

    text = caption or ""
    for category, pattern in FORBIDDEN:
        m = re.search(pattern, text, re.IGNORECASE)
        if m:
            return {"verdict": CAPTION_NAMES_CONSTANT, "word": m.group(0),
                    "category": category,
                    "note": (f"подпись называет ПОСТОЯННОЕ ({category}): "
                             f"{m.group(0)!r}. Названное в каждой подписи "
                             f"уводится от триггера — то есть именно этот "
                             f"признак к триггеру НЕ прилипнет.")}
    for name in subject_names:
        if not name:
            continue
        m = re.search(r"\b" + re.escape(name) + r"\b", text, re.IGNORECASE)
        if m:
            return {"verdict": CAPTION_NAMES_CONSTANT, "word": m.group(0),
                    "category": SUBJECT_NAME,
                    "note": (f"подпись называет субъекта по имени "
                             f"({m.group(0)!r}): личность растечётся по имени "
                             f"вместо триггера.")}
    if not text.strip():
        return {"verdict": CAPTION_UNCHECKED, "word": None, "category": None,
                "note": "подписи нет — проверять нечего. Это не «годна»."}
    if not _one_of_two_alphabets(text):
        return {"verdict": CAPTION_UNCHECKED, "word": None, "category": None,
                "note": ("в подписи есть буквы не латиницы и не кириллицы, а "
                         "словарь двуязычный: на третьем письме он пропускает "
                         "всё подряд, и это не значит, что там чисто.")}
    return {"verdict": CAPTION_OK, "word": None, "category": None,
            "note": "постоянных признаков не названо"}


def _one_of_two_alphabets(text: str) -> bool:
    """Все ли буквы текста — латиница или кириллица. Только stdlib."""
    import unicodedata

    for ch in text:
        if not ch.isalpha():
            continue
        try:
            name = unicodedata.name(ch)
        except ValueError:
            return False
        if not (name.startswith("LATIN ") or name.startswith("CYRILLIC ")):
            return False
    return True


def framing_from_points(points: dict | None, *,
                        min_visibility: float | None = None) -> dict:
    """Кадрировка ПО СКЕЛЕТУ: что от человека реально попало в кадр.

    Принимает `{сустав: (x, y, видимость)}` в нормированных координатах кадра —
    то, что возвращают и `pose.landmarks`, и `skeleton.pose_points`.

    ТРИ СОСТОЯНИЯ У КАЖДОГО СУСТАВА, и на них всё держится. MediaPipe
    экстраполирует сустав ЗА границы кадра, и это ИЗМЕРЕНО: на `kit/face.jpg`
    (кадр обрезан по колени) лодыжки вышли в y = 1.051 и 1.020, то есть детектор
    прямо сказал «их тут нет». Поэтому:

        за кадром     x или y вне [0, 1] — сустав вне снимка;
        виден         внутри кадра и видимость >= порога;
        не наблюдаем  внутри кадра, но видимость ниже порога.

    Третье состояние не сливается ни с первым, ни со вторым, и вот чем это
    ИЗМЕРЕНО. `kit/face.jpg`, обрезанный ещё на 10% (аугментация `crop_tight`),
    даёт лодыжки внутри кадра (y = 0.877 и 0.850) с видимостью 0.152 и 0.146 —
    по одной геометрии это «полный рост», чего в кадре нет. А кадр 0067 из
    `kit/driving` даёт лодыжки внутри кадра (y = 0.645 и 0.582) с видимостью
    0.274 и 0.237 — там они есть, но заслонены. Различить эти два случая по
    имеющимся числам НЕЛЬЗЯ, поэтому оба дают «не смогли определить». Соврать в
    любую сторону дороже, чем промолчать: подпись «полный рост» на обрезанном
    кадре учит модель, что обрезанный кадр — это полный рост.

    Кадр БЕЗ СКЕЛЕТА — тоже «не смогли определить», а НЕ «портрет». ИЗМЕРЕНО:
    `kit/driving/0000.jpg`, обрезанный до верхних 40% и 30%, не дал скелета
    вовсе; назвав такой кадр головой с плечами, мы бы подписали догадку.
    """
    if min_visibility is None:
        min_visibility = pose.MIN_VISIBILITY
    if not points:
        return {"framing": None, "why": "скелета нет", "states": {},
                "note": ("скелет не найден: кадрировка НЕ ИЗМЕРЕНА. Это не "
                         "«голова с плечами» — крупный портрет и пустой кадр "
                         "выглядят отсюда одинаково.")}
    states: dict = {}
    for name, joints in FRAMING_CLASSES:
        state = []
        for j in joints:
            p = points.get(j)
            if p is None:
                state.append("нет точки")
            elif not (0.0 <= p[0] <= 1.0 and 0.0 <= p[1] <= 1.0):
                state.append("за кадром")
            elif p[-1] >= min_visibility:
                state.append("виден")
            else:
                state.append("не наблюдаем")
        states[name] = dict(zip(joints, state))
        if "виден" in state:
            return {"framing": name, "why": "измерено", "states": states,
                    "note": (f"{name}: {joints[state.index('виден')]} в кадре "
                             f"и наблюдаем")}
        if "не наблюдаем" in state or "нет точки" in state:
            return {"framing": None, "why": "не смогли определить",
                    "states": states,
                    "note": (f"{name}: сустав внутри кадра, но не наблюдаем "
                             f"(заслонён или додуман) — сказать, целиком ли "
                             f"человек в кадре, нечем")}
    return {"framing": None, "why": "не смогли определить", "states": states,
            "note": "ни один опорный сустав не попал в кадр"}


def turn_from_points(points: dict | None, world: dict | None, *,
                     size: tuple | None = None) -> dict:
    """Поворот корпуса числом — и почему это число НЕ идёт в подпись.

    Считается так: ширина плеч В КАДРЕ, делённая на длину торса в кадре, к тому
    же отношению В МЕТРИЧЕСКОМ 3D (`pose.world_landmarks`). Проекция укорачивает
    плечи при повороте, 3D — нет, поэтому частное есть косинус разворота и от
    роста, телосложения и масштаба не зависит.

    ЧТО ИЗМЕРЕНО. На 71 кадре `kit/driving` (человек всё время лицом в камеру)
    число разошлось от 0.904 до 1.221 при медиане 1.021. Значения ВЫШЕ единицы
    физически невозможны — косинус не бывает больше 1, — то есть разброс ±0.16
    это шум оценщика на ОДНОМ неподвижном ракурсе. `kit/face.jpg` (человек
    отвернулся, взгляд через плечо) дал 0.152.

    ЧТО ИЗ ЭТОГО СЛЕДУЕТ, и это здесь главное. «Анфас» и «вполоборота» отличаются
    множителем cos 45° = 0.707. Полоса шума на заведомо фронтальном субъекте —
    0.904..1.221, шириной 0.32; отделить внутри неё 1.0 от 0.71 надёжно НЕЛЬЗЯ, а
    измеренного полуоборота у нас нет вовсе — только фронт и почти спина. Порог
    между анфасом и полуоборотом был бы ВЫБРАН без единого замера в той области,
    где он проводится.

    Поэтому ракурс НЕ ПОДПИСЫВАЕТСЯ. Число возвращается и попадает в
    свидетельство — чтобы следующая сессия, получив кадры с настоящим
    полуоборотом, провела границу по замеру, а не по этому тексту.

    Цена молчания та же, что у места: неназванный переменный фактор липнет к
    триггеру. Здесь она меньше, чем у места, ровно потому, что при съёмке по
    нашему же плану ракурс варьируется вокруг фронта, а не систематически.
    """
    import math

    if not points or not world:
        return {"turn": None, "why": "не измерено",
                "note": "нет 2D или 3D точек — поворот не с чем сравнить"}
    w, h = (size or (1.0, 1.0))
    need2 = ("l_shoulder", "r_shoulder", "l_hip", "r_hip")
    if any(points.get(n) is None or world.get(n) is None for n in need2):
        return {"turn": None, "why": "не измерено",
                "note": "не хватает плеч или таза"}
    if any(points[n][-1] < pose.MIN_VISIBILITY for n in need2):
        return {"turn": None, "why": "не измерено",
                "note": "плечи или таз не наблюдаемы"}

    def mid2(a, b):
        return ((points[a][0] + points[b][0]) / 2 * w,
                (points[a][1] + points[b][1]) / 2 * h)

    sho = math.dist((points["l_shoulder"][0] * w, points["l_shoulder"][1] * h),
                    (points["r_shoulder"][0] * w, points["r_shoulder"][1] * h))
    torso = math.dist(mid2("l_shoulder", "r_shoulder"), mid2("l_hip", "r_hip"))

    def mid3(a, b):
        return tuple((world[a][i] + world[b][i]) / 2 for i in range(3))

    sho3 = math.dist(world["l_shoulder"][:3], world["r_shoulder"][:3])
    torso3 = math.dist(mid3("l_shoulder", "r_shoulder"), mid3("l_hip", "r_hip"))
    if torso <= 1e-9 or torso3 <= 1e-9 or sho3 <= 1e-9:
        return {"turn": None, "why": "не измерено",
                "note": "торс вырожден — делить не на что"}
    ratio = (sho / torso) / (sho3 / torso3)
    return {"turn": round(ratio, 4), "why": "измерено",
            "note": ("поворот измерен, но В ПОДПИСЬ НЕ ИДЁТ: шум на заведомо "
                     "фронтальном субъекте 0.904..1.221, а анфас от полуоборота "
                     "отличает 0.707 — граница легла бы внутрь шума")}


def light_classes(brightness: float | None,
                  warm_ratio: float | None) -> dict:
    """Яркость и цветовая температура кадра -> два слова подписи, или None.

    Считается по ВСЕМУ кадру, и это осознанная плата. Тёмный фон под ярким
    ключевым светом даст «dim»: слово описывает СНИМОК, а не осветительную схему.
    Для подписи это правильнее — текстовый энкодер тоже видит весь кадр, а не
    схему света; но называть это «светом на человеке» было бы неверно.
    """
    light = None
    if brightness is not None:
        if brightness <= LIGHT_DIM_MAX:
            light = "dim"
        elif brightness >= LIGHT_BRIGHT_MIN:
            light = "bright"
        else:
            light = "even"
    tone = None
    if warm_ratio is not None:
        if warm_ratio >= WARM_MIN:
            tone = "warm"
        elif warm_ratio <= COOL_MAX:
            tone = "cool"
        else:
            tone = "neutral"
    return {"light": light, "tone": tone}


def pixel_light(path) -> dict | None:
    """Яркость и R/B прямо по пикселям. None — файл не прочитался.

    Яркость — среднее Rec.601 (0.299R + 0.587G + 0.114B), нормированное в 0..1.
    Температура — отношение средних каналов R/B: у нейтральной сцены оно около
    единицы по определению.
    """
    try:
        import numpy as np
        from PIL import Image

        with Image.open(path) as im:
            a = np.asarray(im.convert("RGB"), dtype="float64")
    except Exception:  # noqa: BLE001
        return None
    if a.size == 0:
        return None
    r, g, b = a[..., 0].mean(), a[..., 1].mean(), a[..., 2].mean()
    lum = (0.299 * r + 0.587 * g + 0.114 * b) / 255.0
    return {"brightness": round(float(lum), 4),
            "warm_ratio": (round(float(r / b), 4) if b > 1e-9 else None),
            "size": (int(a.shape[1]), int(a.shape[0]))}


def measure_frame(path) -> dict:
    """ВСЁ, что измеримо на одном кадре. Ни одного слова из запроса.

    Единственное место модуля, которое читает файлы и запускает модели; всё
    остальное — арифметика над тем, что здесь получилось, и потому проверяемо
    без весов и без картинок.

    Не падает на нечитаемом кадре и на кадре без человека: каждая ось
    возвращается отдельно и отдельно же умеет сказать «не измерено».
    """
    out: dict = {"path": str(path)}
    px = pixel_light(path)
    out["brightness"] = px["brightness"] if px else None
    out["warm_ratio"] = px["warm_ratio"] if px else None
    size = px["size"] if px else None
    try:
        pts = pose.landmarks(path)
    except Exception as exc:  # noqa: BLE001
        pts, out["skeleton_error"] = None, str(exc)
    try:
        world = pose.world_landmarks(path) if pts else None
    except Exception:  # noqa: BLE001
        world = None
    # Ключи разводятся по осям намеренно. Слив их в общие `why`/`note`, мы
    # получили бы отчёт, в котором объяснение от ОДНОЙ оси стоит рядом с
    # вердиктом ДРУГОЙ, — и читалось бы это как объяснение вердикта. Поймано
    # на живом прогоне: причиной неизмеренной кадрировки печаталось примечание
    # про ракурс, потому что оно записалось поверх.
    framing = framing_from_points(pts)
    for axis, got in (("framing", framing),
                      ("turn", turn_from_points(pts, world, size=size))):
        out[axis] = got[axis]
        out[f"{axis}_why"] = got["why"]
        out[f"{axis}_note"] = got["note"]
    out["framing_states"] = framing["states"]
    out.update(light_classes(out["brightness"], out["warm_ratio"]))
    return out


def caption_from_measure(measured: dict, *, trigger: str,
                         subject_names=()) -> dict:
    """Замер -> подпись. Ни одна ось не берётся из того, что мы просили.

    В подпись идут ровно три вещи, и каждая измерена на самом кадре: кадрировка
    (по скелету), яркость и цветовая температура (по пикселям). Ракурс измерен,
    но не назван — см. `turn_from_points`.

    МЕСТО (`place`) НЕ НАЗЫВАЕТСЯ ВОВСЕ, и цена этого должна быть сказана вслух:
    неназванный переменный фактор ЛИПНЕТ К ТРИГГЕРУ. Фон в наборе меняется
    (спортзал, серая стена, комната, парк), подпись о нём молчит, значит часть
    «фоновости» модель припишет самому триггеру — и потом при генерации триггер
    будет тянуть за собой обобщённый фон обучающего набора. Это честная цена, а
    не недоделка: назвать место мы можем только со слов ЗАПРОСА, а запрос про
    фон — как раз то, что генератор игнорирует особенно охотно. Соврав про фон,
    мы уведём от триггера тот фон, которого не было, и оставим прилипать тот,
    который был; молчание хотя бы не переворачивает знак. Закрыть это должна
    отдельная семантическая ось по CLIP — она меряет КАДР, а не запрос, и потому
    имеет право говорить о фоне.

    Ось, которую не измерили, В ПОДПИСЬ НЕ ПОПАДАЕТ и перечисляется в
    `unmeasured`. Если не измерилось НИЧЕГО, `caption` равен None: подпись из
    одного триггера — это «всё в кадре есть постоянное», то есть худшая из
    возможных подписей, и молча писать её в .txt рядом с кадром нельзя.
    """
    parts, axes, unmeasured = [], {}, []
    for axis, key, words in (("framing", "framing", FRAMING_WORDS),
                             ("light", "light", LIGHT_WORDS),
                             ("tone", "tone", TONE_WORDS)):
        value = measured.get(key)
        axes[axis] = value
        if value is None:
            unmeasured.append(axis)
        else:
            parts.append(words[value])
    caption = ", ".join([trigger, *parts]) if parts else None
    check = check_caption(caption, subject_names=subject_names)
    note = (f"измерено {len(parts)} из 3 осей"
            + (f"; НЕ ИЗМЕРЕНО: {', '.join(unmeasured)}" if unmeasured else "")
            + ("; подписать нечем — ни одна ось не измерена, кадру место в "
               "отчёте, а не в наборе" if caption is None else ""))
    return {"caption": caption, "trigger": trigger, "axes": axes,
            "unmeasured": unmeasured, "check": check,
            "turn": measured.get("turn"), "note": note}


def caption_from_frame(path, *, trigger: str, subject_names=(),
                       measure=None) -> dict:
    """Подпись одного кадра, снятая с самого кадра.

    Работает одинаково для порождённого кадра, для аугментации и для реального
    фото-якоря — потому что не спрашивает, откуда кадр взялся. Этим и закрываются
    две отдельные дыры: у аугментации `crop_tight` подпись раньше оставалась от
    исходного кадра и была неверна ПО ПОСТРОЕНИЮ (а таких кадров восемь на каждое
    реальное фото), а у реального якоря с весом `REAL_ANCHOR_REPEATS` подписи не
    было вовсе, потому что у него нет `row`.
    """
    m = (measure or measure_frame)(path)
    got = caption_from_measure(m, trigger=trigger, subject_names=subject_names)
    got["measured"] = m
    return got


def caption_samples(samples: list, *, trigger: str, subject_names=(),
                    measure=None) -> dict:
    """Подписать НАБОР замером и сказать, скольким кадрам подписи не досталось.

    Три исхода на кадр, и они не сводятся к двум: подпись полная, подпись
    частичная (часть осей не измерилась — кадр годен, но переменного в нём
    названо меньше) и подписи нет вовсе.
    """
    full, partial, failed, flagged = [], [], [], []
    for s in samples:
        got = caption_from_frame(s.path, trigger=trigger,
                                 subject_names=subject_names, measure=measure)
        s.caption = got["caption"] or ""
        if got["check"]["verdict"] == CAPTION_NAMES_CONSTANT:
            flagged.append((s.path, got["check"]["word"]))
        if got["caption"] is None:
            failed.append(s.path)
        elif got["unmeasured"]:
            partial.append(s.path)
        else:
            full.append(s.path)
        s.note = "; ".join(x for x in (s.note, got["note"]) if x)
    return {
        "full": full, "partial": partial, "failed": failed, "flagged": flagged,
        "note": (f"подписано замером {len(full)} полностью, {len(partial)} "
                 f"частично, {len(failed)} НЕ ПОДПИСАНО"
                 + (f"; {len(flagged)} подпис(ей) называют постоянное — это "
                    f"дефект словаря, а не кадра" if flagged else "")),
    }


@dataclass
class Sample:
    """Один кадр набора вместе с его происхождением.

    Происхождение хранится не для порядка: набор смешанный, и вопрос «сколько
    здесь реального» — первый, который задаст любой, кто будет разбираться,
    почему LoRA выучила именно это.
    """

    path: str
    origin: str                      # "real" | "augmented" | "generated"
    prompt: str = ""
    #: ЧТО ПОПРОСИЛИ (`caption_for`). Хранится отдельно от `caption` намеренно:
    #: пока это было одним полем, запрос и кадр невозможно было сопоставить, а
    #: сопоставить их — единственный способ увидеть, что генератор игнорирует.
    requested: str = ""
    #: ЧТО ИЗМЕРЕНО на кадре (`caption_from_frame`). Только это идёт в обучение.
    caption: str = ""
    repeats: int = 1
    score: float | None = None       # дистанция независимого распознавателя
    kept: bool | None = None
    note: str = ""


def variations(limit: int | None = None) -> list:
    """Комбинации осей разнообразия. Порядок — по одной оси за раз.

    ПОЧЕМУ НЕ ДЕКАРТОВО ПРОИЗВЕДЕНИЕ. Оно даёт 256 комбинаций, из которых
    большинство различается мелочью, а стоит каждая одинаково. Меняя по одной
    оси от базового набора, получаем максимум РАЗЛИЧИЯ на кадр — а именно
    различие и покупается генерацией.
    """
    keys = list(VARIATIONS)
    base = {k: VARIATIONS[k][0] for k in keys}
    out = [dict(base)]
    for k in keys:
        for value in VARIATIONS[k][1:]:
            row = dict(base)
            row[k] = value
            out.append(row)
    return out[:limit] if limit else out


def prompt_for(row: dict, subject: str = "a woman") -> str:
    """Комбинация осей -> текст запроса. Личность НЕ описывается словами."""
    return (f"{subject}, {row['framing']}, {row['angle']}, "
            f"{row['light']}, {row['place']}, photographic, natural skin "
            f"texture, sharp focus on the face")


def caption_for(row: dict, trigger: str) -> str:
    """ЧТО ПОПРОСИЛИ, а не что вышло. В обучение эта строка идти НЕ ДОЛЖНА.

    Функция осталась и осталась под прежним именем, но роль у неё теперь другая
    и ровно одна: запись ЗАПРОСА, которую кладут рядом с записью ЗАМЕРА, чтобы
    расхождение между ними было видно. Именно как обучающая подпись она была
    дефектом — строится из того же `row`, что и промт, то есть описывает
    намерение; а на этом проекте ИЗМЕРЕНО, что генератор часть запроса
    игнорирует. Подпись, описавшая непроисшедшее, уводит от триггера то, чего в
    кадре нет, и оставляет прилипать то, что есть, — знак замысла меняется на
    противоположный.

    Обучающую подпись пишет `caption_from_frame`: она снимается с кадра.

    Проверку `check_caption` эта строка обязана проходить на ВСЕХ комбинациях
    `variations()` — иначе мы запретили то, что сами же порождаем; на это есть
    тест.
    """
    return (f"{trigger}, {row['framing']}, {row['angle']}, "
            f"{row['light']}, {row['place']}")


def augmentations(*, allow_mirror: bool = False) -> list:
    """Преобразования одного реального кадра. Зеркало по умолчанию ЗАПРЕЩЕНО.

    ЗЕРКАЛО — САМАЯ ДОРОГАЯ ОШИБКА В ЭТОЙ ЗАДАЧЕ, и она общепринятая: в
    руководствах по обучению LoRA отражение стоит первым в списке дешёвых
    аугментаций. Для персонажа с ПРИМЕТАМИ оно ядовито: татуировка с левого
    предплечья переезжает на правое, и модель учится, что она бывает и там, и
    там. Ровно то, что наш продукт обязан не допускать — приметы переносятся
    на СВОЁ место, иначе мы не лучше face swap.

    То же касается несимметричных черт: пробора, шрама, родинки.

    Оставлены преобразования, не меняющие сторону: масштаб, сдвиг кадра,
    небольшой поворот, мягкая правка яркости и температуры.
    """
    rows = [
        ("crop_tight", "кадр плотнее на 10% — учит, что человек может быть ближе"),
        ("crop_wide", "кадр шире на 10%"),
        ("rotate_ccw", "поворот на 4 градуса против часовой"),
        ("rotate_cw", "поворот на 4 градуса по часовой"),
        ("bright_up", "ярче на 8% — свет меняется, человек нет"),
        ("bright_down", "темнее на 8%"),
        ("warm", "теплее по цветовой температуре"),
        ("cool", "холоднее по цветовой температуре"),
    ]
    if allow_mirror:
        rows.append(("mirror", "ЗЕРКАЛО: приметы меняют сторону — включать "
                               "только если у субъекта нет несимметричных примет"))
    return rows


def plan(target: int = 20, *, price_per_image: float = 0.035,
         overshoot: float = OVERSHOOT) -> dict:
    """Сколько генерировать и почём, чтобы после отбора осталось `target`.

    Считается ДО траты. Дрейф шлюза измерен (0.345 и 0.367 у лучшей модели при
    баре 0.35), то есть примерно половина кадров отсеется; запас берётся с
    поправкой на это.
    """
    to_generate = int(round(target * overshoot))
    return {
        "target": target,
        "generate": to_generate,
        "augmented_from_real": len(augmentations()),
        "real_anchor_repeats": REAL_ANCHOR_REPEATS,
        "pollen": round(to_generate * price_per_image, 3),
        "note": (f"сгенерировать {to_generate}, чтобы после отбора осталось "
                 f"~{target}; плюс {len(augmentations())} аугментаций и одно "
                 f"реальное фото с весом {REAL_ANCHOR_REPEATS}. "
                 f"Оценка {round(to_generate * price_per_image, 3)} pollen"),
    }


def select(samples: list, *, bar: float, min_kept: int = MIN_DATASET) -> dict:
    """Отбор по НЕЗАВИСИМОМУ распознавателю. Три исхода, а не два.

    `bar` — порог дистанции того распознавателя, которым отбираем. Он ОБЯЗАН
    отличаться от того, которым потом судят обученную LoRA: отобрав по ArcFace,
    мы выберем «то, что нравится ArcFace», и независимость суда потеряем ровно
    там, где собирались её получить.

    Кадр без оценки не отбрасывается молча: «не смогли измерить» — отдельное
    состояние, и оно попадает в отчёт, потому что большая доля неизмеримых
    означает, что отбор вообще не состоялся.
    """
    kept, dropped, unscored = [], [], []
    for s in samples:
        if s.origin == "real":
            s.kept, s.repeats = True, REAL_ANCHOR_REPEATS
            s.note = "реальный якорь: в отбор не входит и не может"
            kept.append(s)
            continue
        if s.score is None:
            s.kept, s.note = None, "НЕ ИЗМЕРЕНО: лицо не найдено или мельче порога"
            unscored.append(s)
            continue
        s.kept = s.score <= bar
        (kept if s.kept else dropped).append(s)
        s.note = (f"дистанция {s.score:.3f} "
                  f"{'<=' if s.kept else '>'} бар {bar}")

    enough = len(kept) >= min_kept
    return {
        "kept": kept, "dropped": dropped, "unscored": unscored,
        "enough": enough,
        "real": sum(1 for s in kept if s.origin == "real"),
        "generated": sum(1 for s in kept if s.origin == "generated"),
        "augmented": sum(1 for s in kept if s.origin == "augmented"),
        "note": (f"оставлено {len(kept)} из {len(samples)} "
                 f"(отсеяно {len(dropped)}, не измерено {len(unscored)})"
                 + ("" if enough else
                    f"; МАЛО: нужно хотя бы {min_kept}, иначе LoRA "
                    f"переобучится на один ракурс")),
    }


def independence_report(*, generator: str, selector: str, judge: str) -> dict:
    """Проверка того, что круг не замкнулся. Главная гарантия этого модуля.

    Утверждение «LoRA даёт личность независимо от ArcFace» проверяемо ровно
    одним способом: посмотреть, не участвует ли судья в порождении или отборе.
    Здесь это делается кодом, а не обещанием в презентации.
    """
    same_family = {"arcface", "buffalo_l", "buffalo_s", "antelopev2",
                   "auraface", "insightface", "ip-adapter-faceid"}

    def fam(name: str) -> bool:
        return any(k in name.lower() for k in same_family)

    problems = []
    if fam(generator) and fam(judge):
        problems.append("судья участвует в ПОРОЖДЕНИИ: обученная модель "
                        "оптимизируется к той же величине, которой её судят")
    if fam(selector) and fam(judge):
        problems.append("судья участвует в ОТБОРЕ: набор выбран по тому, что "
                        "нравится судье, и оценка завышена")
    return {
        "generator": generator, "selector": selector, "judge": judge,
        "independent": not problems,
        "problems": problems,
        "note": ("судья независим от порождения и отбора" if not problems
                 else "; ".join(problems)),
    }


def manifest(samples: list, *, trigger: str, judge: str,
             selector: str, generator: str) -> dict:
    """Полное происхождение набора. То, что кладётся рядом с весами LoRA.

    Без него через неделю невозможно ответить, почему LoRA выучила именно это:
    сколько в наборе было реального, чем отбирали и что судило.

    ПОДПИСИ здесь же, и их состояние — не косметика. Кадр без подписи учит
    модель, что всё в нём постоянно, то есть тянет к триггеру и фон, и свет, и
    кадрировку; такой кадр в наборе хуже, чем отсутствующий, и манифест обязан
    его показать. Рядом с подписью лежит `requested` — то, что ПРОСИЛИ, — чтобы
    расхождение запроса с кадром читалось глазами, а не предполагалось.
    """
    kept = [s for s in samples if s.kept]
    # Пустая подпись попадает в `missing`, а не в `unchecked`: «подписи нет» и
    # «подпись есть, но проверить её нечем» — разные диагнозы и разное лечение.
    checks = [(s.path, check_caption(s.caption)) for s in kept if s.caption]
    return {
        "trigger": trigger,
        "size": len(kept),
        "captions": {
            "measured": sum(1 for s in kept if s.caption),
            "missing": [s.path for s in kept if not s.caption],
            "flagged": [{"path": p, "word": c["word"], "category": c["category"]}
                        for p, c in checks
                        if c["verdict"] == CAPTION_NAMES_CONSTANT],
            "unchecked": [p for p, c in checks
                          if c["verdict"] == CAPTION_UNCHECKED],
        },
        "steps_equivalent": sum(s.repeats for s in kept),
        "by_origin": {o: sum(1 for s in kept if s.origin == o)
                      for o in ("real", "augmented", "generated")},
        "independence": independence_report(generator=generator,
                                            selector=selector, judge=judge),
        "mirror_used": any("mirror" in s.note for s in samples),
        "samples": [{"path": s.path, "origin": s.origin, "repeats": s.repeats,
                     "score": s.score, "caption": s.caption,
                     "requested": s.requested, "note": s.note}
                    for s in kept],
    }
