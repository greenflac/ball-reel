"""Реалистичность вязкой жидкости — числом, а не на глаз.

Без этого модуля LoRA на жидкость неизмерима, и «стало реалистичнее» остаётся
мнением. Это тот же принцип, что и везде здесь: сначала счётчик, потом ручка.

ЧТО ИМЕННО МЕРЯЕТСЯ И ПОЧЕМУ ЭТО, А НЕ «КАЧЕСТВО»

Настоящая вязкая жидкость на коже отличается от нарисованной не «красотой», а
тремя оптическими свойствами, каждое из которых считается арифметикой:

**1. Блики редкие и очень яркие.** Мокрая изогнутая поверхность отражает
источник света почти зеркально: получается несколько крошечных пятен, которые
на порядок ярче остального. Генератор вместо этого обычно кладёт широкий мягкий
глянец — светлее фона, но без экстремумов. Мера: какая доля пикселей попадает в
верхний хвост яркости и насколько этот хвост оторван от медианы.

**2. Блик обесцвечен.** Зеркальное отражение несёт цвет ИСТОЧНИКА, а не
материала, поэтому у настоящего блика насыщенность резко падает — он белый.
Генератор часто оставляет в блике цвет вещества. Мера: насыщенность в верхнем
хвосте яркости против насыщенности области целиком. Это же свойство делает меру
устойчивой к цвету самой жидкости — мы сравниваем её с собой, а не с эталонным
оттенком.

**3. Мелкая деталь на месте.** У настоящей жидкости есть высокочастотная
структура: микроблики, пузырьки, кромка мениска. Сглаженная генерация её теряет.
Мера: энергия лапласиана, нормированная на контраст области, — иначе метрика
меряла бы просто «поярче картинка».

ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ, И ЭТО ВАЖНО

Он **не говорит «реалистично» в отрыве от эталона**. Три числа выше — это
координаты, а не оценка. Чтобы сказать «стало ближе к настоящему», нужен корпус
реальных фотографий жидкости: тогда `realism_shift` меряет, сдвинулась ли
генерация В СТОРОНУ эталона. Без корпуса честно доступно только сравнение двух
генераций между собой, и функция это прямо сообщает, а не выдаёт число за
вердикт.

Калибровка на реальных фото ЕЩЁ НЕ ПРОВЕДЕНА — корпус собирается. Тесты
проверяют, что метрика различает синтетические якоря с заведомо известными
свойствами (редкие резкие блики против широкого мягкого глянца), то есть что
она меряет то, что заявлено. Это не то же самое, что калибровка, и выдавать
одно за другое нельзя.

ПОЧЕМУ У КАЖДОЙ ОСИ СВОЙ ФИКСИРОВАННЫЙ МАСШТАБ, А НЕ ДЕЛЕНИЕ НА ЭТАЛОН

Первая версия нормировала каждую ось на неё саму: `(x - y) / max(|x|, |y|)`.
Это выглядит безобидно и переворачивает вердикт. Три следствия, все замеренные:

* эталон на оси равен нулю — и любое ненулевое значение даёт вклад ровно 1.0.
  Отличие на 0.002 и отличие на 0.40 неразличимы;
* ось знаковая (обесцвечивание бывает отрицательным) — и противоположные знаки
  дают до 4.0. Разница в 0.002 единицы насыщенности стоила больше, чем полное
  отсутствие жидкости на всех четырёх осях сразу;
* вклад оси упирается в потолок: «доля блика больше эталонной втрое» весит
  0.49, «больше в тридцать три раза» — 0.94. Дальше расти нечему.

Замер, ради которого это чинилось: белёсый гель, снятый дважды (источник света
на 0.4% теплее, максимум расхождения по каналу 0.004), давал до эталона 2.0, а
кожа БЕЗ ЖИДКОСТИ ВООБЩЕ — 1.8027. То есть «жидкости нет» объявлялось более
похожим на гель, чем сам этот гель. Ровно наоборот тому, ради чего модуль есть.

Поэтому у каждой оси теперь ШКАЛА — сколько единиц этой оси считается
расхождением в единицу расстояния. Шкала не зависит от сравниваемых значений,
поэтому расстояние монотонно и не имеет потолка, а вклад оси пропорционален
величине отличия, а не его отношению к эталону.

Работает на CPU, ничего не генерирует, в сеть не ходит.
"""

from __future__ import annotations

import math

#: Меньше этого по короткой стороне — судить не о чем. Область 30x40 пикселей
#: (а именно столько занимает кисть на общем плане, замерено на нашем
#: driving-отрезке: плечи 181 px при кадре 720) не содержит статистики, по
#: которой можно отличить резкий блик от мягкого. Отсюда режиссёрское
#: следствие: сцену с жидкостью надо снимать крупным планом, иначе её нечем
#: измерять. Это ограничение физики измерения, а не придирка.
MIN_REGION_PX = 48

#: Насколько пиксель должен быть ярче ТИПИЧНОГО, чтобы считаться бликом —
#: в робастных сигмах (MAD x 1.4826) над медианой.
#:
#: Изначально здесь стояла перцентиль (верхние 5%), и это была ошибка, которую
#: поймал собственный тест. Настоящий зеркальный блик занимает доли процента
#: площади: на синтетическом якоре 54 ярких пикселя из 9216: это 0.6%. Верхние
#: же 5% — 460 пикселей, то есть маска на 88% набиралась ФОНОМ, и «блик»
#: выходил не ярче медианы (1.01x) и не белее вещества (обесцвечивание 0.0).
#: Метрика мерила фон и называла это бликом.
#:
#: Порог по отрыву от типичного адаптируется к тому, насколько блики на самом
#: деле редки, вместо того чтобы навязывать их долю заранее. Четыре сигмы —
#: обычная граница выброса, а не подобранное под якорь число.
HIGHLIGHT_SIGMAS = 4.0

#: Размер окна вокруг кисти в долях плечевой ширины. Привязка к телу, а не к
#: пикселям, делает окно одинаковым при разной дистанции до камеры.
HAND_BOX_SHOULDERS = 0.45

#: Квант 8-битного кадра, 1/255. Ниже него измерения нет: там шум округления
#: JPEG, а не свойство жидкости. Служит полом сразу в трёх местах, где иначе
#: получается деление на ноль или на почти ноль: медиана в отрыве хвоста,
#: контраст в мелкой детали и вырождение робастного масштаба.
#: ИЗМЕРЕН — это разрешающая способность формата, а не выбранное число.
LUMA_QUANTUM = 1.0 / 255.0

#: Доля размаха, начиная с которой пиксель считается бликом в АВАРИЙНОЙ ветке —
#: когда MAD выродился (область почти однотонная и робастного масштаба нет).
#:
#: Прежняя формулировка считала отсечку как med + сигмы * ((max - med) / сигмы),
#: то есть арифметически ровно max, и округление плавающей точки решало, попадут
#: самые яркие пиксели в маску или нет. Замерено на зеркальном якоре: при общем
#: множителе 0.99 блик исчезал ЦЕЛИКОМ (доля 0.0, отрыв 1.0x), при 0.98 и 0.999
#: — нет. Ножевой край, дающий «жидкости нет» на картинке с бликами.
#: ВЫБРАН: середина размаха. На почти однотонной области всё, что выше
#: середины между типичным и максимумом, — выброс по построению, и запас до
#: края в половину размаха снимает зависимость от округления.
FLAT_SPAN_FRACTION = 0.5

#: ШКАЛЫ ОСЕЙ. Каждая отвечает на один вопрос: какое расхождение по этой оси
#: считать расхождением в единицу расстояния. Расстояние — евклидова норма по
#: осям, поделённым на свои шкалы.

#: Доля площади под бликом. ИЗМЕРЕН на семействе синтетических якорей: у
#: зеркального (редкие крошечные пятна) доля пробегает 0.00065 (одно пятно 1x1)
#: .. 0.0788 (пятна радиусом 5), типично 0.006; у широкого мягкого глянца —
#: 0.055 .. 0.074 при любой силе. Разрыв между «редкие пятна» и «широкое пятно»
#: приходится примерно на 0.05, поэтому единица шкалы = 5% площади: ровно
#: переход через тот разрыв, ради различения которого ось введена.
HIGHLIGHT_SHARE_SCALE = 0.05

#: Во сколько раз хвост ярче медианы. По построению не меньше 1.0. ИЗМЕРЕН:
#: на якорях 1.0 (бликов нет) .. 2.75 (зеркальный); мягкий глянец 1.29 .. 2.17.
#: ВЫБРАН из этого диапазона как 1.0 — «хвост ярче медианы ещё на одну
#: медиану». Это тот самый отрыв «в разы», которым настоящий блик отличается от
#: глянца «на проценты»; круглое число внутри измеренного размаха.
HIGHLIGHT_RATIO_SCALE = 1.0

#: Обесцвечивание блика, в единицах насыщенности (сама насыщенность 0..1).
#: ИЗМЕРЕН: на якорях 0.0 (глянец сохраняет цвет вещества) .. 0.44 (белый блик
#: на тёплом геле). ВЫБРАН как 0.25 — чуть больше половины измеренного размаха
#: и ровно четверть физически возможной шкалы насыщенности. Ось знаковая, и
#: шкала намеренно НЕ мельче: у белёсого геля обесцвечивать нечего, значения
#: болтаются около нуля с обоими знаками, и мелкая шкала превращала бы шум
#: съёмки в расхождение.
HIGHLIGHT_DESAT_SCALE = 0.25

#: Энергия лапласиана на контраст. ИЗМЕРЕН: на якорях 0.0033 (сглаженный
#: глянец, детали нет) .. 0.35 (шестнадцать микробликов), типичный зеркальный
#: 0.21. ВЫБРАН как 0.25 — размах между «детали нет» и «детали столько же,
#: сколько у зеркального якоря».
DETAIL_SCALE = 0.25


def _luma(rgb):
    """Яркость по Rec. 601. Отдельно, чтобы не тянуть цветовые библиотеки."""
    return (0.299 * rgb[..., 0] + 0.587 * rgb[..., 1] + 0.114 * rgb[..., 2])


def _saturation(rgb):
    """Насыщенность как (max-min)/max по каналам, 0..1."""
    import numpy as np

    hi = rgb.max(axis=-1)
    lo = rgb.min(axis=-1)
    return np.where(hi > 1e-6, (hi - lo) / np.maximum(hi, 1e-6), 0.0)


def _detail(lum) -> float:
    """Энергия лапласиана на контраст. Ядро 4-соседей, без scipy.

    Контраст в знаменателе полом на квант: у однотонной области std равен нулю,
    и без пола «детали» получалось 0/1e-6 — число, зависящее от подобранной
    заглушки, а не от картинки. С полом однотонная область честно даёт 0.0.
    """
    import numpy as np

    lap = (lum[:-2, 1:-1] + lum[2:, 1:-1] + lum[1:-1, :-2] + lum[1:-1, 2:]
           - 4.0 * lum[1:-1, 1:-1])
    spread = max(float(lum.std()), LUMA_QUANTUM)
    return float(np.abs(lap).mean()) / spread


def _clean(value: float, places: int) -> float:
    """Округлить и убрать минус-ноль: «-0.0» в отчёте читается как ошибка."""
    return round(float(value), places) + 0.0


def fluid_stats(region) -> dict | None:
    """Три оптические координаты области. None, если судить не о чем.

    None — это ОТДЕЛЬНЫЙ исход «не смогли измерить», а не «плохо» и не ноль.
    Он возвращается, когда область меньше `MIN_REGION_PX` по короткой стороне,
    когда это не картинка HxWx3, когда среза для лапласиана не набирается
    (меньше трёх пикселей по стороне) и когда во входе есть NaN или
    бесконечность. Последнее особенно важно: раньше проверка «значения больше
    единицы» на NaN давала False, приведение к 0..1 не срабатывало, и NaN
    доезжал до поля `detail` и дальше в вердикт.

    `region` — массив HxWx3 в 0..1 (или 0..255, приводится). Возвращает:

    * ``highlight_share`` — доля пикселей в верхнем хвосте яркости;
    * ``highlight_ratio`` — во сколько раз хвост ярче медианы. Настоящий блик
      отрывается от фона в разы, мягкий глянец — на проценты;
    * ``highlight_desaturation`` — насколько блик белее области. Зеркальное
      отражение несёт цвет источника, поэтому у настоящего число заметно
      положительное;
    * ``detail`` — энергия лапласиана, нормированная на контраст.

    Все значения гарантированно конечны: если бы что-то вышло NaN, функция
    отдаёт None, а не число.
    """
    import numpy as np

    a = np.asarray(region, dtype=np.float64)
    if a.ndim != 3 or a.shape[2] < 3:
        return None
    if min(a.shape[0], a.shape[1]) < MIN_REGION_PX:
        return None
    # Проверка не дублирует порог выше, а держится сама: порог — настраиваемая
    # величина, а трёхпиксельный срез — требование самого оператора. Без этой
    # строки сдвинутый порог даёт mean() по пустому срезу, то есть NaN.
    if min(a.shape[0], a.shape[1]) < 3:
        return None
    a = a[..., :3]
    if not bool(np.isfinite(a).all()):
        return None
    if a.max() > 1.0:
        a = a / 255.0
    a = np.clip(a, 0.0, 1.0)

    lum = _luma(a)
    sat = _saturation(a)
    med = float(np.median(lum))
    span = float(lum.max()) - med
    # Робастный масштаб: MAD не уводится теми самыми выбросами, которые мы
    # ищем, в отличие от стандартного отклонения.
    scale = float(np.median(np.abs(lum - med))) * 1.4826
    if scale >= LUMA_QUANTUM:
        cut = med + HIGHLIGHT_SIGMAS * scale
    else:
        # Область почти однотонная, MAD выродился: сигм тут нет. Бликом
        # считаем то, что попало в верхнюю долю размаха. Отсечка берётся от
        # размаха НАПРЯМУЮ, а не через умножение-деление на сигмы, — именно
        # там сидел ножевой край, выбрасывавший самые яркие пиксели.
        cut = med + FLAT_SPAN_FRACTION * span
    # Второе условие обязательно: на однотонной заливке span равен нулю,
    # отсечка совпадает с медианой, и «бликом» стал бы весь кадр.
    mask = (lum >= cut) & (lum > med + LUMA_QUANTUM)

    pixels = int(a.shape[0] * a.shape[1])
    if not mask.any():
        # Бликов нет вовсе — это факт о картинке, а не повод делить на ноль.
        out = {"highlight_share": 0.0, "highlight_ratio": 1.0,
               "highlight_desaturation": 0.0,
               "detail": _clean(_detail(lum), 4), "pixels": pixels}
    else:
        out = {
            "highlight_share": _clean(mask.mean(), 5),
            # Пол на квант: у почти чёрной области медиана равна нулю, и отрыв
            # хвоста улетал в 1000000.0 — число, которое потом задавит все оси.
            "highlight_ratio": _clean(
                float(lum[mask].mean()) / max(med, LUMA_QUANTUM), 4),
            "highlight_desaturation": _clean(
                float(sat.mean()) - float(sat[mask].mean()), 4),
            "detail": _clean(_detail(lum), 4),
            "pixels": pixels,
        }
    if not all(math.isfinite(v) for v in out.values()):
        return None
    return out


def hand_region(image_path: str, points: dict, *, side: str = "l"):
    """Вырезать окно вокруг кисти. None, если кисть не видна или мала.

    Окно строится от плечевой ширины, а не от абсолютных пикселей: так оно
    ловит одну и ту же часть тела независимо от того, насколько далеко камера.
    """
    import numpy as np
    from PIL import Image

    wrist = points.get(f"{side}_wrist")
    ls, rs = points.get("l_shoulder"), points.get("r_shoulder")
    if not (wrist and ls and rs) or wrist[2] < 0.5:
        return None
    w, h, _ = points.get("__size__", (0.0, 0.0, 1.0))
    if not w or not h:
        return None
    shoulder = abs(ls[0] - rs[0]) * w
    box = shoulder * HAND_BOX_SHOULDERS
    if box < MIN_REGION_PX:
        return None
    cx, cy = wrist[0] * w, wrist[1] * h
    x0, y0 = int(max(0, cx - box / 2)), int(max(0, cy - box / 2))
    x1, y1 = int(min(w, cx + box / 2)), int(min(h, cy + box / 2))
    with Image.open(image_path) as im:
        crop = im.convert("RGB").crop((x0, y0, x1, y1))
    return np.asarray(crop, dtype=np.uint8)


def _is_number(v) -> bool:
    """Число и только число: bool сюда не считается, NaN и inf тоже."""
    return (isinstance(v, (int, float)) and not isinstance(v, bool)
            and math.isfinite(v))


def _distance(a, b) -> float | None:
    """Расстояние между наборами координат. None, если сравнить не удалось.

    Каждая ось делится на СВОЮ ШКАЛУ (см. `*_SCALE` выше), а не на сравниваемые
    значения. Это и есть починка главного дефекта: деление на эталон делало
    вклад безразмерным и потому бессмысленным — при нулевом эталоне любое
    отличие весило ровно 1.0, при смене знака до 4.0, а сверху всё упиралось в
    потолок. Со шкалами вклад растёт пропорционально величине отличия, без
    потолка и без разрывов, поэтому расстояние монотонно на всём диапазоне.

    Неполные координаты дают None, а не малое число. Раньше набор без общих
    осей давал 0.0, то есть «идентичны», и неизмеримый результат молча
    становился лучшим из возможных. «Не смогли измерить» и «совпало» — разные
    ответы, и склеивать их дороже всего.
    """
    scales = {"highlight_share": HIGHLIGHT_SHARE_SCALE,
              "highlight_ratio": HIGHLIGHT_RATIO_SCALE,
              "highlight_desaturation": HIGHLIGHT_DESAT_SCALE,
              "detail": DETAIL_SCALE}
    if not isinstance(a, dict) or not isinstance(b, dict):
        return None
    total = 0.0
    for k, scale in scales.items():
        x, y = a.get(k), b.get(k)
        if not (_is_number(x) and _is_number(y)):
            return None
        if not (_is_number(scale) and scale > 0.0):
            return None
        total += ((x - y) / scale) ** 2
    if not math.isfinite(total):
        return None
    return round(total ** 0.5, 4)


def realism_shift(before: dict, after: dict,
                  reference: dict | None = None) -> dict:
    """Сдвинулась ли генерация В СТОРОНУ эталона.

    Без `reference` честно отказывается выносить вердикт и отдаёт только
    расстояние между двумя генерациями. Это не заглушка: сказать «стало
    реалистичнее», не имея образца реального, нельзя в принципе — можно сказать
    только «стало иначе». Разница между этими утверждениями и есть то, за чем
    написан весь этот проект.

    Поле ``state`` называет исход и отличает три разных ответа, которые раньше
    сливались в два:

    * ``"measured"`` — вердикт есть, ``verdict`` булев;
    * ``"no_reference"`` — эталона нет, вердикт невозможен в принципе;
    * ``"not_measured"`` — область, эталон или координаты не сняты. Раньше
      такой вход давал расстояние 0.0 и объявлялся УЛУЧШЕНИЕМ: замерено
      «до эталона было 1.8451, стало 0.0 — ближе к настоящему» на пустом
      словаре. Неизмеримое обязано быть отличимо и от «хорошо», и от «плохо».
    """
    unmeasured = (f"нечего сравнивать: одна из областей не измерена "
                  f"(меньше {MIN_REGION_PX}px по короткой стороне — "
                  f"снимать крупнее; либо координаты неполны/не числа)")
    if not before or not after:
        return {"verdict": None, "state": "not_measured", "closer": None,
                "note": unmeasured}
    changed = _distance(before, after)
    if changed is None:
        return {"verdict": None, "state": "not_measured", "closer": None,
                "note": unmeasured}
    if reference is None:
        return {"verdict": None, "state": "no_reference", "closer": None,
                "changed": changed,
                "note": (f"изменение {changed}, но БЕЗ ЭТАЛОНА это не оценка "
                         f"реализма: видно только что стало иначе, а не что "
                         f"стало ближе к настоящему. Нужен корпус реальных "
                         f"фотографий жидкости.")}
    d_before = _distance(before, reference)
    d_after = _distance(after, reference)
    if d_before is None or d_after is None:
        return {"verdict": None, "state": "not_measured", "closer": None,
                "changed": changed,
                "note": "эталон не измерен или его координаты неполны: "
                        "сравнивать не с чем, вердикта нет"}
    closer = d_after < d_before
    # «Не сдвинулось» — не улучшение, поэтому вердикт остаётся ложью; но и не
    # «ДАЛЬШЕ», и писать так в отчёте значит врать о направлении.
    where = ("ближе к настоящему" if closer
             else ("НЕ СДВИНУЛОСЬ" if d_after == d_before
                   else "ДАЛЬШЕ от настоящего"))
    return {
        "verdict": bool(closer), "state": "measured", "closer": closer,
        "changed": changed,
        "distance_before": d_before, "distance_after": d_after,
        "note": (f"до эталона было {d_before}, стало {d_after} — "
                 f"{where} (изменение {changed})"),
    }
