"""Верность мимики: повторило ли лицо в результате лицо driving-кадра.

`PRODUCT.md` обещает, что движение берётся с референса. Мимика — часть движения:
человек на видео открывает рот, поднимает брови, щурится, и если в результате
он этого не делает, обещание нарушено ровно так же, как если бы он не прыгнул.
`driving.py` уже снимает с референса 52 ARKit-коэффициента (`_blendshapes`), но
до сих пор НИКТО их не сравнивал с результатом. То есть мимика заявлена,
извлечена — и не проверена.

Здесь только СЧЁТЧИК. Канала впрыска мимики в проекте нет, и этот модуль его не
добавляет: сначала измеритель, потом ручка — тот же порядок, что в `marks.py`,
и по той же причине.

ПОЧЕМУ НЕЛЬЗЯ ПРОСТО СРАВНИТЬ 52 ЧИСЛА

Наивная метрика «средний модуль разности по всем 52 коэффициентам» меряет не то,
что кажется. Замерено на `kit/driving` (71 кадр реальной съёмки, 720x1278):

  * 5 коэффициентов из 52 равны НУЛЮ во всех кадрах (`_neutral`, cheekSquint L/R,
    noseSneer L/R), ещё 21 имеет полный размах меньше 0.02 за весь клип;
  * кадр с самым открытым ртом и кадр с самым закрытым отличаются по `jawOpen`
    на 0.387 — а в среднем по 52 коэффициентам всего на 0.0911.

То есть заведомо РАЗНЫЕ выражения одного и того же человека дают «расхождение
0.09 из 1.0», которое любой читатель примет за совпадение. Мёртвые коэффициенты
не нейтральны — они РАЗБАВЛЯЮТ, и разбавляют в сторону оптимистичного ответа.
Поэтому судим по отобранному набору, а не по всем 52.

ПОЧЕМУ МОРГАНИЕ НЕ УЧАСТВУЕТ

Между соседними кадрами (83 мс при 12 fps) `eyeBlinkRight` на нашем материале
менялся максимум на 0.743 при медианном шаге 0.0033 — размах в 225 раз больше
типичного. Это не мимика, это затвор: два кадра одного и того же выражения
отличаются по моргу сильнее, чем два разных выражения по всему остальному лицу.
Требовать от генерации попадания в фазу моргания — значит штрафовать её за то,
что не является выражением. Для сравнения, `jawOpen`: максимальный шаг 0.167 при
медианном 0.0176 (в 9 раз), `browInnerUp` — 0.238 при 0.0654 (в 4 раза); эти
двигаются НЕПРЕРЫВНО, и по ним судить можно.

По той же причине выброшен взгляд (`eyeLook*`): на нашем клипе он даёт самые
большие размахи из всех (до 0.76 между соседними кадрами) — но это направление
глаз и поворот головы, а не выражение лица. Генерация, поставившая голову на
пару градусов иначе, получила бы штраф за мимику, которую воспроизвела.

ЧЕГО ЭТА МЕТРИКА НЕ УМЕЕТ

  * **Не отделяет лицо в покое от выражения.** У двух разных людей разное
    «нулевое» лицо: посаженные брови, приоткрытый рот. Разница покоя попадёт в
    расхождение и будет записана как непереданная мимика. Разложение на
    постоянную и переменную часть здесь не делается — для него нужен эталонный
    нейтральный кадр того же человека, которого у нас на выходе нет.
  * **Слепа к щекам, носу и взгляду.** Надутые щёки, сморщенный нос, подмигивание
    и направление взгляда не судятся вовсе (см. выше). На реальном материале эти
    коэффициенты не двигались, откалибровать их не на чем, а включать в оценку
    то, что всегда ноль, — это ровно разбавление, от которого мы ушли.
  * **Не проверяет, ТОТ ЖЕ ЛИ ЭТО ЧЕЛОВЕК.** Совпадение коэффициентов — это
    совпадение выражения, и его даст любое лицо. Личность меряет
    `identity_arcface`, и одно другим не подменяется.
  * **Ломается на сильном повороте головы.** Коэффициенты сетки при большом
    ракурсе врут, и метрика этого не видит: она получит числа и посчитает их.
  * **Откалибрована на ОДНОМ клипе одного человека и ни на одной генерации.**
    Полосы ниже измерены на паре «настоящий кадр против настоящего кадра». Что
    показывает генератор — ещё никто не мерил, и пороги ниже придётся
    пересмотреть, когда появится первый прогон.

Работает на CPU, ничего не генерирует, в сеть не ходит.
"""

from __future__ import annotations

from pathlib import Path

from .intake import MIN_MESH_FACE_PX

#: Группы коэффициентов, по которым выносится вердикт, и вес каждой группы.
#:
#: Считается СРЕДНЕЕ ПО ГРУППЕ, а потом взвешенная сумма групп — не среднее по
#: коэффициентам. Иначе брови (пять коэффициентов) автоматически перевесили бы
#: раскрытие рта (два), хотя на видео первым читается именно рот.
#:
#: Веса ВЫБРАНЫ по заметности глазом, а не измерены: измерить «насколько зритель
#: замечает поднятую бровь» нечем, пока нет разметки людьми. Что ИЗМЕРЕНО — это
#: состав групп (см. докстринг модуля) и последнее место глаз: `eyeSquintLeft`
#: на нашем клипе имеет среднее 0.196, а `eyeSquintRight` — 0.058 при
#: симметричном лице. Такая лево-правая асимметрия означает, что прищур сетка
#: читает как минимум наполовину из освещения, и полагаться на него нельзя.
JUDGED_GROUPS: dict[str, tuple[float, tuple[str, ...]]] = {
    "jaw": (0.30, ("jawOpen", "mouthClose")),
    "brow": (0.25, ("browInnerUp", "browOuterUpLeft", "browOuterUpRight",
                    "browDownLeft", "browDownRight")),
    "smile": (0.20, ("mouthSmileLeft", "mouthSmileRight",
                     "mouthFrownLeft", "mouthFrownRight")),
    "mouth": (0.15, ("mouthPucker", "mouthFunnel",
                     "mouthStretchLeft", "mouthStretchRight")),
    "eyes": (0.10, ("eyeSquintLeft", "eyeSquintRight",
                    "eyeWideLeft", "eyeWideRight")),
}

#: Ниже этого размера лица (короткая сторона рамки, px) блендшейпы не читаются
#: вовсе — берём смысл и число у `intake.MIN_MESH_FACE_PX`, потому что это
#: ровно тот же физический факт: сетка из 478 точек не садится на слишком мелкое
#: лицо даже после кропа.
#:
#: ЗДЕСЬ ВАЖНО НЕ ВЗЯТЬ ЧУЖОЙ ПОРОГ. В `driving.py` рядом лежит
#: `MIN_EXPRESSION_FACE_PX = 100` с комментарием «та же причина и тот же масштаб,
#: что у порога личности» (и он там ни разу не применяется). Это заимствование
#: неверно: 100 px существуют потому, что ArcFace пересаживает лицо в 112x112 и
#: на меньшем кропе распознаёт домысленные пиксели. Сетке лица такой кроп не
#: нужен. ИЗМЕРЕНО на `kit/driving`: все 71 лицо имеют 71-92 px (медиана 86),
#: то есть НИ ОДНО не проходит порог в 100 px, — и при этом коэффициенты ведут
#: себя связно (`jawOpen` проходит 0.002 -> 0.389 медианным шагом 0.018).
#: Судить по порогу 100 px значило бы объявить весь реальный материал
#: неизмеримым. Отсюда же продуктовый факт: мимику на таком плане мерить МОЖНО,
#: а личность на нём уже НЕЛЬЗЯ.
MIN_JUDGE_FACE_PX = MIN_MESH_FACE_PX

#: Расхождение, ниже которого кадры считаются показывающими ОДНО выражение.
#:
#: ИЗМЕРЕНА полоса, ВЫБРАНО округление. На `kit/driving` расстояние между
#: соседними кадрами (83 мс, заведомо одно выражение) дало p50 0.0215 и
#: p90 0.0355, а между кадрами, разнесёнными на две и более секунды, — p10
#: 0.0352 и p50 0.0534. Полосы «то же самое» и «другое» СМЫКАЮТСЯ на 0.035.
#: 0.04 — это верхний край измеренной полосы совпадения, округлённый вверх.
#:
#: На настоящей генерации этот порог НЕ проверялся ни разу.
MATCH_MAX = 0.04

#: Во сколько раз кадр должен быть ближе к СВОЕМУ driving-кадру, чем к чужим.
#:
#: Это главная защита от подделки, и без неё метрика обманывается. ИЗМЕРЕНО:
#: неподвижное лицо, замороженное на медианном выражении клипа, даёт расхождение
#: с каждым кадром p50 0.0389 — то есть почти проходит `MATCH_MAX`, ничего при
#: этом не повторив. Расстояние само по себе не отличает «следит за мимикой» от
#: «держит одно усреднённое лицо».
#:
#: Отличает — сравнение со СВОИМ ЖЕ нулевым распределением: расстояние до
#: сопоставленного кадра против расстояния до всех остальных. Замеренные якоря
#: на реальном клипе: точная копия 0.000, отставание на 1 кадр 0.403, на 4 кадра
#: 0.561, вдвое ослабленная мимика 0.450, замороженное лицо 1.000, случайно
#: перемешанные кадры 1.029. Зазор между «следит с задержкой» и «не следит»
#: измерен, 0.75 в его середине — ВЫБРАНО.
FOLLOW_MAX = 0.75

#: Ниже этого разброса нулевого распределения driving-клип сам почти не меняет
#: выражения, и вопрос «следит ли генерация» задавать не о чем: делить придётся
#: на шум. ВЫБРАНО равным измеренному шуму соседних кадров (p50 0.0215).
MIN_NULL_SPREAD = 0.02

#: Сколько сопоставленных кадров нужно, чтобы вердикт что-то значил. ВЫБРАНО
#: тем же числом, каким `driving.validate` считает клип слишком коротким, чтобы
#: описывать движение: мимика не может быть измерима там, где движение уже нет.
MIN_PAIRS = 6

#: Доля кадров, которые обязаны быть измеримы. Та же планка и тот же смысл, что
#: у `identity_arcface.MIN_COVERAGE` и у порога мимики в `driving.validate`:
#: ниже половины вердикт описывает выборку, а не клип.
MIN_COVERAGE = 0.5

#: Сколько чужих кадров максимум берётся на один кадр при построении нулевого
#: распределения. Длинный клип иначе даёт квадратичную работу без выигрыша в
#: точности медианы. Прореживание с постоянным шагом, а не случайное, чтобы
#: число не менялось от прогона к прогону.
NULL_SAMPLE_CAP = 60


def judged_shapes() -> tuple[str, ...]:
    """Все коэффициенты, которые реально участвуют в вердикте."""
    out: list[str] = []
    for _, names in JUDGED_GROUPS.values():
        out.extend(names)
    return tuple(out)


def _quantile(values: list[float], q: float) -> float:
    """Квантиль с линейной интерполяцией. Локальная, чтобы вердикт не тянул
    ни numpy, ни scipy: арифметику, на которой стоит вывод, скептик должен
    уметь пересчитать в уме."""
    if not values:
        return 0.0
    s = sorted(values)
    if len(s) == 1:
        return s[0]
    pos = q * (len(s) - 1)
    lo = int(pos)
    hi = min(lo + 1, len(s) - 1)
    return s[lo] + (s[hi] - s[lo]) * (pos - lo)


def group_errors(a: dict, b: dict) -> dict | None:
    """Расхождение по каждой группе отдельно. None — судить нельзя.

    Отдаётся наружу не ради красоты отчёта: «мимика не доехала» и «не доехали
    именно брови» чинятся в разных местах, и склеивать их в одно число значит
    отправлять чинить наугад.

    None означает, что в одном из словарей нет нужных коэффициентов — например
    туда передали `track`-строку из `driving.py`, где хранится только десяток
    ключевых. Это отсутствие наблюдения, а не расхождение, и подставлять вместо
    отсутствующего коэффициента ноль нельзя: ноль — это осмысленное значение
    («мышца расслаблена»), и подстановка превратила бы дырку в утверждение.
    """
    if not a or not b:
        return None
    out = {}
    for group, (_, names) in JUDGED_GROUPS.items():
        if any(n not in a or n not in b for n in names):
            return None
        out[group] = round(sum(abs(float(a[n]) - float(b[n]))
                               for n in names) / len(names), 5)
    return out


def frame_distance(a: dict, b: dict) -> float | None:
    """Расхождение мимики двух кадров, 0 — одинаковые. None — судить нельзя.

    Взвешенная сумма ошибок по группам, а не по коэффициентам: см. почему в
    `JUDGED_GROUPS`. Модуль разности, а не квадрат, — чтобы один промазанный
    коэффициент не решал за всё лицо; квадратичная мера здесь превращается в
    измеритель самой резкой ошибки, а нам нужно «насколько то же лицо в целом».
    """
    errs = group_errors(a, b)
    if errs is None:
        return None
    return round(sum(JUDGED_GROUPS[g][0] * e for g, e in errs.items()), 5)


def _face_model(face_model: str | Path | None) -> Path:
    import os

    return Path(str(face_model or os.environ.get(
        "BALL_REEL_FACE_MODEL", "~/.mediapipe/face_landmarker.task"))).expanduser()


def read_expression(path: str | Path, *, face_model: str | Path | None = None,
                    min_face_px: int = MIN_JUDGE_FACE_PX) -> dict:
    """Один кадр -> 52 коэффициента и приговор об их пригодности.

    Возвращает `state`, а не только числа, потому что «мимики нет» и «мимику не
    удалось прочитать» — разные утверждения, и второе не должно попадать в
    расчёт под видом нейтрального лица.

    Извлечение делегировано `driving._blendshapes`, а не скопировано: там уже
    лежит кроп вокруг лица перед сеткой, без которого на общем плане мимика
    читается в 0% кадров, и держать вторую копию этой поправки — верный способ
    однажды поправить только одну из них. Цена — детектор лица прогоняется
    дважды на кадр (нам отдельно нужен его размер), и на измерителе это
    приемлемо.
    """
    from .driving import _blendshapes
    from .identity_arcface import face_detail

    path = str(path)
    out = {"path": path, "state": "no_face", "face_px": None,
           "shapes": None, "note": ""}
    model = _face_model(face_model)
    if not model.exists():
        out["state"] = "no_model"
        out["note"] = (f"нет модели сетки лица в {model}: мимика НЕ измерена. "
                       f"Это не «мимики нет» — это отсутствие инструмента.")
        return out

    det = face_detail(path)
    if det is None:
        out["note"] = "лицо не найдено: судить о мимике не о чем"
        return out
    px = int(det["face_px"])
    out["face_px"] = px
    if px < min_face_px:
        out["state"] = "too_small"
        out["note"] = (f"лицо {px}px < {min_face_px}px: сетка на таком лице не "
                       f"садится, коэффициенты были бы выдумкой. Снимать ближе.")
        return out

    shapes = _blendshapes(path, model)
    if not shapes:
        out["state"] = "no_mesh"
        out["note"] = (f"лицо {px}px найдено, но сетка на него не села "
                       f"(поворот, смаз, перекрытие) — мимика НЕ измерена")
        return out
    out["state"] = "measured"
    out["shapes"] = shapes
    return out


def read_clip(paths, *, face_model: str | Path | None = None,
              min_face_px: int = MIN_JUDGE_FACE_PX) -> list:
    """`read_expression` по списку кадров, в том же порядке."""
    return [read_expression(p, face_model=face_model, min_face_px=min_face_px)
            for p in paths]


def _shapes_of(item) -> dict | None:
    """Принять и готовый словарь коэффициентов, и результат `read_expression`."""
    if not item:
        return None
    if isinstance(item, dict) and "state" in item and "shapes" in item:
        return item["shapes"] if item["state"] == "measured" else None
    return item


def expression_match(driving, generated, *, match_max: float = MATCH_MAX,
                     follow_max: float = FOLLOW_MAX,
                     min_pairs: int = MIN_PAIRS,
                     min_coverage: float = MIN_COVERAGE) -> dict:
    """Повторила ли генерация мимику driving-клипа. Чистая арифметика.

    На вход — два СОПОСТАВЛЕННЫХ ПО ИНДЕКСУ списка: элемент i генерации отвечает
    элементу i референса. Сопоставление — забота вызывающего: модуль не знает ни
    частоты кадров, ни смещения, и угадывать их значило бы выдумывать.
    Элементами могут быть словари коэффициентов, результаты `read_expression`
    или None (кадр не измерен).

    ДВА ВОПРОСА, А НЕ ОДИН, и в этом весь смысл:

    * **насколько близко** — медиана расхождения по сопоставленным кадрам;
    * **следит ли вообще** — то же расхождение против расстояния до ЧУЖИХ
      driving-кадров. Клип сам даёт себе нулевую гипотезу: если сопоставленные
      кадры не ближе случайных, генерация мимике не следует, какой бы маленькой
      ни была абсолютная цифра. Именно так ловится замороженное лицо, которое по
      одному расстоянию проходит почти как настоящее (см. `FOLLOW_MAX`).

    Медиана, а не среднее, — по той же причине, по которой `identity_arcface`
    судит по медиане, а не по худшему кадру: один смазанный кадр не должен
    решать за клип. `p90` при этом отдаётся наружу, потому что клип, который
    держит мимику в начале и бросает в конце, живёт ровно в хвосте. Вердикт
    остаётся на медиане: хвост из десятка кадров — это, по арифметике из
    `timing.MIN_TAIL_SAMPLES`, почти целиком один худший замер.

    Исход «не смогли измерить» возвращается ОТДЕЛЬНО от «не похоже»: verdict
    None и `state` с причиной.
    """
    total = max(len(driving), len(generated))
    empty = {"verdict": None, "state": "not_measurable", "pairs": 0,
             "total": total, "coverage": 0.0, "distance_p50": None,
             "distance_p90": None, "follow_ratio": None, "null_p50": None,
             "per_group": {}, "unjudged": 0}
    if len(driving) != len(generated):
        return {**empty, "note": (
            f"списки разной длины ({len(driving)} против {len(generated)}): "
            f"кадры не сопоставлены, и сопоставить их за вызывающего нельзя")}

    drv = [_shapes_of(x) for x in driving]
    gen = [_shapes_of(x) for x in generated]
    matched: list[tuple[int, float]] = []
    groups: dict[str, list[float]] = {g: [] for g in JUDGED_GROUPS}
    unjudged = 0
    for i, (d, g) in enumerate(zip(drv, gen)):
        errs = group_errors(d, g) if (d and g) else None
        if errs is None:
            unjudged += 1
            continue
        for name, val in errs.items():
            groups[name].append(val)
        matched.append((i, sum(JUDGED_GROUPS[k][0] * v for k, v in errs.items())))

    empty["unjudged"] = unjudged
    coverage = round(len(matched) / total, 3) if total else 0.0
    empty["coverage"] = coverage
    empty["pairs"] = len(matched)
    if len(matched) < min_pairs:
        return {**empty, "note": (
            f"измеримо только {len(matched)} кадр(ов) из {total} — нужно "
            f"{min_pairs}. Это НЕ «мимика не совпала», это отсутствие "
            f"измерения: лицо не найдено, слишком мелкое или сетка не села.")}
    if coverage < min_coverage:
        return {**empty, "note": (
            f"измерено {coverage:.0%} кадров при пороге {min_coverage:.0%}: "
            f"вердикт описывал бы выборку, а не клип. Мимика НЕ ИЗМЕРЕНА.")}

    dists = [d for _, d in matched]
    p50 = round(_quantile(dists, 0.5), 5)
    p90 = round(_quantile(dists, 0.9), 5)
    per_group = {g: round(_quantile(v, 0.5), 5) for g, v in groups.items() if v}

    # Нулевая гипотеза: то же расхождение, но с ЧУЖИМИ driving-кадрами.
    have = [i for i in range(total) if drv[i] is not None]
    step = max(1, len(have) // NULL_SAMPLE_CAP)
    others = have[::step]
    null: list[float] = []
    for i, _ in matched:
        for j in others:
            if j == i:
                continue
            v = frame_distance(drv[j], gen[i])
            if v is not None:
                null.append(v)
    null_p50 = round(_quantile(null, 0.5), 5) if null else None

    base = {"pairs": len(matched), "total": total, "coverage": coverage,
            "distance_p50": p50, "distance_p90": p90, "null_p50": null_p50,
            "per_group": per_group, "unjudged": unjudged}
    worst = max(per_group, key=lambda g: per_group[g]) if per_group else None
    tail = (f"расхождение p50 {p50}, p90 {p90} по {len(matched)}/{total} кадрам"
            + (f"; хуже всего {worst} ({per_group[worst]})" if worst else ""))

    if null_p50 is None or null_p50 < MIN_NULL_SPREAD:
        return {**base, "verdict": None, "state": "driving_static",
                "follow_ratio": None,
                "note": (f"driving-клип почти не меняет выражения (нулевой "
                         f"разброс {null_p50} < {MIN_NULL_SPREAD}): проверить, "
                         f"СЛЕДИТ ли генерация за мимикой, нечем — совпасть с "
                         f"неподвижным лицом можно и не следя. Расхождение всё "
                         f"же измерено: {tail}.")}

    follow = round(p50 / null_p50, 3)
    close = p50 <= match_max
    follows = follow <= follow_max
    verdict = bool(close and follows)
    if verdict:
        why = (f"МИМИКА ВОСПРОИЗВЕДЕНА: {tail}; свои кадры ближе чужих в "
               f"{1 / max(follow, 1e-6):.1f} раза (порог {follow_max})")
    elif not follows and close:
        why = (f"МИМИКА НЕ ВОСПРОИЗВЕДЕНА, хотя расхождение мало: свои кадры "
               f"не ближе чужих ({follow} при пороге {follow_max}) — лицо в "
               f"результате не следует за референсом, а держит одно выражение. "
               f"{tail}")
    elif not close and follows:
        why = (f"МИМИКА ВОСПРОИЗВЕДЕНА ЧАСТИЧНО: генерация следует за "
               f"референсом ({follow} при пороге {follow_max}), но не дотягивает "
               f"по величине — {tail} при пороге {match_max}")
    else:
        why = (f"МИМИКА НЕ ВОСПРОИЗВЕДЕНА: {tail} при пороге {match_max}, и свои "
               f"кадры не ближе чужих ({follow} при пороге {follow_max})")
    return {**base, "verdict": verdict, "state": "measured",
            "follow_ratio": follow, "note": why}


def clip_expression(driving_frames, generated_frames, *,
                    face_model: str | Path | None = None,
                    min_face_px: int = MIN_JUDGE_FACE_PX, **kwargs) -> dict:
    """Полный путь: два списка путей к кадрам -> вердикт о мимике.

    Причины непрочитанных кадров пересказываются в `reasons`, потому что низкое
    покрытие лечится по-разному: «лицо мелкое» — снимать крупнее, «сетка не
    села» — другой ракурс, «нет модели» — скачать веса.
    """
    drv = read_clip(driving_frames, face_model=face_model,
                    min_face_px=min_face_px)
    gen = read_clip(generated_frames, face_model=face_model,
                    min_face_px=min_face_px)
    got = expression_match(drv, gen, **kwargs)
    reasons: dict[str, int] = {}
    for side, rows in (("driving", drv), ("generated", gen)):
        for r in rows:
            if r["state"] != "measured":
                reasons[f"{side}:{r['state']}"] = (
                    reasons.get(f"{side}:{r['state']}", 0) + 1)
    got["reasons"] = reasons
    px = [r["face_px"] for r in drv + gen if r["face_px"]]
    got["face_px_p50"] = int(_quantile([float(v) for v in px], 0.5)) if px else None
    return got
