"""Маршрутизатор телосложения: НУЖНА ЛИ ЭТОЙ ФОТОГРАФИИ LoRA ВООБЩЕ.

ЭТО НЕ ИЗМЕРИТЕЛЬ ТЕЛОСЛОЖЕНИЯ, и различие принципиальное. Измерителю нужен
калиброванный порог, а порог выводится из когорты, которой нет и в MVP не
будет. Маршрутизатору когорта не нужна: чтобы решить, включать ли LoRA,
достаточно СОГЛАСИЯ С ЧЕЛОВЕКОМ на горстке примеров.

И он ничего не решает про генерацию: КАК рисуется тело такого типа — дело LoRA
темплейта. Здесь только «включать / не включать / не уверен».

---

ЧТО ИМЕННО ИЗМЕНИЛОСЬ В СМЫСЛЕ, И ПОЧЕМУ ЭТО НЕ ПЕРЕИМЕНОВАНИЕ РАДИ КРАСОТЫ.

~~Прежние корзины «как в драйвинге» и «полная женщина 40+»~~ читались как ДВЕ
LoRA, между которыми маршрутизатор выбирает. Снято ХЭНДОФ §2a: обучается ОДНА
LoRA (полная 40+), а «как в драйвинге» — это ОТСУТСТВИЕ LoRA. Телосложение
драйвинга приходит само: скелет задаёт пропорции, маска задаёт силуэт, модель
рисует человека, который в них укладывается. LoRA нужна только для ОТКЛОНЕНИЯ
от этого.

Поэтому исходы названы по §2 дословно — `LoRA не нужна` / `LoRA полная 40+` /
`не уверен`. Имя корзины попадает в отчёт как есть и не требует расшифровки:
«как в драйвинге» на разборе каждый раз приходилось переводить в «то есть без
LoRA», и один раз это уже прочитали как «вторая LoRA».

---

АСИММЕТРИЯ ЦЕНЫ ОШИБКИ. ГЛАВНОЕ СВОЙСТВО ЭТОГО ФАЙЛА.

Первый исход стал ВЕТВЬЮ ПО УМОЛЧАНИЮ, то есть безопасной (§2): «ошибка скорее
недодаст эффект, чем навяжет чужую фигуру». Две ошибки стоят разного:

| ошибка | что видит человек | цена |
|---|---|---|
| зря НЕ включили LoRA | эффекта меньше, чем могло быть | недоработка, видна и правится повтором |
| зря ВКЛЮЧИЛИ LoRA | ему навязали ЧУЖУЮ ФИГУРУ | брак, и это про его тело |

Симметричная полоса неуверенности вокруг точки раздела молча утверждала бы, что
цены равны. Здесь полоса НЕСИММЕТРИЧНА и склоняется в сторону «LoRA не нужна»:
запас со стороны LoRA широкий, со стороны без-LoRA почти нулевой. Числа и их
происхождение — у самих констант ниже.

Следствие, которое надо назвать вслух, а не обнаружить потом: доля
включений LoRA будет ЗАНИЖЕНА, и это выбранное поведение, а не дефект
маршрутизатора. Проверять его надо не по доле включений, а по `agreement` —
и отдельно смотреть, не уходит ли в «не уверен» слишком многое.

---

ЧТО РЕШЕНО ЧУЖИМ КОДОМ, А НЕ НАМИ. Пропорции берутся из
`pose.world_proportions` — в трёхмерных мировых координатах, нормированные на
длину торса. Ракурс там уже решён, и это не наше достижение: причина записана
в `metrics.py` дословно — проекция не есть тело, поворот схлопывает ширину плеч
к нулю, тогда как бёдра держатся, и отношение переворачивается.

ЧЕГО НЕТ: ТЕЛА НА ПОРТРЕТЕ. Проверено прогоном, а не выведено:
`demo/lora_dataset/img/real_0000.png` возвращает `None`, а `demo/hero.png` даёт
`shoulder_width 0.6448, hip_width 0.4157, shoulder_to_hip 1.5511`
(команда — в `docs/FORK_LORA.md`). Портрет — самый частый случай у
пользовательских фотографий, и он попадает в «не уверен» ПО ПОСТРОЕНИЮ, а не по
недосмотру.

Портрет НЕ падает в безопасную ветвь автоматически, хотя она безопасная.
Асимметрия говорит, куда клониться, КОГДА ИЗМЕРЕНИЕ ЕСТЬ и оно пограничное;
когда измерения нет вовсе, клониться не от чего — это `не смогли`, а не
«пограничная фигура» (Р1). Человек, получив такой исход, скорее всего выберет
без-LoRA сам; но выберет он, и это будет видно.

Существующий `intake._check_build` в такой ситуации откатывается на
`ASSUMED_PROPORTIONS` с пометкой `assumed`. Здесь этот откат НЕ ПОВТОРЯЕТСЯ, и
это осознанно: типовое тело годится, чтобы не отказать человеку в приёме, но
негодно, чтобы ВЫБРАТЬ ЕМУ ВЕТВЬ — выбор по типовому телу это и есть выбор
наугад, только с видом уверенности. Заодно замечено прогоном: типовое
`shoulder_to_hip = 1.49` и само попало бы в «не уверен», так что откат не дал бы
даже решения — только его видимость.

---

НЕПРОВЕРЕНО (Ц4): согласие с человеком не замерялось — размеченной горстки нет.
`agreement` умеет его посчитать, но числа пока не существует. Точка раздела и
обе половины полосы ВЫБРАНЫ, не измерены.
"""

from __future__ import annotations

from pathlib import Path

from .fork_identity import PASS, UNMEASURED

#: Исходы MVP. Названы по ХЭНДОФ §2 дословно, чтобы имя читалось в отчёте без
#: расшифровки. Матрицы «N темплейтов x M фигур» здесь не будет: её стоимость
#: растёт произведением, а двух плеч достаточно, чтобы механизм показал себя
#: или не показал. Разрыв между плечами взят максимальным намеренно — это самый
#: строгий тест механизма, а не самый удобный.
#:
#: ~~BUCKET_DRIVING = "как в драйвинге"~~ — снято §2a, закрыто именем
#: `BUCKET_NO_LORA`: это не фигура, а отсутствие LoRA.
BUCKET_NO_LORA = "LoRA не нужна"        # плечи широкие относительно бёдер:
                                        # скелет и маска уже дают нужную фигуру
BUCKET_LORA_FULL_W40 = "LoRA полная 40+"  # бёдра выраженные, плечи уже:
                                          # нужно ОТКЛОНЕНИЕ, за него и LoRA
UNSURE = "не уверен"
BUCKETS = (BUCKET_NO_LORA, BUCKET_LORA_FULL_W40, UNSURE)

#: Безопасная ветвь. Не «первая в списке» — именно та, ошибка в сторону которой
#: недодаёт эффект вместо того, чтобы навязать чужую фигуру (§2). Вынесена
#: отдельным именем, потому что от неё зависит знак асимметрии ниже, и связь
#: должна быть видна в коде, а не только в комментарии.
SAFE_BUCKET = BUCKET_NO_LORA

#: По какому числу делим. `shoulder_to_hip` — отношение уже нормированных на
#: торс ширин, то есть безразмерное вдвойне и сравнимое между людьми. Ширины по
#: отдельности зависят от того, насколько удачно детектор поймал каждый пояс;
#: их отношение устойчивее, потому что общая ошибка масштаба сокращается.
#:
#: Направление: БОЛЬШЕ отношение — шире плечи относительно бёдер — тем ближе
#: фигура к тому, что скелет с маской дадут сами, и тем меньше нужна LoRA.
KEY = "shoulder_to_hip"

#: Точка раздела. **ВЫБРАНА, не измерена.** Опорные числа, прочитанные из кода
#: и с прогона, а не по памяти: комментарий к `metrics.ASSUMED_PROPORTIONS`
#: держит двух замеренных в 3D людей с `shoulder/hip` 1.58 и 1.48, а
#: `demo/hero.png` даёт 1.5511. Три доступные точки лежат в 1.48..1.58, и
#: 1.53 — их середина.
#:
#: Три точки — это НЕ когорта, и порогом в смысле измерителя это число не
#: является. Оно годится ровно на то, для чего взято: развести два плеча так,
#: чтобы человек чаще соглашался, чем нет.
SPLIT = 1.53

#: Запас со стороны LoRA. **ВЫБРАН 0.10** — ровно наблюдавшийся разброс
#: 1.48..1.58, то есть «включаем LoRA только там, где значение ушло ниже всего,
#: что мы вообще видели». Дорогая ошибка требует, чтобы фигура была заметно
#: полнее раздела, а не чуть-чуть.
#:
#: Побочное следствие, названное вслух: замеренный человек с 1.48 и типовое тело
#: с 1.49 при этом запасе НЕ получают LoRA, а уходят в «не уверен». Это верно:
#: одна точка на границе — не основание менять человеку фигуру.
MARGIN_TO_LORA = 0.10

#: Запас со стороны без-LoRA. **ВЫБРАН 0.01**, на порядок меньше первого.
#: Отношение 10:1 и есть числовая запись асимметрии цены (§2): выше раздела
#: ошибка дешёвая, поэтому страховать её почти нечем — запас оставлен только
#: чтобы точное совпадение со значением раздела не решалось равенством
#: чисел с плавающей точкой.
#:
#: Ноль сюда не поставлен намеренно: «дёшево» не значит «бесплатно», недоданный
#: эффект человек тоже видит.
#:
#: Ни одно из двух чисел не сужается иначе как замером согласия на размеченной
#: горстке. Пока не сужены, маршрутизатор чаще спрашивает человека — лишний
#: вопрос дешевле неверной ветви, а неверная ветвь дороже с одной стороны, чем
#: с другой.
MARGIN_TO_NO_LORA = 0.01

#: Прежняя симметричная полуширина ~~UNSURE_BAND = 0.08~~ снята: она молча
#: утверждала, что обе ошибки стоят одинаково. Закрыта парой запасов выше.


def bounds(*, split: float = SPLIT, margin_to_lora: float = MARGIN_TO_LORA,
           margin_to_no_lora: float = MARGIN_TO_NO_LORA) -> tuple:
    """Края полосы неуверенности: `(low, high)`. Ниже low — LoRA, выше high — нет.

    Отдельной функцией, чтобы отчёт и тест читали края оттуда же, откуда их
    читает решение (Е1), а не пересчитывали второй раз своим сложением.
    """
    return split - margin_to_lora, split + margin_to_no_lora


def route(photo: str | Path | None = None, *, proportions: dict | None = None,
          split: float = SPLIT, margin_to_lora: float = MARGIN_TO_LORA,
          margin_to_no_lora: float = MARGIN_TO_NO_LORA) -> dict:
    """«LoRA не нужна» / «LoRA полная 40+» / «не уверен». Третий обязателен.

    Принимает либо путь к фотографии, либо уже снятые пропорции — второе для
    тестов и для случая, когда пропорции уже посчитаны выше по течению и
    считать их второй раз значит потратить секунды на то же самое.
    """
    if proportions is None:
        if photo is None:
            raise ValueError("нужна либо фотография, либо готовые пропорции")
        from . import pose

        proportions = pose.world_proportions(photo)

    if not proportions:
        return {"bucket": UNSURE, "value": None, "measured": False,
                "note": ("тела на фотографии не видно — скорее всего портрет. "
                         "Это НЕ ветвь по умолчанию: безопасная ветвь говорит, "
                         "куда клониться при ПОГРАНИЧНОМ ИЗМЕРЕНИИ, а здесь "
                         "измерения нет вовсе. Спросить у клиента или выбрать "
                         "руками.")}

    value = proportions.get(KEY)
    if value is None:
        return {"bucket": UNSURE, "value": None, "measured": False,
                "note": (f"в пропорциях нет {KEY}: пояс плеч или таза детектор "
                         f"не поймал. Не смогли — не то же, что «пограничная "
                         f"фигура».")}

    low, high = bounds(split=split, margin_to_lora=margin_to_lora,
                       margin_to_no_lora=margin_to_no_lora)
    if value < low:
        bucket = BUCKET_LORA_FULL_W40
        why = (f"{value} ниже {low:.4f} — ушло ниже всего наблюдавшегося "
               f"разброса, поэтому отклонение оправдано")
    elif value > high:
        bucket = BUCKET_NO_LORA
        why = (f"{value} выше {high:.4f} — скелет и маска дадут такую фигуру "
               f"сами")
    else:
        bucket = UNSURE
        why = (f"{value} внутри полосы [{low:.4f}, {high:.4f}], где у нас нет "
               f"оснований выбирать")
    return {"bucket": bucket, "value": value, "measured": True,
            "split": split, "margin_to_lora": margin_to_lora,
            "margin_to_no_lora": margin_to_no_lora,
            "low": low, "high": high, "safe_bucket": SAFE_BUCKET,
            "note": (f"{KEY} = {value}; {why} -> {bucket}"
                     + ("" if bucket != UNSURE else
                        ". Падает на ручной выбор — это и есть работа третьего "
                        "исхода, а не отказ")
                     + (f". Полоса несимметрична ({margin_to_lora} вниз против "
                        f"{margin_to_no_lora} вверх): ошибочно НЕ включить LoRA "
                        f"недодаёт эффект, ошибочно включить — навязывает "
                        f"человеку чужую фигуру"))}


def agreement(labelled, *, split: float = SPLIT,
              margin_to_lora: float = MARGIN_TO_LORA,
              margin_to_no_lora: float = MARGIN_TO_NO_LORA) -> dict:
    """Согласие с человеком на размеченной горстке. Приёмка маршрутизатора.

    `labelled` — пары `(пропорции_или_путь, исход_по_мнению_человека)`.

    СЧИТАЮТСЯ ТРИ ЧИСЛА, А НЕ ОДНО (Р2, Е3): совпало, разошлось, отдано
    человеку. Третье НЕ ошибка — маршрутизатор для того и сделан, чтобы
    отдавать сомнительное. Но и не успех: маршрутизатор, отдающий человеку
    ВСЁ, согласуется с ним идеально и не делает ничего. Поэтому доля «не
    уверен» печатается рядом и судится отдельно.

    Расхождения печатаются с направлением, а не только числом: при
    несимметричной полосе два направления стоят разного, и `disagreed`
    целиком из дешёвых промахов — другая новость, чем `disagreed` целиком из
    навязанных фигур.
    """
    agreed, disagreed, deferred = [], [], []
    imposed = 0  # разошлись в дорогую сторону: включили LoRA, человек — нет
    for item, human in labelled:
        got = route(**({"proportions": item} if isinstance(item, dict)
                       else {"photo": item}), split=split,
                    margin_to_lora=margin_to_lora,
                    margin_to_no_lora=margin_to_no_lora)
        if got["bucket"] == UNSURE:
            deferred.append((item, human))
        elif got["bucket"] == human:
            agreed.append((item, human))
        else:
            disagreed.append((item, human, got["bucket"]))
            if got["bucket"] == BUCKET_LORA_FULL_W40:
                imposed += 1

    total = len(labelled)
    decided = len(agreed) + len(disagreed)
    return {
        "outcome": UNMEASURED if not total else PASS,
        "total": total, "agreed": len(agreed), "disagreed": len(disagreed),
        "deferred": len(deferred), "imposed_lora": imposed,
        "accuracy_on_decided": (round(len(agreed) / decided, 3)
                                if decided else None),
        "deferral_share": round(len(deferred) / total, 3) if total else None,
        "disagreements": disagreed,
        "note": (f"примеров {total}: совпало {len(agreed)}, разошлось "
                 f"{len(disagreed)} (из них {imposed} с навязанной LoRA — "
                 f"дорогая сторона), отдано человеку {len(deferred)}. "
                 + (f"На решённых точность "
                    f"{len(agreed) / decided:.0%}. " if decided else
                    "Решённых нет — маршрутизатор отдал человеку всё, то есть "
                    "не сделал ничего. ")
                 + "НЕПРОВЕРЕНО: размеченной горстки пока не существует."),
    }

