#
# ЗАЧЕМ ЭТО ЗДЕСЬ, А НЕ В `fork_mask`. Маску РИСУЕТ `fork_mask`, а РЕШАЕТ, какой
# она ширины, тот, кто посмотрел на клиента, — то есть этот модуль. Положить
# решение рядом с рисованием значило бы завести второе место, где живёт знание
# о телосложении, и оно разъехалось бы с первым (Е1).
#
# ЧТО ЭТО ЗА РЫЧАГ. Маска очерчивает силуэт АКТЁРА, и клиент физически не может
# выйти за её границу: плотнее актёра — тесно, и модель начнёт его ужимать.
# Расширение маски снимает потолок. Оно НЕ задаёт телосложение — задают его
# фотография и промпт, — но без него заданное некуда поместить.
#
# ЦЕНА РАСШИРЕНИЯ ЗАМЕРЕНА потоком C на живом кадре и печатается рядом с
# вердиктом: силуэт как есть занимает 65.6% кадра, +32 px — 78.6%, +64 px —
# 89.6%. За +64 идти некуда: вне маски остаётся десятая часть кадра, и ось
# протечки перестаёт что-либо сторожить.

#: Доля кадра под маской для каждого плеча. ИЗМЕРЕНО потоком C на demo/hero.png,
#: командой `fork_mask.sequence` с соответствующим `arm_name`. Числа держатся
#: здесь, чтобы отчёт называл цену выбора, а не только сам выбор.
ARM_OCCUPANCY = {"narrow": 0.656, "wide": 0.786, "wider": 0.896}


def arm_for(value: float | None = None, *, split: float | None = None,
            margin_to_lora: float | None = None,
            margin_to_no_lora: float | None = None) -> dict:
    """Какое плечо маски дать клиенту с таким отношением плеч к бёдрам.

    ТРИ ИСХОДА, и третий не декоративный: если отношение не измерено, плечо НЕ
    ВЫБИРАЕТСЯ. Подставить умолчание значило бы решить за оператора на основании
    отсутствующего измерения — ровно то, против чего у роутера заведён `UNSURE`.

    ГРАНИЦЫ БЕРУТСЯ ИЗ `bounds()`, А НЕ ЗАВОДЯТСЯ ЗАНОВО. Полоса неуверенности
    вокруг `SPLIT` уже посчитана и уже сторожится мутациями; вводить рядом
    вторую пару порогов означало бы два независимых представления об одном и
    том же теле. Соответствие такое:

        выше полосы  — плечи широки относительно бёдер, фигура ближе к тому,
                       что скелет с маской дадут сами  ->  `narrow`
        внутри полосы — там же, где роутер не уверен про LoRA  ->  `wide`
        ниже полосы  — бёдра шире относительно плеч, тесно  ->  `wider`

    **ВЫБРАНО, НЕ ИЗМЕРЕНО, И ЭТО ГЛАВНАЯ ОГОВОРКА.** Полоса `bounds()` выведена
    под вопрос «нужна ли LoRA», а не под вопрос «сколько миллиметров добавить к
    маске». Что это те же самые границы — предположение, удобное тем, что не
    вводит новых чисел. Оно ОБЯЗАНО быть пересчитано после первого прогона на
    карте: берём одного клиента, гоняем на трёх плечах, смотрим, где фигура
    начинает читаться и где начинает уплывать фон.
    """
    # Умолчания разрешаются ЗДЕСЬ, а не в сигнатуре: значение по умолчанию
    # связывается на импорте, и подмена константы модуля до него не доходит
    # (И7, форму уже выгребали в семи местах). `bounds` ждёт числа, а не None.
    lo, hi = bounds(
        split=SPLIT if split is None else split,
        margin_to_lora=MARGIN_TO_LORA if margin_to_lora is None
        else margin_to_lora,
        margin_to_no_lora=MARGIN_TO_NO_LORA if margin_to_no_lora is None
        else margin_to_no_lora)
    if value is None:
        return {"outcome": UNMEASURED, "arm": None, "value": None,
                "bounds": (lo, hi), "occupancy": None,
                "note": ("отношение плеч к бёдрам не измерено — плечо маски НЕ "
                         "выбирается. Умолчание здесь было бы решением за "
                         "оператора по отсутствующему измерению; выбрать "
                         "руками в файле-описании шаблона")}

    if value > hi:
        arm = "narrow"
        why = f"{value:.4f} выше полосы {hi} — фигура близка к актёрской"
    elif value < lo:
        arm = "wider"
        why = f"{value:.4f} ниже полосы {lo} — бёдра шире, силуэта актёра мало"
    else:
        arm = "wide"
        why = (f"{value:.4f} внутри полосы {lo}..{hi} — там же, где роутер не "
               f"уверен про LoRA; запас в один блок как хедж")

    occ = ARM_OCCUPANCY[arm]
    return {
        "outcome": PASS, "arm": arm, "value": round(float(value), 4),
        "bounds": (lo, hi), "occupancy": occ,
        "note": (f"плечо {arm!r}: {why}. Под маской окажется {occ:.1%} кадра, "
                 f"под охраной {1 - occ:.1%}. Границы ВЫБРАНЫ по полосе "
                 f"роутера и подлежат пересчёту после первого прогона"),
    }


def arm_for_photo(photo=None, *, proportions: dict | None = None) -> dict:
    """Плечо маски прямо по фотографии. Обёртка над `route` и `arm_for`.

    Сделана одной функцией нарочно: два вызова подряд в чужом коде — это два
    места, где можно передать РАЗНЫЕ пропорции в маршрутизацию и в выбор
    плеча, и получить корзину от одного человека, а ширину маски от другого.
    """
    routed = route(photo, proportions=proportions)
    got = arm_for(routed.get("value"))
    got["bucket"] = routed["bucket"]
    got["note"] = f"{got['note']}. Корзина: {routed['bucket']}"
    return got
