"""Маршрутизатор телосложения: какой ВАРИАНТ темплейта взять под эту фотографию.

ЭТО НЕ ИЗМЕРИТЕЛЬ ТЕЛОСЛОЖЕНИЯ, и различие принципиальное. Измерителю нужен
калиброванный порог, а порог выводится из когорты, которой нет и в MVP не
будет. Маршрутизатору когорта не нужна: чтобы разложить фотографии по двум
корзинам, достаточно СОГЛАСИЯ С ЧЕЛОВЕКОМ на горстке примеров.

И он ничего не решает про генерацию: КАК рисуется тело такого типа — дело LoRA
темплейта. Здесь только выбор из двух вариантов, плюс третий исход.

---

ТРЕТИЙ ИСХОД — «НЕ УВЕРЕН» — И ОН ГЛАВНЫЙ.

Маршрутизатор не заменяет ручной выбор, а СОКРАЩАЕТ, как часто тот нужен.
Поэтому у него три исхода, и третий не декоративный: он падает на ручной выбор
или на вопрос клиенту. Двухисходный маршрутизатор был бы обязан угадывать на
пограничных фигурах — и угадывал бы молча.

Полоса неуверенности вокруг точки раздела — это ПРЯМОЕ ПРИЗНАНИЕ, что когорты
нет. Была бы когорта — полосу можно было бы сузить замером. Пока её ширина
ВЫБРАНА, и это записано у числа, а не в документе.

---

ЧТО РЕШЕНО ЧУЖИМ КОДОМ, А НЕ НАМИ. Пропорции берутся из
`pose.world_proportions` — в трёхмерных мировых координатах, нормированные на
длину торса. Ракурс там уже решён, и это не наше достижение: причина записана
в `metrics.py` дословно — проекция не есть тело, поворот схлопывает ширину плеч
к нулю, тогда как бёдра держатся, и отношение переворачивается.

ЧЕГО НЕТ: ТЕЛА НА ПОРТРЕТЕ. Проверено прогоном, а не выведено:
`demo/lora_dataset/img/real_0000.png` возвращает `None`, а `demo/hero.png` даёт
`shoulder_width 0.6448, hip_width 0.4157, shoulder_to_hip 1.5511`
(команда — в `docs/FORK_LORA.md`). Портрет — самый частый случай у
пользовательских фотографий, и он попадает в «не уверен» ПО ПОСТРОЕНИЮ, а не по
недосмотру.

Существующий `intake._check_build` в такой ситуации откатывается на
`ASSUMED_PROPORTIONS` с пометкой `assumed`. Здесь этот откат НЕ ПОВТОРЯЕТСЯ, и
это осознанно: типовое тело годится, чтобы не отказать человеку в приёме, но
негодно, чтобы ВЫБРАТЬ ЕМУ КОРЗИНУ — выбор по типовому телу это и есть выбор
наугад, только с видом уверенности.

---

НЕПРОВЕРЕНО (Ц4): согласие с человеком не замерялось — размеченной горстки нет.
`agreement` умеет его посчитать, но числа пока не существует. Точка раздела
ВЫБРАНА, не измерена.
"""

from __future__ import annotations

from pathlib import Path

from .fork_identity import PASS, UNMEASURED

#: Корзины MVP. Две, и матрицы «N темплейтов x M фигур» здесь не будет: её
#: стоимость растёт произведением, а двух плеч достаточно, чтобы механизм
#: показал себя или не показал.
BUCKET_A = "A"          # фигура с выраженными бёдрами: плечи узкие относительно бёдер
BUCKET_B = "B"          # фигура с плечами шире бёдер
UNSURE = "не уверен"
BUCKETS = (BUCKET_A, BUCKET_B, UNSURE)

#: По какому числу делим. `shoulder_to_hip` — отношение уже нормированных на
#: торс ширин, то есть безразмерное вдвойне и сравнимое между людьми. Ширины по
#: отдельности зависят от того, насколько удачно детектор поймал каждый пояс;
#: их отношение устойчивее, потому что общая ошибка масштаба сокращается.
KEY = "shoulder_to_hip"

#: Точка раздела. **ВЫБРАНА, не измерена.** Опорные числа, прочитанные из кода
#: и с прогона, а не по памяти: `metrics.ASSUMED_PROPORTIONS` держит двух
#: замеренных в 3D людей с `shoulder/hip` 1.58 и 1.48, а `demo/hero.png` даёт
#: 1.5511. Три доступные точки лежат в 1.48..1.58, и 1.53 — их середина.
#:
#: Три точки — это НЕ когорта, и порогом в смысле измерителя это число не
#: является. Оно годится ровно на то, для чего взято: развести две корзины так,
#: чтобы человек чаще соглашался, чем нет.
SPLIT = 1.53

#: Полоса неуверенности вокруг точки раздела, в тех же единицах. ВЫБРАНА 0.08 —
#: примерно ширина разброса трёх известных точек (1.48..1.58 это 0.10). То
#: есть полоса накрывает всё, что мы вообще наблюдали, и честно говорит: внутри
#: этого разброса у нас нет оснований выбирать.
#:
#: Сузить её можно только замером согласия на размеченной горстке. Пока не
#: сужена, маршрутизатор чаще спрашивает человека — и это верное поведение для
#: MVP: лишний вопрос дешевле неверной корзины.
UNSURE_BAND = 0.08


def route(photo: str | Path | None = None, *, proportions: dict | None = None,
          split: float = SPLIT, band: float = UNSURE_BAND) -> dict:
    """Корзина A / корзина B / не уверен. Три исхода, третий обязателен.

    Принимает либо путь к фотографии, либо уже снятые пропорции — второе для
    тестов и для случая, когда пропорции уже посчитаны выше по течению и
    считать их второй раз значит потратить секунды на то же самое.
    """
    if proportions is None:
        if photo is None:
            raise ValueError("нужна либо фотография, либо готовые пропорции")
        from . import pose

        proportions = pose.world_proportions(photo)

    if not proportions:
        return {"bucket": UNSURE, "value": None, "measured": False,
                "note": ("тела на фотографии не видно — скорее всего портрет. "
                         "Это НЕ корзина по умолчанию: выбирать корзину по "
                         "типовому телу значит выбирать наугад с видом "
                         "уверенности. Спросить у клиента или выбрать руками.")}

    value = proportions.get(KEY)
    if value is None:
        return {"bucket": UNSURE, "value": None, "measured": False,
                "note": (f"в пропорциях нет {KEY}: пояс плеч или таза детектор "
                         f"не поймал. Не смогли — не то же, что «пограничная "
                         f"фигура».")}

    low, high = split - band, split + band
    if value < low:
        bucket, why = BUCKET_A, f"{value} ниже {low:.4f}"
    elif value > high:
        bucket, why = BUCKET_B, f"{value} выше {high:.4f}"
    else:
        bucket, why = UNSURE, (f"{value} внутри полосы [{low:.4f}, {high:.4f}], "
                               f"где у нас нет оснований выбирать")
    return {"bucket": bucket, "value": value, "measured": True,
            "split": split, "band": band,
            "note": (f"{KEY} = {value}; {why} -> {bucket}"
                     + ("" if bucket != UNSURE else
                        ". Падает на ручной выбор — это и есть работа третьего "
                        "исхода, а не отказ"))}


def agreement(labelled, *, split: float = SPLIT,
              band: float = UNSURE_BAND) -> dict:
    """Согласие с человеком на размеченной горстке. Приёмка маршрутизатора.

    `labelled` — пары `(пропорции_или_путь, корзина_по_мнению_человека)`.

    СЧИТАЮТСЯ ТРИ ЧИСЛА, А НЕ ОДНО (Р2, Е3): совпало, разошлось, отдано
    человеку. Третье НЕ ошибка — маршрутизатор для того и сделан, чтобы
    отдавать сомнительное. Но и не успех: маршрутизатор, отдающий человеку
    ВСЁ, согласуется с ним идеально и не делает ничего. Поэтому доля «не
    уверен» печатается рядом и судится отдельно.
    """
    agreed, disagreed, deferred = [], [], []
    for item, human in labelled:
        got = route(**({"proportions": item} if isinstance(item, dict)
                       else {"photo": item}), split=split, band=band)
        if got["bucket"] == UNSURE:
            deferred.append((item, human))
        elif got["bucket"] == human:
            agreed.append((item, human))
        else:
            disagreed.append((item, human, got["bucket"]))

    total = len(labelled)
    decided = len(agreed) + len(disagreed)
    return {
        "outcome": UNMEASURED if not total else PASS,
        "total": total, "agreed": len(agreed), "disagreed": len(disagreed),
        "deferred": len(deferred),
        "accuracy_on_decided": (round(len(agreed) / decided, 3)
                                if decided else None),
        "deferral_share": round(len(deferred) / total, 3) if total else None,
        "disagreements": disagreed,
        "note": (f"примеров {total}: совпало {len(agreed)}, разошлось "
                 f"{len(disagreed)}, отдано человеку {len(deferred)}. "
                 + (f"На решённых точность "
                    f"{len(agreed) / decided:.0%}. " if decided else
                    "Решённых нет — маршрутизатор отдал человеку всё, то есть "
                    "не сделал ничего. ")
                 + "НЕПРОВЕРЕНО: размеченной горстки пока не существует."),
    }
