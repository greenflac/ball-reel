"""Кадры моста: промежуточные КАДРЫ драйвинга между концом круга и началом.

ЗАЧЕМ, И ПОЧЕМУ КАДРЫ, А НЕ СКЕЛЕТЫ. Идеальной петли в снятом материале не
бывает: между последним кадром круга и первым остаётся стык. Мост его
закрывает — по нему тело доходит от одной позы к другой с обычной скоростью.

Первая редакция строила мост НА СКЕЛЕТАХ: интерполировала 133 точки и рисовала
позу. Владелец поправил — совмещать надо кадры, — и поправка подтвердилась
замером, а не согласием. ИЗМЕРЕНО на боевом материале, петля 114..162, порог
видимости точки 0.3:

    настоящий кадр 162   точек 133/133   колени/лодыжки 0.874 0.788 0.865 0.777
    ПРОМЕЖУТОЧНЫЙ КАДР   точек 133/133                  0.875 0.819 0.861 0.798
    настоящий кадр 114   точек 133/133                  0.876 0.824 0.869 0.805

Детектор не отличает промежуточный кадр от настоящего — разница в пределах
шума. Отсюда три следствия, и все три снимают особые случаи, а не добавляют:

    поза   снимается с кадра моста ОБЫЧНЫМ путём -> исчезает вопрос «точка
           видна только на одном конце», который на скелетном мосту давал
           третий исход и ронял вердикт на боевой петле;
    маска  снимается с кадра моста ОБЫЧНЫМ путём -> есть картинка, есть что
           сегментировать; на скелетном мосту сегментировать было нечего;
    конвейер про мост НИЧЕГО НЕ ЗНАЕТ — кадр моста лежит в каталоге драйвинга
           рядом с настоящими и обрабатывается как настоящий.

ЛИЦО С КАДРА МОСТА НЕ БЕРЁТСЯ, И ЭТО ИЗМЕРЕНО, А НЕ ИЗ ОСТОРОЖНОСТИ. В
`face_images` уходят ПИКСЕЛИ кадра, а не отрисовка. Энергия границ кропа лица
(Лаплас по яркости, кроп 512 по вендорской рамке):

    настоящие кадры 162 / 114 / 113:  3.3 / 3.3 / 3.2  — разброс 3.5%
    промежуточный:                    2.1              — ПРОСАДКА 35.6%

Смена по каналам браковала перекрёстное затухание уже при просадке 11-15%;
здесь 35.6%, и глазами видно сразу (оправа очков размыта). Поэтому лицо на
кадрах моста берётся у ближайшего настоящего кадра — правило живёт в
`fork_channels`, здесь оно только названо, чтобы не потерялось.

ПРИБОР КАЧЕСТВА ЗДЕСЬ ОДИН, И ОН ВЫБРАН ПОСЛЕ ТОГО, КАК ПЕРВЫЙ ПРОВАЛИЛ
НЕГАТИВНЫЙ КОНТРОЛЬ (И5). Сначала мерилась резкость кадра целиком — и была
отвергнута ПРОГОНОМ:

    кадр сам с собой                 просадка 0.00%   (обязан молчать — молчит)
    правильная близкая пара          просадка 54.0%
    два далёких кадра (114 и 300)    просадка  4.6%   <- ХУЖЕ ВХОД, ЛУЧШЕ ЧИСЛО

Резкость меряет «есть ли высокие частоты», а не «правильные ли они»: поток
между далёкими кадрами мажет материал по кадру, и его рваные края держат
дисперсию высокой. Порог на такой мере — прибор, измеряющий не то.

Взята ВЕЛИЧИНА СМЕЩЕНИЯ: 95-й процентиль длины вектора потока, приведённый к
обычному межкадровому смещению ЭТОЙ ЖЕ окрестности клипа. Не среднее по кадру:
фон неподвижен и утопил бы движение конечностей. Оба негативных контроля
проходятся:

    кадр сам с собой                 0.000 px          (молчит)
    два далёких кадра (114 и 300)    96.71 px = 27.3 обычного шага  (кричит)
    стык петли 114..162               5.00 px =  1.41 обычного шага
    стык петли 297..345               8.52 px =  0.58 обычного шага

То есть на боевых стыках смещение сравнимо с ОДНИМ обычным межкадровым шагом —
интерполяция делает ровно то, что делает между обычными соседними кадрами.

ТРИ ИСХОДА (Р1):

    годно      кадры построены; сказано сколько, с каким смещением и во
               сколько обычных шагов оно обошлось;
    не годно   кадры не читаются, разного размера, либо смещение на стыке
               выше потолка — интерполировать через такой разрыв значит
               выдумать движение, которого никто не снимал;
    не смогли  опорного смещения клипа нет (не из чего считать отношение) —
               число получить можно, а СУДИТЬ по нему нечем.

ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ И НЕ БУДЕТ. Он не решает, СКОЛЬКО кадров в мосту —
это `fork_looper.bridge_frames` по измеренному стыку. Он не раскладывает ролик
— это `fork_splice.cycle_plan`. Он не судит, годна ли поза, снятая с его кадра
— это дело того, кто её снимает. Он производит кадры и честно печатает, чего
они стоили.
"""

from __future__ import annotations

import time
from pathlib import Path

from . import fork_looper, fork_video
from .fork_identity import FAIL, PASS, UNMEASURED

# ---------------------------------------------------------------------------
# КОНСТАНТЫ-РЕШЕНИЯ. У каждой помечено происхождение (И4).
# ---------------------------------------------------------------------------

#: ВЫБРАНО (кем: эта смена; из чего: из наличного в образе). Плотный
#: оптический поток `cv2.DISOpticalFlow`, средняя предустановка. Стороннего
#: интерполятора кадров в код НЕ ВНЕСЕНО: по Ц10 существование внешнего имени
#: доказывается командой ДО того, как оно попадает в код, по Ц5 лицензия
#: проверяется до встраивания — ни того, ни другого не сделано.
#: DEBT(2026-08-20): настоящий интерполятор кадров снял бы и просадку лица
#: (35.6%), и тогда лицо можно было бы брать с кадра моста.
FLOW_PRESET = "DIS_MEDIUM"

#: ИЗМЕРЕНО (чем: 95-й процентиль длины вектора потока; на чём:
#: `assets/driving_yogaball.mp4`, окрестности 110..170 и 292..350). Обычное
#: межкадровое смещение — 3.54 px и 14.76 px соответственно, то есть по клипу
#: оно гуляет вчетверо. Поэтому опорное смещение считается ЛОКАЛЬНО, по
#: окрестности стыка, а не по всему ролику. Тот же вывод сделала смена отбора
#: для длины моста, и по той же причине.
SHIFT_PERCENTILE = 95

#: РАСЧЁТ (по `fork_looper.BRIDGE_MAX_FRAMES`, не с прогона). Потолок смещения
#: на стыке — тот же, что потолок длины моста, и это не совпадение: мост
#: длиной k кадров строится ровно потому, что стык равен k обычным шагам.
#: Два разных числа для одной величины разъехались бы (Е1), поэтому здесь
#: импорт, а не копия. Само значение выведено сменой отбора по плато: ответ
#: устойчив на 5..12, то есть при изменении потолка в 2.4 раза.
SHIFT_MAX_STEPS = fork_looper.BRIDGE_MAX_FRAMES

#: ВЫБРАНО (кем: эта смена; из чего: из устройства моста). Мост из нуля кадров
#: — это не мост, а его отсутствие; спрашивать у модуля ноль кадров законно
#: только как «мост не нужен», и отвечает он тогда пустым списком и «годно»,
#: а не отказом.
MIN_BRIDGE = 0

EXIT_BY_OUTCOME = {PASS: 0, FAIL: 1, UNMEASURED: 2}


# ---------------------------------------------------------------------------
# Чистые функции. Развилки вынесены из точки входа, чтобы их красил тест (Т5).
# ---------------------------------------------------------------------------

def moments(count: int) -> list:
    """Моменты времени кадров моста: k штук между концами, концы НЕ включены.

    Делится на k+1, а не на k: мост стоит МЕЖДУ кадром j и кадром i, и ни один
    его кадр не совпадает ни с одним из концов. Деление на k положило бы
    первый кадр моста ровно на донора — то есть удвоило бы кадр там, где мы
    как раз убираем удвоение.
    """
    if not isinstance(count, int) or isinstance(count, bool):
        raise TypeError(f"кадров моста ожидалось целое, пришло {count!r}")
    if count < MIN_BRIDGE:
        raise ValueError(f"кадров моста {count}: отрицательным мост не бывает")
    return [(n + 1) / (count + 1) for n in range(count)]


def shift_verdict(shift_px: float, step_px: float | None) -> dict:
    """Годится ли стык для интерполяции. Три исхода, и третий — не отказ.

    Судит ОТНОШЕНИЕ смещения к обычному межкадровому смещению этой же
    окрестности, а не сами пиксели: обычный шаг гуляет по клипу вчетверо
    (3.54 px против 14.76 на боевом ролике), и абсолютный порог означал бы
    разные требования к разным местам одного и того же ролика.
    """
    if step_px is None:
        return {"outcome": UNMEASURED, "steps": None,
                "note": (f"смещение на стыке {shift_px:.2f} px, но обычное "
                         f"межкадровое смещение окрестности неизвестно — "
                         f"судить не с чем. Это НЕ «стык мал»")}
    if step_px <= 0:
        return {"outcome": UNMEASURED, "steps": None,
                "note": (f"обычное межкадровое смещение {step_px} — делить на "
                         f"это нельзя. Ноль означает неподвижную окрестность, "
                         f"а не мгновенное движение")}
    steps = shift_px / step_px
    if steps > SHIFT_MAX_STEPS:
        return {"outcome": FAIL, "steps": round(steps, 3),
                "note": (f"смещение на стыке {shift_px:.2f} px = "
                         f"{steps:.2f} обычных шага при потолке "
                         f"{SHIFT_MAX_STEPS}. Интерполировать через такой "
                         f"разрыв значит выдумать движение, которого никто "
                         f"не снимал")}
    return {"outcome": PASS, "steps": round(steps, 3),
            "note": (f"смещение на стыке {shift_px:.2f} px = {steps:.2f} "
                     f"обычного шага окрестности (потолок "
                     f"{SHIFT_MAX_STEPS}) — столько же, сколько между "
                     f"обычными соседними кадрами")}


# ---------------------------------------------------------------------------
# Работа с пикселями. Точка внедрения одна и объявлена (Т4)
# ---------------------------------------------------------------------------

def read_flow(a, b):
    """Плотный оптический поток из `a` в `b`. ТОЧКА ВНЕДРЕНИЯ: тест подменяет.

    Импорт ленивый и внутри тела: `cv2` тяжёл, а счёт этого модуля обязан
    проверяться без него. Умолчание, связанное в сигнатуре, мутация константы
    уже не достаёт — эту форму на проекте выгребали.
    """
    import cv2

    dis = cv2.DISOpticalFlow_create(cv2.DISOPTICAL_FLOW_PRESET_MEDIUM)
    return dis.calc(cv2.cvtColor(a, cv2.COLOR_BGR2GRAY),
                    cv2.cvtColor(b, cv2.COLOR_BGR2GRAY), None)


def flow_shift(flow) -> float:
    """Насколько картинка уехала: процентиль длины вектора потока.

    НЕ СРЕДНЕЕ ПО КАДРУ. Фон в наших роликах неподвижен и занимает большую
    часть кадра; среднее утопило бы в нём движение конечностей, ради которого
    всё и меряется. Тот же довод, по которому оси стыка сводятся максимумом.
    """
    import numpy as np

    mag = np.hypot(flow[..., 0], flow[..., 1])
    return float(np.percentile(mag, SHIFT_PERCENTILE))


def warp(img, flow, t: float):
    """Сдвинуть картинку вдоль потока на долю `t`."""
    import cv2
    import numpy as np

    h, w = img.shape[:2]
    gx, gy = np.meshgrid(np.arange(w, dtype=np.float32),
                         np.arange(h, dtype=np.float32))
    return cv2.remap(img, gx + flow[..., 0] * t, gy + flow[..., 1] * t,
                     cv2.INTER_LINEAR, borderMode=cv2.BORDER_REPLICATE)


def tween(a, b, t: float, *, flow=None):
    """Промежуточный кадр в момент `t`. Оба конца тянутся НАВСТРЕЧУ.

    Тянуть только один конец дешевле на один расчёт потока, но тогда кадр
    моста наследует закрытия ровно одного донора: то, что на нём заслонено,
    останется заслонённым весь мост. Встречная деформация берёт каждую область
    у того донора, который ближе по времени.
    """
    import cv2

    if not 0.0 < t < 1.0:
        raise ValueError(
            f"момент моста t={t}: кадр моста лежит СТРОГО между концами. "
            f"t=0 и t=1 — это сами доноры, и класть их значит удвоить кадр")
    flow = read_flow if flow is None else flow
    return cv2.addWeighted(warp(a, flow(a, b), t), 1 - t,
                           warp(b, flow(b, a), 1 - t), t, 0)


# ---------------------------------------------------------------------------
# Разбор целиком
# ---------------------------------------------------------------------------

def local_step(paths, around: int, *, span: int = 8, flow=None,
               reader=None) -> dict:
    """Обычное межкадровое смещение ОКРЕСТНОСТИ кадра. Три исхода.

    `span` пар в каждую сторону; медиана, а не среднее — одиночный резкий
    кадр не должен задирать опору, по которой судят все остальные.
    """
    import numpy as np

    flow = read_flow if flow is None else flow
    reader = _read_image if reader is None else reader
    lo = max(0, around - span)
    hi = min(len(paths) - 1, around + span)
    vals = []
    for k in range(lo, hi):
        a, b = reader(paths[k]), reader(paths[k + 1])
        if a is None or b is None:
            continue
        vals.append(flow_shift(flow(a, b)))
    if not vals:
        return {"outcome": UNMEASURED, "step": None, "pairs": 0,
                "note": (f"вокруг кадра {around} не набралось ни одной пары "
                         f"для опоры: прочитано 0 из {max(0, hi - lo)}")}
    return {"outcome": PASS, "step": float(np.median(vals)),
            "pairs": len(vals),
            "note": (f"обычное межкадровое смещение вокруг кадра {around}: "
                     f"{np.median(vals):.2f} px по {len(vals)} парам")}


def _read_image(path):
    import cv2

    return cv2.imread(str(path))


def build(paths, j: int, i: int, count: int, out_dir, *, flow=None,
          reader=None, writer=None) -> dict:
    """Построить `count` кадров моста от кадра `j` к кадру `i`.

    `paths` — отсортированный список кадров драйвинга, `j` — последний кадр
    круга, `i` — первый. Имена файлов берутся у раскодировщика
    (`fork_video.frame_name`, Е1): дальше по пути кадры собираются
    `sorted(glob('*.png'))`, и своя схема имён сортировалась бы иначе ровно
    там, где этого никто не проверяет.
    """
    t0 = time.perf_counter()
    flow = read_flow if flow is None else flow
    reader = _read_image if reader is None else reader
    writer = _write_image if writer is None else writer
    steps = []

    def done(outcome, note, **extra):
        out = {"outcome": outcome, "written": 0, "paths": [], "shift": None,
               "steps_of_clip": None,
               "elapsed": round(time.perf_counter() - t0, 4),
               "checks": steps, "note": note}
        out.update(extra)
        return out

    if count == 0:
        return done(PASS, "мост не нужен: заказано 0 кадров")
    try:
        moments_at = moments(count)
    except (TypeError, ValueError) as exc:
        return done(FAIL, str(exc))
    for name, k in (("j", j), ("i", i)):
        if not isinstance(k, int) or isinstance(k, bool):
            return done(FAIL, f"{name}={k!r}: ожидался номер кадра")
        if not 0 <= k < len(paths):
            return done(FAIL, f"{name}={k} вне материала из {len(paths)} "
                              f"кадров")

    a, b = reader(paths[j]), reader(paths[i])
    if a is None or b is None:
        gone = paths[j] if a is None else paths[i]
        return done(FAIL, f"кадр не читается как изображение: {gone}")
    if a.shape != b.shape:
        return done(FAIL, (f"концы стыка разного размера: {a.shape} и "
                           f"{b.shape} — интерполировать нечего"))
    steps.append(("концы", PASS, f"оба кадра читаются, {a.shape[1]}x"
                                 f"{a.shape[0]}"))

    # Дешёвое раньше дорогого (П2): отказ по смещению не должен стоить ни
    # одного построенного кадра. Поток на паре — миллисекунды, построение
    # моста — count пар плюс запись.
    shift = flow_shift(flow(a, b))
    # ОПОРА БЕРЁТСЯ У ОБОИХ КОНЦОВ, И БЕРЁТСЯ МЕНЬШАЯ. НАЙДЕНО СВОИМ ЖЕ
    # НЕГАТИВНЫМ КОНТРОЛЕМ (И5), а не рассуждением: пока опора считалась
    # только вокруг `i`, пара кадров 114 и 300 — разъехавшихся на 96.71 px,
    # то есть заведомый мусор — прошла как «годно». Кадр 300 лежит в быстром
    # упражнении (16.47 px на шаг), и мусор поделился на большое число.
    # Вокруг кадра 114 шаг 2.81 px, и то же смещение даёт 34.4 шага — отказ.
    # Меньшая опора выбрана не для строгости ради строгости: мост обязан идти
    # со скоростью МЕДЛЕННОЙ из двух окрестностей, иначе в ней он мчится.
    at_j = local_step(paths, j, flow=flow, reader=reader)
    at_i = local_step(paths, i, flow=flow, reader=reader)
    have = [r["step"] for r in (at_j, at_i) if r["step"] is not None]
    base_step = min(have) if have else None
    verdict = shift_verdict(shift, base_step)
    steps.append(("смещение", verdict["outcome"],
                  (f"опора: вокруг {j} {at_j['step'] and round(at_j['step'], 2)}"
                   f" px, вокруг {i} "
                   f"{at_i['step'] and round(at_i['step'], 2)} px, берём "
                   f"меньшую; {verdict['note']}")))
    if verdict["outcome"] != PASS:
        return done(verdict["outcome"], verdict["note"], shift=round(shift, 3),
                    steps_of_clip=verdict["steps"])

    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for n, t in enumerate(moments_at):
        dst = out / fork_video.frame_name(n)
        writer(dst, tween(a, b, t, flow=flow))
        written.append(dst)
    steps.append(("запись", PASS, f"кадров моста записано {len(written)}"))
    return done(PASS,
                (f"мост из {len(written)} кадр(ов) между {j} и {i}: "
                 f"{verdict['note']}. Лицо с этих кадров НЕ БЕРЁТСЯ "
                 f"(интерполяция мылит кроп на 35.6% при естественном "
                 f"разбросе 3.5%) — его берут у ближайшего настоящего кадра"),
                written=len(written), paths=written, shift=round(shift, 3),
                steps_of_clip=verdict["steps"])


def _write_image(path, img):
    import cv2

    cv2.imwrite(str(path), img)


def main(argv=None) -> int:
    """Точка входа: КАДРЫ + СТЫК -> КАДРЫ МОСТА. Три исхода, три кода."""
    import argparse

    p = argparse.ArgumentParser(
        prog="python3 -m ball_reel.fork_bridge",
        description="Промежуточные кадры драйвинга между концом круга и его "
                    "началом")
    p.add_argument("frames", help="каталог кадров драйвинга")
    p.add_argument("--from", dest="j", type=int, required=True,
                   help="номер последнего кадра круга")
    p.add_argument("--to", dest="i", type=int, required=True,
                   help="номер первого кадра круга")
    p.add_argument("--count", type=int, required=True,
                   help="сколько кадров моста (считает fork_looper)")
    p.add_argument("--out", required=True, help="куда положить кадры моста")
    a = p.parse_args(argv)

    paths = fork_looper.frame_paths(Path(a.frames))
    rep = build(paths, a.j, a.i, a.count, a.out)
    for name, outcome, note in rep["checks"]:
        print(f"  [{outcome:>18}] {name:<10} {note}")
    print(f"\n{rep['outcome']}: {rep['note']}")
    return EXIT_BY_OUTCOME[rep["outcome"]]


