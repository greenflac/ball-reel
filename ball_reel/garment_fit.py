#: Кости, вдоль которых имеет смысл спрашивать про ткань. Кисти, стопы и шея
#: выкинуты не по вкусу, а потому что одежды на них обычно нет, а мелкий
#: масштаб гарантирует отказ измерять.
WORN_BONES = ("torso", "l_thigh", "r_thigh", "l_upperarm", "r_upperarm",
              "l_shin", "r_shin")

#: Сколько узлов у выкройки вдоль кости и поперёк неё. Числа ВЫБРАНЫ из
#: геометрии сетки, а не подобраны: 48 узлов на 0.7 длины кости при минимально
#: допустимой кости (см. `MIN_LIMB_PX`) дают шаг чуть больше пикселя, то есть
#: сетка нигде не выдумывает деталь, которой в кадре нет.
GRID_ALONG = 48
GRID_ACROSS = 20

#: Сколько отрезать у концов кости. Возле суставов цилиндр перестаёт быть
#: цилиндром: там сгиб, там же кончается рукав и начинается кожа. ВЫБРАНО.
U_MARGIN = 0.15

#: Докуда по обхвату брать поверхность. У силуэта (|v| -> 1) участок
#: поверхности занимает считанные пиксели, и выкройка там растягивает шум.
#: ВЫБРАНО: 0.6 по нашей шкале — это 54 градуса от центра, где сжатие ещё
#: меньше двукратного.
V_LIMIT = 0.6

#: Окно размытия для высокочастотного остатка, в узлах сетки. ВЫБРАНО:
#: 9 узлов — это 0.13 длины кости, то есть заметно крупнее складки и заметно
#: мельче светотени на конечности. Слишком маленькое окно съело бы сами
#: складки, слишком большое оставило бы светотень.
HIGHPASS_CELLS = 9

#: Короче этого (длина кости в пикселях) выкройку строить нечестно: сетка на
#: 48 узлов начнёт интерполировать вместо того, чтобы читать. ПОСЧИТАНО от
#: сетки, а не выбрано на глаз: 48 узлов / 0.7 длины = 69 px; округлено вверх
#: до 80, чтобы шаг оставался больше пикселя с запасом. На нашем driving-
#: отрезке (кадр 720x1278) кости оказались 142..258 px, то есть порог не режет
#: съёмку общим планом, но конечность вдвое дальше он уже отклонит.
MIN_LIMB_PX = 80

#: Ниже этого среднеквадратичного контраста выкройки (в долях 0..1, уже после
#: высокочастотного остатка) отслеживать нечего: ткань гладкая, узора нет.
#: Это ОТКАЗ ИЗМЕРЯТЬ, а не «плохо»: на однотонном полотне без складок
#: прилегание принципиально ненаблюдаемо — скользящая гладкая ткань выглядит
#: ровно так же, как прилегающая, — и молчать об этом нельзя.
#:
#: Обе опоры ИЗМЕРЕНЫ:
#:     синтетика, заливка без узора            0.0000
#:     driving-отрезок, 71 кадр, 7 костей      min 0.0040, p10 0.0147,
#:                                             p50 0.0302
#: Бар 0.003 лежит между ними, ближе к нулю: цена ложного «нет узора» —
#: молчание там, где можно было судить, и она ниже цены обратной ошибки.
MIN_TEXTURE = 0.003

#: Ниже этого пика нормированной корреляции сдвиг не определён: совпадать
#: нечему. Так выглядит либо полностью перерисованная область, либо сорванная
#: поза. Тоже ОТКАЗ ИЗМЕРЯТЬ, а не приговор.
#:
#: Обе опоры ИЗМЕРЕНЫ:
#:     две независимые случайные текстуры (30 прогонов)  пик 0.058..0.078
#:     driving-отрезок, соседние кадры (448 пар)         p50 0.847, p10 0.605,
#:                                                       min 0.141
#: Разделение почти восьмикратное. Бар 0.30 стоит заметно выше шума и
#: ниже настоящего сопровождения; при нём из 448 настоящих пар не судились 10
#: (2.2%) — это те кадры, где поза дёрнулась.
MIN_PEAK = 0.30

#: Насколько далеко ищется сдвиг, в долях длины кости. За этой границей
#: «скольжение» неотличимо от совпадения с другой складкой. ВЫБРАНО 0.18 —
#: примерно ширина конечности, дальше сравнивать уже нечего.
SEARCH_ALONG = 0.18

#: Тот же поиск по обхвату, в единицах v.
SEARCH_ACROSS = 0.4

#: Допустимое скольжение ткани вдоль кости, в долях длины кости, по МЕДИАНЕ
#: пар кадров (почему медиана — см. `garment_fit`). Бар ВЫБРАН, но зажат между
#: двумя ИЗМЕРЕННЫМИ опорами:
#:
#:     driving-отрезок, соседние кадры, настоящая одежда на настоящем теле —
#:     то есть ткань заведомо прилегает:
#:         |slip_u| p50 по костям 0.0043..0.0175 (худшая l_upperarm 0.0175),
#:         p90 до 0.0547
#:     та же настоящая текстура с ВНЕСЁННЫМ сдвигом 0.0447 длины кости:
#:         восстановлено p50 0.0461 (p10 0.0243, p90 0.0683, 438 пар)
#:     внесённый сдвиг 0.1043:
#:         восстановлено p50 0.1060
#:
#: 0.03 — геометрическая середина между полом настоящей съёмки (0.0175) и
#: заведомым скольжением (0.046). ЭТО СЛАБОЕ РАЗДЕЛЕНИЕ: 2.6 раза против
#: семикратного у `garment.GARMENT_DRIFT_MAX`, и признать это честнее, чем
#: назвать бар выверенным. Пол настоящей съёмки — не чистый шум позы: рукав на
#: плече действительно ползает, и метрика права, что это видит.
#:
#: ЧЕГО ЗДЕСЬ НЕТ: верхней опоры на настоящей ГЕНЕРАЦИИ. Ни один
#: сгенерированный клип этой метрикой ещё не мерился, и число придётся
#: перепроверить на первом же — ровно как это уже случилось с одеждой.
SLIP_MAX = 0.03

#: Меньше этого числа измеренных пар — клип не судится. Одна-две пары ловят
#: случайную дрожь позы, а не поведение ткани.
MIN_PAIRS = 5


def _load(image):
    """Картинка -> массив 0..1. Принимает путь или готовый массив."""
    import numpy as np
    from PIL import Image

    if isinstance(image, (str, bytes)) or hasattr(image, "__fspath__"):
        with Image.open(image) as im:
            return np.asarray(im.convert("RGB"), dtype=np.float64) / 255.0
    arr = np.asarray(image, dtype=np.float64)
    return arr / 255.0 if arr.max() > 1.0 else arr


def _bone_frame(points: dict, bone: str, min_visibility: float):
    """Кость в пикселях: (начало, направление, нормаль, длина). None — не судим.

    None означает «кость не видна», а не «ткань плохая». Это то же различение,
    что в `marks.locate`, и держать его надо так же строго.
    """
    pair = marks.BONES.get(bone)
    if pair is None:
        return None
    a, b = points.get(pair[0]), points.get(pair[1])
    if not a or not b:
        return None
    if min(a[2], b[2]) < min_visibility:
        return None
    w, h, _ = points.get("__size__", (0.0, 0.0, 1.0))
    if not w or not h:
        return None
    ax, ay = a[0] * w, a[1] * h
    dx, dy = b[0] * w - ax, b[1] * h - ay
    length = (dx * dx + dy * dy) ** 0.5
    if length < 1e-6:
        return None
    ux, uy = dx / length, dy / length
    return (ax, ay), (ux, uy), (-uy, ux), length


def surface_to_pixel(points: dict, bone: str, u, v, *,
                     half_width: float = marks.LIMB_HALF_WIDTH,
                     min_visibility: float = 0.5):
    """Точка поверхности (u, v) -> пиксель этого кадра. Обратна `marks.limb_uv`.

    Держится здесь, а не берётся из `marks`, по одной причине: `marks` — чужой
    модуль с одним писателем, и опираться на его приватные имена значит
    подписаться на чужие правки. Расхождение с оригиналом ловит тест, который
    гоняет туда-обратно через настоящий `marks.limb_uv`: если формулы разойдутся,
    круговой прогон сломается, а не тихо соврёт.
    """
    import numpy as np

    frame = _bone_frame(points, bone, min_visibility)
    if frame is None:
        return None
    (ax, ay), (ux, uy), (px, py), length = frame
    # d = r*sin(v * pi/2) — ровно то, что limb_uv обращает через arcsin.
    d = length * half_width * np.sin(np.asarray(v, dtype=float) * (np.pi / 2))
    u = np.asarray(u, dtype=float)
    return ax + ux * length * u + px * d, ay + uy * length * u + py * d


def _bilinear(arr, xs, ys):
    """Значения картинки в дробных координатах. (значения, внутри кадра?)."""
    import numpy as np

    h, w = arr.shape[:2]
    inside = (xs >= 0) & (xs <= w - 1) & (ys >= 0) & (ys <= h - 1)
    x0 = np.clip(np.floor(xs), 0, w - 2).astype(int)
    y0 = np.clip(np.floor(ys), 0, h - 2).astype(int)
    fx = np.clip(xs - x0, 0.0, 1.0)[..., None]
    fy = np.clip(ys - y0, 0.0, 1.0)[..., None]
    top = arr[y0, x0] * (1 - fx) + arr[y0, x0 + 1] * fx
    bot = arr[y0 + 1, x0] * (1 - fx) + arr[y0 + 1, x0 + 1] * fx
    return top * (1 - fy) + bot * fy, inside


def _box_blur(t, k: int):
    """Скользящее среднее k x k по двум последним осям, край продлевается."""
    import numpy as np

    k = int(k)
    if k % 2 == 0:
        k += 1
    k = max(1, min(k, t.shape[-1] // 2 * 2 - 1, t.shape[-2] // 2 * 2 - 1))
    if k <= 1:
        return t
    pad = k // 2
    a = np.pad(t, [(0, 0)] * (t.ndim - 2) + [(pad, pad), (pad, pad)],
               mode="edge")
    c = np.cumsum(a, axis=-1)
    c = np.concatenate([np.zeros_like(c[..., :1]), c], axis=-1)
    a = (c[..., k:] - c[..., :-k]) / k
    c = np.cumsum(a, axis=-2)
    c = np.concatenate([np.zeros_like(c[..., :1, :]), c], axis=-2)
    return (c[..., k:, :] - c[..., :-k, :]) / k


def _channels(rgb):
    """Яркость и две оппонентные оси цвета.

    Цвет здесь не роскошь: печатный рисунок бывает равнояркостным (красное на
    зелёном той же светлоты), и на одной яркости он невидим. Оппонентные оси
    берутся как разности каналов, потому что разность не зависит от общего
    множителя освещения так же сильно, как сам канал.
    """
    import numpy as np

    r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
    lum = 0.299 * r + 0.587 * g + 0.114 * b
    return np.stack([lum, r - g, b - (r + g) / 2.0])


def unwrap(image, points: dict, bone: str, *,
           along: int = GRID_ALONG, across: int = GRID_ACROSS,
           u_margin: float = U_MARGIN, v_limit: float = V_LIMIT,
           highpass: int = HIGHPASS_CELLS,
           min_limb_px: int = MIN_LIMB_PX,
           min_visibility: float = 0.5):
    """Развернуть конечность в «выкройку» (u, v). None — судить нельзя.

    Возвращает словарь с полем `texture` формы (3, across, along): три канала,
    строки — обхват, столбцы — вдоль кости. Это и есть ткань в координатах
    ТЕЛА: один и тот же столбец в двух кадрах смотрит на одно и то же место
    тела, как бы человек ни повернулся.

    Из выкройки сразу вычитается низкая частота и строчное среднее — см.
    докстринг модуля, пункты 1 и 2. Без этого метрика мерила бы светотень,
    которая приклеена к телу и потому всегда «прилегает».

    None возвращается в трёх случаях, и все три означают ОТСУТСТВИЕ
    НАБЛЮДЕНИЯ: кость не видна, кость мельче `min_limb_px`, поверхность
    заметно вышла за край кадра. Ни один из них не является претензией к
    одежде.
    """
    import numpy as np

    frame = _bone_frame(points, bone, min_visibility)
    if frame is None:
        return None
    length = frame[3]
    if length < min_limb_px:
        return None

    arr = _load(image)
    us = np.linspace(u_margin, 1.0 - u_margin, along)[None, :]
    vs = np.linspace(-v_limit, v_limit, across)[:, None]
    mapped = surface_to_pixel(points, bone, np.broadcast_to(us, (across, along)),
                              np.broadcast_to(vs, (across, along)),
                              min_visibility=min_visibility)
    if mapped is None:
        return None
    xs, ys = mapped
    px, inside = _bilinear(arr, xs, ys)
    # Кусок конечности, ушедший за край кадра, — это не «ткань уехала»,
    # а отсутствие пикселей. Сравнивать выкройку, half of which is edge clamp,
    # значит выдумывать.
    if inside.mean() < 0.95:
        return None

    t = _channels(px)
    t = t - _box_blur(t, highpass)
    # Строчное среднее: структура, зависящая только от обхвата, про сдвиг
    # вдоль кости не знает ничего, а пик корреляции делает плоским.
    t = t - t.mean(axis=-1, keepdims=True)

    du = (1.0 - 2.0 * u_margin) / max(along - 1, 1)
    dv = (2.0 * v_limit) / max(across - 1, 1)
    return {
        "bone": bone,
        "texture": t,
        "du": du,
        "dv": dv,
        "limb_px": round(float(length), 1),
        "contrast": round(float(np.sqrt((t ** 2).mean())), 5),
    }


def _correlate(a, b, max_u: int, max_v: int):
    """Пик нормированной корреляции по сетке сдвигов. (пик, su, sv, при нуле).

    Сдвиг (su, sv) означает: узор кадра B стоит там, где у кадра A он был
    на (su, sv) узлов раньше. Нормировка считается ЗАНОВО в каждом окне
    перекрытия — иначе сдвиги с меньшим перекрытием получали бы фору.
    """
    import numpy as np

    nv, nu = a.shape[-2], a.shape[-1]
    best = (-2.0, 0, 0)
    at_zero = -2.0
    for sv in range(-max_v, max_v + 1):
        av0, av1 = max(0, -sv), nv - max(0, sv)
        bv0, bv1 = max(0, sv), nv - max(0, -sv)
        if av1 - av0 < 3:
            continue
        for su in range(-max_u, max_u + 1):
            au0, au1 = max(0, -su), nu - max(0, su)
            bu0, bu1 = max(0, su), nu - max(0, -su)
            if au1 - au0 < 3:
                continue
            x = a[..., av0:av1, au0:au1]
            y = b[..., bv0:bv1, bu0:bu1]
            x = x - x.mean(axis=(-2, -1), keepdims=True)
            y = y - y.mean(axis=(-2, -1), keepdims=True)
            nx = float(np.sqrt((x ** 2).sum()))
            ny = float(np.sqrt((y ** 2).sum()))
            if nx < 1e-12 or ny < 1e-12:
                continue
            c = float((x * y).sum()) / (nx * ny)
            if su == 0 and sv == 0:
                at_zero = c
            if c > best[0]:
                best = (c, su, sv)
    return best[0], best[1], best[2], at_zero


def _refine(a, b, su: int, sv: int, max_u: int):
    """Подузловое уточнение сдвига вдоль кости параболой по трём точкам.

    Нужно не ради красоты: шаг сетки 0.015 длины кости, а бар — 0.05, то есть
    без уточнения вердикт различал бы всего три ступеньки.
    """
    import numpy as np

    if abs(su) >= max_u:
        return float(su)
    nv, nu = a.shape[-2], a.shape[-1]
    vals = []
    for s in (su - 1, su, su + 1):
        au0, au1 = max(0, -s), nu - max(0, s)
        bu0, bu1 = max(0, s), nu - max(0, -s)
        av0, av1 = max(0, -sv), nv - max(0, sv)
        bv0, bv1 = max(0, sv), nv - max(0, -sv)
        x = a[..., av0:av1, au0:au1]
        y = b[..., bv0:bv1, bu0:bu1]
        x = x - x.mean(axis=(-2, -1), keepdims=True)
        y = y - y.mean(axis=(-2, -1), keepdims=True)
        nx = float(np.sqrt((x ** 2).sum()))
        ny = float(np.sqrt((y ** 2).sum()))
        vals.append(float((x * y).sum()) / (nx * ny) if nx > 1e-12
                    and ny > 1e-12 else -2.0)
    lo, mid, hi = vals
    denom = lo - 2 * mid + hi
    if abs(denom) < 1e-9:
        return float(su)
    delta = 0.5 * (lo - hi) / denom
    return float(su) + float(np.clip(delta, -1.0, 1.0))


def surface_slip(before: dict | None, after: dict | None, *,
                 max_slip: float = SLIP_MAX,
                 min_texture: float = MIN_TEXTURE,
                 min_peak: float = MIN_PEAK,
                 search_along: float = SEARCH_ALONG,
                 search_across: float = SEARCH_ACROSS) -> dict:
    """На сколько уехал узор ткани между двумя выкройками одной кости.

    Четыре исхода, и склеивать их нельзя:

    * ``not_observed`` — одной из выкроек нет: кость не видна, мелка или ушла
      за край кадра. Отсутствие наблюдения, не отказ ткани;
    * ``no_texture`` — ткань гладкая, следить не за чем. Прилегание тут
      ненаблюдаемо в принципе, и назвать это «прилегает» было бы враньём:
      скользящая гладкая ткань выглядит ровно так же;
    * ``weak_match`` — совпадения нет ни при каком сдвиге. Область
      перерисована целиком или поза сорвалась. Это тоже не вердикт о ткани;
    * ``measured`` — сдвиг найден, и `held` отвечает на вопрос.

    `slip_u` — в долях длины кости, со знаком: положительный означает, что
    узор уехал к дочернему суставу. `slip_v` возвращается справочно и в
    вердикт не входит (см. докстринг модуля).
    """
    if before is None or after is None:
        return {"held": None, "state": "not_observed",
                "note": ("кость не видна, мельче "
                         f"{MIN_LIMB_PX}px или вышла за край кадра — "
                         "прилегание не наблюдалось")}
    if before["bone"] != after["bone"]:
        raise ValueError("сравниваются выкройки разных костей")
    weakest = min(before["contrast"], after["contrast"])
    if weakest < min_texture:
        return {"held": None, "state": "no_texture",
                "contrast": weakest, "bone": before["bone"],
                "note": (f"контраст выкройки {weakest} < {min_texture}: ткань "
                         "гладкая, следить не за чем. Прилегание на однотонном "
                         "полотне без складок НЕНАБЛЮДАЕМО, и это отказ "
                         "измерять, а не «прилегает»")}

    a, b = before["texture"], after["texture"]
    du, dv = before["du"], before["dv"]
    max_u = max(1, int(round(search_along / du)))
    max_v = max(1, int(round(search_across / dv)))
    peak, su, sv, at_zero = _correlate(a, b, max_u, max_v)
    if peak < min_peak:
        return {"held": None, "state": "weak_match", "peak": round(peak, 4),
                "bone": before["bone"],
                "note": (f"пик совпадения {round(peak, 3)} < {min_peak}: узор "
                         "не опознаётся ни при каком сдвиге — область "
                         "перерисована или поза сорвалась. Судить нельзя")}

    fine = _refine(a, b, su, sv, max_u)
    slip_u = fine * du
    slip_v = sv * dv
    held = abs(slip_u) <= max_slip
    return {
        "held": bool(held), "state": "measured", "bone": before["bone"],
        "slip_u": round(slip_u, 4), "slip_v": round(slip_v, 4),
        "peak": round(peak, 4), "peak_at_zero": round(at_zero, 4),
        "contrast": weakest,
        "note": (f"узор ткани сместился на {abs(slip_u):.3f} длины кости "
                 f"(бар {max_slip}, совпадение {peak:.2f}); "
                 + ("держится за телом" if held else
                    "СКОЛЬЗИТ — ткань живёт отдельно от тела")
                 + f"; по обхвату {slip_v:+.3f} (справочно, в вердикт не входит)"),
    }


def _percentile(values, q: float) -> float:
    import numpy as np

    return float(np.percentile(np.asarray(values, dtype=float), q))


def garment_fit(frames: list, points_by_frame: list, *,
                bones=WORN_BONES, stride: int = 1,
                max_slip: float = SLIP_MAX,
                min_pairs: int = MIN_PAIRS) -> dict:
    """Прилегает ли одежда по всему клипу.

    `points_by_frame` — позы тех же кадров (`dwpose.pose_points` или
    `skeleton.pose_points`): поверхность выводится из скелета.

    ПОЧЕМУ МЕДИАНА, А НЕ ХВОСТ. Судится ХУДШАЯ кость по МЕДИАНЕ модуля
    скольжения. Хвост здесь принадлежит не ткани, а оценщику позы: на
    driving-отрезке p90 доходит до 0.055 при медиане 0.017, и разница — это
    кадры, где человек резко двинул рукой, скелет дёрнулся, и выкройка
    поехала вместе с ним. Метрика, судящая по p90, судила бы DWPose.
    Скользящая же ткань скользит В БОЛЬШИНСТВЕ кадров, а не в хвосте, поэтому
    медиана ловит именно её. `p90` возвращается рядом, но в вердикт не входит.

    Худшая кость, а не средняя: среднее прощает одну проваленную конечность
    десятком удачных, а зритель смотрит ровно на ту, где ткань поехала.

    `drift` — сумма скольжений СО ЗНАКОМ по кости: медленный односторонний
    сполз, который каждая отдельная пара пропускает, виден только так. Это
    СПРАВОЧНОЕ число без бара, и вот почему: на настоящей съёмке оно тоже не
    ноль (до 0.37 за 66 пар), потому что рукав действительно ползёт по плечу
    за время клипа. Отделить «ползёт как настоящая ткань» от «ползёт как
    генерация» без опоры на сгенерированный клип нельзя, и ставить бар,
    которого не на чем калибровать, значит выдавать выбранное за измеренное.

    Кости и пары, которые не удалось измерить, считаются отдельно и в вердикт
    не входят. Если измеренных пар меньше `min_pairs`, вердикт не выносится
    вовсе: «не смогли измерить» — это третий ответ, а не «плохо».
    """
    if len(frames) != len(points_by_frame):
        raise ValueError("кадров и поз должно быть поровну")

    per_bone: dict = {}
    refused: dict = {"not_observed": 0, "no_texture": 0, "weak_match": 0}
    cache: dict = {}
    images: dict = {}

    def _unwrapped(idx: int, bone: str):
        key = (idx, bone)
        if key not in cache:
            pts = points_by_frame[idx]
            if not pts:
                cache[key] = None
            else:
                # Кадр читается с диска один раз на все кости.
                if idx not in images:
                    images[idx] = _load(frames[idx])
                cache[key] = unwrap(images[idx], pts, bone)
        return cache[key]

    for i in range(0, len(frames) - stride, stride):
        for bone in bones:
            got = surface_slip(_unwrapped(i, bone), _unwrapped(i + stride, bone),
                               max_slip=max_slip)
            if got["state"] != "measured":
                refused[got["state"]] += 1
                continue
            per_bone.setdefault(bone, []).append(got["slip_u"])
        for key in [k for k in cache if k[0] <= i]:
            cache.pop(key)
        images.pop(i, None)

    measured = sum(len(v) for v in per_bone.values())
    if measured < min_pairs:
        return {"bones": {}, "worst": None, "fits": None,
                "measured": measured, "refused": refused,
                "note": (f"прилегание НЕ ПРОВЕРЕНО: измеренных пар {measured} "
                         f"из нужных {min_pairs}. Отказы: "
                         + ", ".join(f"{k} {v}" for k, v in refused.items())
                         + ". Это отсутствие измерения, а не вердикт")}

    stats = {}
    for bone, vals in per_bone.items():
        mag = [abs(v) for v in vals]
        stats[bone] = {"p50": round(_percentile(mag, 50), 4),
                       "p90": round(_percentile(mag, 90), 4),
                       "drift": round(sum(vals), 4),
                       "pairs": len(vals)}
    worst = max(stats, key=lambda b: stats[b]["p50"])
    fits = stats[worst]["p50"] <= max_slip
    return {
        "bones": stats, "worst": (worst, stats[worst]["p50"]),
        "fits": bool(fits), "measured": measured, "refused": refused,
        "note": ("скольжение ткани (медиана модуля, доли длины кости): "
                 + ", ".join(f"{b} {s['p50']:.3f}"
                             for b, s in sorted(stats.items()))
                 + f" (бар {max_slip}); "
                 + ("одежда держится за телом" if fits else
                    f"ОДЕЖДА СКОЛЬЗИТ на «{worst}» — ткань живёт отдельно "
                    "от тела")
                 + f"; не судилось {sum(refused.values())} сравнени(й): "
                 + ", ".join(f"{k} {v}" for k, v in refused.items())),
    }
