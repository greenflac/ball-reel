"""Прилегание одежды: едет ли ткань ВМЕСТЕ С ТЕЛОМ или скользит по нему.

`garment.py` меряет другое — ДРЕЙФ ЦВЕТА одежды между кадрами: не переоделся ли
человек посреди клипа. Это важный, но слепой к движению вопрос. Худи может во
всех кадрах оставаться ровно того же оттенка и при этом ползать по торсу, как
плёнка по воде: цвет не дрогнет, а глаз увидит подделку с первой секунды. Это
второй, независимый отказ, и до сих пор его не видел ни один гейт.

ЧТО ТАКОЕ ПРИЛЕГАНИЕ, ЕСЛИ СКАЗАТЬ ЕГО ЧИСЛОМ

Настоящая ткань прикреплена к телу. Точка ткани — складка, шов, элемент принта —
держится НАД ОДНОЙ И ТОЙ ЖЕ ТОЧКОЙ ТЕЛА: рука повернулась, ткань повернулась с
ней. Сгенерированная ткань этого не обязана: каждый кадр рисуется заново, узор
пересобирается по месту, и материальная точка уезжает вдоль конечности от кадра
к кадру. Отсюда определение, годное для арифметики:

    прилегание = насколько мало смещается узор ткани В КООРДИНАТАХ ТЕЛА.

Координаты тела уже есть — `marks.limb_uv` даёт (u, v): u вдоль кости, v по
обхвату. Это МАТЕРИАЛЬНАЯ точка поверхности, одна и та же при любой позе. Значит
можно развернуть конечность в прямоугольник (u, v) — «выкройку» — в каждом
кадре, и спросить, на сколько надо сдвинуть выкройку кадра B, чтобы она легла на
выкройку кадра A. Прилегающая ткань даёт сдвиг около нуля; скользящая — сдвиг,
который и есть искомая величина, сразу в долях длины кости.

Заметьте, что меряется НЕ похожесть содержимого. Похожесть падает от смены
света, от перерисовки, от шума сжатия — и ничего не говорит о прилегании.
Меряется ПОЛОЖЕНИЕ наилучшего совпадения. Свет двигает значения, но не двигает
максимум корреляции; скольжение двигает именно его.

ПОЧЕМУ ОПОРА СНОВА ЛОКАЛЬНАЯ

Тот же приём, что спас `garment.py` (хроматичность вместо RGB) и `marks.py`
(контраст с окрестной кожей вместо абсолютного цвета). Здесь он принимает три
формы, и каждая нужна:

**1. Высокочастотный остаток вместо самой картинки.** Из выкройки вычитается её
же размытая копия. Широкая светотень — свойство ТЕЛА и освещения, она стоит на
месте, пока ткань едет, и, оставшись в данных, приклеила бы максимум корреляции
к нулю, то есть отчиталась бы «прилегает» о чём угодно. Остаётся мелкая
структура — складки и принт, то есть ровно то, что принадлежит ткани.

**2. Вычитание строчного среднего.** Структура, зависящая только от v (тень
вдоль всей конечности), про сдвиг по u не знает ничего, зато коррелирует сама с
собой при ЛЮБОМ сдвиге — она делает пик корреляции плоским и выдаёт уверенность
там, где информации нет. Убирается.

**3. Нормированная корреляция.** Совпадение считается против собственного
среднего и собственной нормы в каждом окне перекрытия, поэтому равномерное
изменение яркости и контраста между кадрами на результат не влияет.

ЧЕГО ЭТА МЕТРИКА НЕ УМЕЕТ, И ЭТО НАДО ЗНАТЬ ДО ТОГО, КАК ССЫЛАТЬСЯ НА ЧИСЛО

**Гладкая ткань неизмерима вовсе.** Однотонное полотно без складок и принта не
даёт за чем следить: скользящее и прилегающее выглядят одинаково. Это не
недоделка, а свойство наблюдения, и модуль отвечает отдельным исходом
`no_texture`, а не «прилегает».

**Полосатое и клетчатое врёт.** Периодический узор совпадает сам с собой через
период, и найденный сдвиг может оказаться на период больше или меньше
настоящего. На нашей апериодической синтетике восстановление точное
(внесли 0.10 — прочли 0.098), на первой же периодической версии того же теста
сдвиг 0.05 прочёлся как -0.031. Тельняшка эту метрику обманет.

**Порог совпадения ловит только ПОЛНУЮ потерю соответствия.** Он отсекает
область, перерисованную во что-то несвязанное. Область, перерисованную ТЕМ ЖЕ
материалом — та же ткань, другие складки, — он пропустит, и сдвиг будет назван
уверенно и, возможно, неверно. Замерено на синтетике: узор той же семьи с
другой фазой дал пик 0.53 при баре 0.30.

**Ошибка позы читается как скольжение.** Выкройка строится от найденного
скелета, поэтому дёрнувшийся сустав неотличим от поехавшей ткани. Отсюда
вердикт по медиане, а не по хвосту (см. `garment_fit`), и отсюда же пол шума,
ниже которого бар опускать нельзя.

**Судится смещение ВДОЛЬ кости (u).** Смещение по обхвату (v) считается и
возвращается, но вердикт на нём НЕ строится: плоская модель конечности не
отличает «ткань съехала вбок» от «конечность повернулась вокруг своей оси» —
во втором случае вместе с тканью поворачивается и кожа под ней, и никакого
скольжения нет.

**Свободная одежда — не ошибка генератора.** Юбка, плащ и широкий рукав
двигаются относительно тела по-настоящему; метрика назовёт это скольжением,
потому что это оно и есть. Отличить физику ткани от небрежности генератора она
не может, и на такой одежде её показания надо читать как описание, а не как
приговор.

**Наклон кости ОТ камеры не моделируется** — ограничение унаследовано от
`marks.limb_uv` и требует глубины, которой у нас нет.

Работает на CPU, ничего не генерирует, в сеть не ходит. numpy и Pillow.
"""

