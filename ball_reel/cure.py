"""Команды лечения, которые можно ВЫПОЛНИТЬ на той машине, где они напечатаны.

Весь предполёт построен на одном правиле: у каждой строки отказа есть лечение,
и оно печатается рядом. Правило держалось ровно до первой машины с Windows.
Там оператор увидел четыре отказа и НИ ОДНОГО исполнимого лечения:

    mkdir -p ~/.mediapipe && curl ...     `mkdir -p` в CMD нет, `~` не
                                          раскрывается
    curl -sSLO ... && unzip -o ...        `unzip` в Windows нет
    python3 - <<'EOF' ... EOF             heredoc — синтаксис Bourne shell;
                                          CMD выполняет первую строку и падает
    python3 -c "..."                      `python3` на Windows открывает
                                          Microsoft Store

Лечение, которое нельзя скопировать, — это не лечение, а описание проблемы
вторыми словами. Причём хуже обычного описания: оно выглядит как готовое
решение, и оператор тратит время не на починку, а на разбор синтаксиса чужой
оболочки — накануне сдачи.

ЧТО ЗДЕСЬ ЕСТЬ. Ровно два: имя интерпретатора и способ породить команду,
которая работает в обеих оболочках. Никакой абстракции «команда» — она бы
разрослась, а задача узкая.

ПРЕДПОЧТЕНИЕ ОДНОСТРОЧНИКУ НА PYTHON. Где выбор есть, лечение выдаётся как
`python -c "..."`, а не как пара утилит: `curl`, `unzip`, `mkdir -p` есть не
везде и ведут себя по-разному, а интерпретатор на машине заведомо есть — иначе
некому было бы напечатать этот отказ.
"""

from __future__ import annotations

import os

#: `python3` на Windows либо не найдётся, либо откроет Microsoft Store.
#: Проверять надо `os.name`, а не `sys.platform`: под MSYS/Cygwin второй
#: говорит что-то своё, а оболочка там всё равно не CMD.
WINDOWS = os.name == "nt"

#: Имя интерпретатора для ПЕЧАТАЕМЫХ команд. Не `sys.executable`: у него на
#: Windows пробелы в пути (`C:\Users\User\AppData\Local\...`), и строка без
#: кавычек ломается, а с кавычками — становится нечитаемой.
PY = "python" if WINDOWS else "python3"


def py_snippet(body: str) -> str:
    """Многострочный код на Python -> ОДНА команда, исполнимая в любой оболочке.

    Раньше это печаталось как heredoc (`python3 - <<'EOF'`). В CMD его нет:
    оболочка выполняет первую строку, спотыкается на `<<` и печатает
    `The system cannot find the file specified` — то есть отказ, не имеющий
    отношения к тому, что чинили.

    Точки с запятой вместо переводов строки, потому что `python -c` принимает
    их как разделители операторов верхнего уровня. Отступы недопустимы —
    значит и конструкции с телом (if, for, def) сюда не годятся; для них нужен
    файл, и это осознанная граница применимости.
    """
    parts = [ln.strip() for ln in body.strip().splitlines() if ln.strip()]
    return f'{PY} -c "' + "; ".join(parts) + '"'


def mkdir(path) -> str:
    """Создать каталог вместе с родителями, в обеих оболочках.

    `mkdir -p` в CMD не существует, а голый `mkdir` там как раз создаёт
    промежуточные каталоги (и ругается, если он уже есть, — что безвредно).
    """
    return f'mkdir "{path}"' if WINDOWS else f"mkdir -p {path}"


def download(url: str, dst) -> str:
    """Скачать файл по адресу. `curl` есть и в Windows 10+, и в Unix.

    Кавычки вокруг назначения обязательны на Windows: путь идёт через
    `%USERPROFILE%`, а в имени пользователя бывает пробел.
    """
    return f'curl -sSL -o "{dst}" {url}' if WINDOWS else f"curl -sSL -o {dst} {url}"


def home(sub: str = "") -> str:
    """Домашний каталог в том виде, в каком его поймёт ОБОЛОЧКА, а не Python.

    В отказ идёт строка, которую оператор скопирует, — значит `~` для Unix и
    `%USERPROFILE%` для CMD. Готовый абсолютный путь тоже годится, но он
    привязывает напечатанное к машине, на которой печаталось.
    """
    base = "%USERPROFILE%" if WINDOWS else "~"
    return f"{base}\\{sub}" if (WINDOWS and sub) else (
        f"{base}/{sub}" if sub else base)


def set_env(name: str, value: str = "...") -> str:
    """Задать переменную окружения — командой ТОЙ оболочки, где это печатают.

    `export` есть только в Bourne-совместимых. В CMD это `set`, в PowerShell —
    `$env:`. Печатать `export` пользователю Windows значит отправить его гуглить
    вместо того, чтобы починить: та же ошибка, что с `mkdir -p`.

    Для Windows даётся ДВЕ формы: `$env:` действует до закрытия окна, `setx` —
    навсегда, но подхватывается только в НОВОМ окне. Разница неочевидна и
    стоит одного потерянного часа: `setx` выполнен, переменной в этом окне нет.
    """
    if not WINDOWS:
        return f"export {name}={value}"
    return (f'$env:{name} = "{value}"   (в этом окне)\n'
            f'  setx {name} "{value}"   (навсегда, подхватится в НОВОМ окне)')
