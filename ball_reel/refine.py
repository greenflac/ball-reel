def union_box(boxes, *, size, margin: float | None = None) -> tuple:
    """Покадровые боксы лица -> ОДИН фиксированный квадратный бокс. (бокс, отчёт).

    `boxes` — последовательность (x0, y0, x1, y1) в пикселях кадра; `None` на
    месте кадра означает «лица не нашли», и это не ошибка, а обычное дело на
    полноростовой раскадровке. `size` — (ширина, высота) кадра.

    ТРИ ИСХОДА, и средний — не «плохо»:

    * лиц не нашли ни на одном кадре — `(None, ok=None)`. Мерить было нечего,
      и это ДРУГОЕ утверждение, чем «лицо мелкое»: доводить, может, и было бы
      что, но мы не знаем где;
    * бокс получился мельче `MIN_CROP_PX` — `(None, ok=False)`. Здесь мы
      измерили и отказались: на каждую ячейку латента приходится меньше
      одного исходного пикселя, доводка выродилась бы в чистую выдумку;
    * бокс годен — `(бокс, ok=True)`, плюс `upsample` и пометка
      `heavy_upsample`, если увеличение перевалило за `HEAVY_UPSAMPLE`.

    Бокс ГАРАНТИРОВАННО квадратный и ГАРАНТИРОВАННО внутри кадра — оба
    свойства проверяются тестом на всём диапазоне размеров лица, включая
    крайние. Если запас не помещается в кадр, уменьшается сторона, а не
    ломается квадратность: растянутый в 512x512 прямоугольник деформирует лицо,
    и это ровно та ошибка, которую проект уже ловил на условиях.
    """
    margin = UNION_MARGIN if margin is None else margin
    if margin < 0:
        raise ValueError(f"запас не может быть отрицательным: {margin}")
    width, height = int(size[0]), int(size[1])
    if width <= 0 or height <= 0:
        raise ValueError(f"размер кадра должен быть положительным: {size}")

    boxes = list(boxes)
    total = len(boxes)
    seen = []
    for b in boxes:
        if b is None:
            continue
        x0, y0, x1, y1 = (float(v) for v in b)
        if x1 <= x0 or y1 <= y0:
            raise ValueError(
                f"вырожденный бокс {b}: у детектора такого не бывает, значит "
                f"перепутан порядок координат — ждём (x0, y0, x1, y1)")
        seen.append((x0, y0, x1, y1))

    base = {"outcome": "", "frames": total, "with_face": len(seen),
            "coverage": round(len(seen) / total, 3) if total else 0.0,
            "face_px": None, "box_px": None, "upsample": None,
            "heavy_upsample": False, "low_coverage": False}
    if not seen:
        return None, {**base, "ok": None, "outcome": "no_faces",
                      "reason": (f"ни на одном из {total} кадров лица не нашли: "
                                 f"доводить НЕЧЕГО и НЕГДЕ. Это не «лицо "
                                 f"мелкое» — это «нечего измерять», и списывать "
                                 f"одно на другое нельзя")}

    ux0 = min(b[0] for b in seen)
    uy0 = min(b[1] for b in seen)
    ux1 = max(b[2] for b in seen)
    uy1 = max(b[3] for b in seen)
    face_px = round(min(ux1 - ux0, uy1 - uy0), 1)
    want = max(ux1 - ux0, uy1 - uy0) * (1.0 + 2.0 * margin)

    # Квадрат сохраняется ЦЕНОЙ СТОРОНЫ, а не ценой формы.
    side = int(round(min(want, width, height)))
    cx, cy = (ux0 + ux1) / 2.0, (uy0 + uy1) / 2.0
    x0 = min(max(int(round(cx - side / 2.0)), 0), width - side)
    y0 = min(max(int(round(cy - side / 2.0)), 0), height - side)
    box = (x0, y0, x0 + side, y0 + side)
    upsample = round(REFINE_SIDE / side, 2) if side else None

    from .identity_arcface import MIN_COVERAGE

    low = bool(total) and (len(seen) / total) < MIN_COVERAGE
    got = {**base, "face_px": face_px, "box_px": side, "upsample": upsample,
           "low_coverage": low}
    if side < MIN_CROP_PX:
        return None, {
            **got, "ok": False, "outcome": "too_small",
            "reason": (f"объединённый бокс вышел {side} px при поле "
                       f"{MIN_CROP_PX} px: в кропе меньше пикселей, чем ячеек в "
                       f"латенте {REFINE_SIDE // VAE_SCALE}x"
                       f"{REFINE_SIDE // VAE_SCALE}. Это была бы не доводка, а "
                       f"рисование лица с нуля в том месте, где оно случайно "
                       f"оказалось. Выход: кадрировать теснее или поднять "
                       f"высоту кадра")}
    heavy = upsample is not None and upsample >= HEAVY_UPSAMPLE
    reason = (f"лицо {face_px} px на {len(seen)}/{total} кадрах, фиксированный "
              f"бокс {side} px (запас {margin:.0%} на сторону), увеличение до "
              f"{REFINE_SIDE} px в {upsample}x")
    if heavy:
        reason += (f". Увеличение от {HEAVY_UPSAMPLE}x: на ячейку латента "
                   f"остаётся меньше 2x2 исходных пикселей, то есть лицо здесь "
                   f"скорее ПОРОЖДАЕТСЯ, чем доводится — так и говорить")
    if low:
        reason += (f". Лицо видели меньше чем на {MIN_COVERAGE:.0%} кадров: "
                   f"бокс построен по меньшинству, на остальных кадрах лицо "
                   f"могло уехать за его границы")
    return box, {**got, "ok": True, "outcome": "ok", "heavy_upsample": heavy,
                 "reason": reason}


def refine_plan(face_px: float | None, height: int, *,
                share: float | None = None, upscale: int | None = None,
                margin: float | None = None, side: int | None = None) -> dict:
    """Что даст доводка В ПИКСЕЛЯХ ЛИЦА и станет ли лицо судимым. До GPU-минут.

    Форма ответа намеренно повторяет `run_local.identity_forecast`
    (`label`/`ok`/`value`/`note`): решение о дорогом шаге принимается ДО его
    оплаты, и читается оно в одном ряду с прочими прогнозами прогона.

    `face_px` — ИЗМЕРЕННЫЙ размер лица в кадре первой ступени (короткая сторона
    бокса, как в `identity_arcface.face_detail`). `None` — не измерили: тогда
    считается прогноз по типовой доле, и `ok` возвращается `None`, потому что
    типовая доля уже один раз обещала 146 px там, где по факту было 59.

    `ok` трёхзначен:

    * `True` — после вклейки и апскейла лицо выходит на бар гейта;
    * `False` — не выходит (или доводить нечем: кроп ниже `MIN_CROP_PX`).
      Это ИЗМЕРЕННЫЙ отказ, и в примечании сказано, что его чинит;
    * `None` — размер лица не измерен; сказать заранее нечего.

    Обратите внимание, чего в ответе НЕТ: обещания, что ArcFace покажет
    маленькую дистанцию. Он её покажет, и это ничего не докажет — см. докстринг
    модуля. Прогноз здесь строго про РАЗРЕШЕНИЕ, то есть про то, будет ли гейту
    что судить, а не про то, каким будет вердикт.
    """
    upscale = UPSCALE_FACTOR if upscale is None else upscale
    margin = UNION_MARGIN if margin is None else margin
    side = REFINE_SIDE if side is None else side
    if upscale <= 0:
        raise ValueError(f"множитель апскейла должен быть положительным: {upscale}")
    if height <= 0:
        raise ValueError(f"высота кадра должна быть положительной: {height}")

    bar = _judge_bar()
    measured = face_px is not None
    if not measured:
        share = _full_body_share() if share is None else share
        face_px = share * height
    face_px = float(face_px)
    box_px = face_px * (1.0 + 2.0 * margin)
    upsample = round(side / box_px, 2) if box_px > 0 else None
    out_px = round(face_px * upscale, 1)
    row = {"label": "доводка лица", "ok": None, "value": out_px,
           "face_px_in": round(face_px, 1), "face_px_out": out_px,
           "box_px": round(box_px, 1), "upsample": upsample,
           "measured": measured, "bar": bar,
           "heavy_upsample": bool(upsample and upsample >= HEAVY_UPSAMPLE),
           "biased": True}

    honesty = ("Число ArcFace после доводки СМЕЩЕНО в оптимистичную сторону: "
               "лицо порождено под обусловливанием тем же эмбеддингом, которым "
               "его потом судят")
    if not measured:
        return {**row, "ok": None,
                "note": (f"размер лица НЕ ИЗМЕРЕН — взята типовая доля "
                         f"{share:g} от высоты {height}, это ~{face_px:.0f} px, "
                         f"и после апскейла x{upscale} было бы ~{out_px} px. "
                         f"Верить нельзя: типовая доля уже обещала 146 px там, "
                         f"где по условиям оказалось 59. Померить лицо на "
                         f"готовых кадрах и позвать заново. {honesty}")}
    if box_px < MIN_CROP_PX:
        return {**row, "ok": False,
                "note": (f"лицо {face_px:.0f} px даёт кроп {box_px:.0f} px при "
                         f"поле {MIN_CROP_PX} px — доводить нечем: в кропе "
                         f"меньше пикселей, чем ячеек в латенте. Апскейл из "
                         f"этого сделает крупную кашу, а не лицо. Выход: "
                         f"кадрировать теснее либо поднять высоту кадра")}
    if out_px >= bar:
        note = (f"лицо {face_px:.0f} px -> после вклейки и апскейла x{upscale} "
                f"~{out_px} px при баре {bar}: гейту будет что судить. Пикселей "
                f"добавляет АПСКЕЙЛ, а доводка добавляет содержимое — без неё "
                f"апскейлер увеличит кашу. Кроп {box_px:.0f} px растягивается в "
                f"{side} в {upsample}x")
        if row["heavy_upsample"]:
            note += (f"; увеличение от {HEAVY_UPSAMPLE}x — лицо скорее "
                     f"порождается, чем доводится")
        return {**row, "ok": True, "note": note + ". " + honesty}
    need_face = bar / upscale
    return {**row, "ok": False,
            "note": (f"лицо {face_px:.0f} px -> после апскейла x{upscale} только "
                     f"~{out_px} px, а бар {bar}: гейт вернёт «НЕ ПРОВЕРЕНО» и "
                     f"после доводки тоже. Нужно лицо от {need_face:.0f} px в "
                     f"кадре (теснее кадрировка или выше холст) либо апскейл "
                     f"x{bar / face_px:.1f}. Доводку при этом всё равно имеет "
                     f"смысл делать ради картинки, но ИЗМЕРИМОСТИ она не даст")}


