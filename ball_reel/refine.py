def vram_delta(width: int, height: int, *, side: int | None = None,
               frames: int | None = None) -> dict:
    """Сколько ДОБАВЛЯЕТ вторая ступень к пику видеопамяти. РАСЧЁТ, не замер.

    Веса не добавляются вовсе: пайплайн переиспользуется (`AnimateDiffVideoTo
    VideoPipeline.from_pipe`), UNet, VAE, текстовый энкодер и адаптер лица те же
    самые объекты. Значит расти могут только АКТИВАЦИИ, а они считаются по
    площади латента на число кадров: первая ступень — width x height, вторая —
    side x side.

    И вот главный вывод, ради которого функция написана: 512x512 МЕНЬШЕ, чем
    512x768, в полтора раза. Пик второй ступени не превышает пика первой, то
    есть добавляет она НОЛЬ — при условии, что кадры первой ступени успели
    освободиться. Если бы вывод был противоположным, ступень пришлось бы
    планировать отдельно; здесь достаточно не держать оба стека разом.

    ЧТО В ЭТОМ ЧИСЛЕ НЕПРАВДА, если читать его как замер. Отношение площадей —
    честная оценка ДЛЯ АКТИВАЦИЙ UNet, потому что они линейны по числу
    элементов латента. Но временное внимание модуля движения растёт как квадрат
    ЧИСЛА КАДРОВ (оно одинаково на обеих ступенях, 16, поэтому в отношение не
    входит), а пространственное — как квадрат площади латента на кадр, и там
    отношение было бы 0.44, а не 0.67. То есть 0.67 — оценка СВЕРХУ. Абсолютных
    гигабайт здесь нет и быть не может: коэффициент «гигабайт на ячейку
    латента» без замера на карте неизвестен, а выдумывать его — ровно то, за
    что в этом проекте правят метрики. Единственное абсолютное число, которое
    выводится честно, — размер самого латента, и он приведён как НИЖНЯЯ
    ГРАНИЦА, а не как ответ.

    ControlNet на второй ступени не используется, но его 0.72 ГБ с карты НЕ
    уходят: исходный пайплайн продолжает на него ссылаться. Экономия появится
    только если его освободить явно, и это отдельное решение вызывающего —
    вернуть его потом можно лишь повторной загрузкой.
    """
    from .animate import WEIGHTS_GB

    side = REFINE_SIDE if side is None else side
    frames = _context_frames() if frames is None else frames
    if min(width, height, side, frames) <= 0:
        raise ValueError("все размеры обязаны быть положительными: "
                         f"{width}x{height}, side={side}, frames={frames}")

    cells1 = (width // VAE_SCALE) * (height // VAE_SCALE) * frames
    cells2 = (side // VAE_SCALE) * (side // VAE_SCALE) * frames
    ratio = round(cells2 / cells1, 3) if cells1 else None
    # 4 канала латента, fp16 -> 2 байта. Нижняя граница, не ответ.
    latent_gb = round(cells2 * 4 * 2 / 1e9, 5)
    added = 0.0 if (ratio is not None and ratio <= 1.0) else None
    note = (f"РАСЧЁТ, не замер (карты в среде разработки нет). Веса те же "
            f"самые, пайплайн переиспользуется: +0 ГБ на весах из "
            f"{round(sum(WEIGHTS_GB.values()), 2)} ГБ. Активации второй ступени "
            f"составляют {ratio if ratio is not None else '?'} от первой "
            f"({side}x{side} против {width}x{height} на {frames} кадров), и это "
            f"оценка СВЕРХУ")
    if added == 0.0:
        note += (". Значит к пику она не добавляет ничего — при условии, что "
                 "кадры первой ступени освобождены до вызова второй")
    else:
        note += (". Вторая ступень ШИРЕ первой: пик вырастет, и планировать её "
                 "надо отдельно")
    note += (f". Абсолютных гигабайт активаций здесь нет: без замера на карте "
             f"коэффициент неизвестен. Сам латент занимает {latent_gb} ГБ — это "
             f"НИЖНЯЯ ГРАНИЦА, настоящий пик кратно больше. ControlNet "
             f"({WEIGHTS_GB['controlnet']} ГБ) на этой ступени не работает, но "
             f"с карты не уходит: на него ссылается исходный пайплайн")
    return {"stage1_latent_cells": cells1, "stage2_latent_cells": cells2,
            "activation_ratio": ratio, "latent_gb_lower_bound": latent_gb,
            "added_peak_gb": added, "added_weights_gb": 0.0,
            "controlnet_idle_gb": WEIGHTS_GB["controlnet"],
            "measured": False, "note": note}


