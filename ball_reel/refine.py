def refine_preflight(crops, *, face_embeds, denoise: float | None = None,
                     steps: int | None = None, side: int | None = None,
                     frames: int | None = None, pipe=None) -> dict:
    """Отказы ДО дорогого шага. Возвращает разбор, бросает ValueError на отказе.

    Всё, что здесь проверяется, стоит миллисекунду и НЕ ТРЕБУЕТ КАРТЫ, а без
    проверки обходится в GPU-минуты или, хуже, в успешно выглядящий мусор.
    Порядок — по стоимости отказа, как и в `animate.preflight`.

    Отдельно про два отказа, которые выглядят придирками:

    * `face_embeds is None`. Без эмбеддинга vid2vid не «оставит лицо как есть»,
      а нарисует лицо ПО ПРОМТУ — то есть постороннего человека, уверенно и
      без единой ошибки в логе. Канал личности на этой ступени единственный;
    * ControlNet на пайплайне. Он здесь снят по замыслу (скелет лица OpenPose
      не кодирует), и если он всё-таки на месте, значит `from_pipe` отдал не тот
      класс пайплайна — а пайплайн с ControlNet потребует условия, которых у
      нас нет, и упадёт уже после загрузки.
    """
    denoise = REFINE_DENOISE if denoise is None else denoise
    steps = REFINE_STEPS if steps is None else steps
    side = REFINE_SIDE if side is None else side
    window = _context_frames()
    frames = window if frames is None else frames

    crops = list(crops)
    if len(crops) != frames:
        raise ValueError(
            f"кропов {len(crops)}, а ступень требует {frames}. Стек обязателен: "
            f"по одному кадру vid2vid даёт мерцание, ради устранения которого "
            f"вся ступень и делается стеком. Окно модуля движения — {window}")
    for i, c in enumerate(crops):
        size = getattr(c, "size", None)
        if size is None:
            shape = getattr(c, "shape", None)
            size = (shape[1], shape[0]) if shape and len(shape) >= 2 else None
        if size is None:
            raise ValueError(f"кроп {i} — не картинка и не массив: {type(c)}")
        if tuple(size) != (side, side):
            raise ValueError(
                f"кроп {i} имеет размер {size[0]}x{size[1]}, а нужен квадрат "
                f"{side}x{side}: несквадратный кроп, растянутый в квадрат, "
                f"деформирует лицо")
    if face_embeds is None:
        raise ValueError(
            "нет эмбеддинга лица: IP-Adapter FaceID — единственный канал "
            "личности на этой ступени. Без него доводка нарисует лицо по "
            "промту, то есть ПОСТОРОННЕГО ЧЕЛОВЕКА, и сделает это молча")
    if not 0.0 < denoise <= 1.0:
        raise ValueError(f"denoise задаётся в (0, 1]: {denoise}")
    if denoise > REFINE_DENOISE_MAX:
        raise ValueError(
            f"denoise {denoise} выше потолка {REFINE_DENOISE_MAX}: это уже не "
            f"доводка, а перерисовка. Выше половины расписания уезжает контур "
            f"головы, и лицо перестаёт совпадать с телом, которое первая "
            f"ступень согласовала с ControlNet")
    if steps <= 0:
        raise ValueError(f"шагов должно быть больше нуля: {steps}")
    effective = int(steps * denoise)
    if effective < 1:
        raise ValueError(
            f"{steps} шагов при denoise {denoise} дают int({steps}*{denoise}) = "
            f"0 фактических шагов: diffusers вернёт вход НЕТРОНУТЫМ, и ступень "
            f"будет выглядеть отработавшей. Поднять шаги или denoise")
    if pipe is not None and getattr(pipe, "controlnet", None) is not None:
        raise ValueError(
            "на пайплайне остался ControlNet: на этой ступени он снят по "
            "замыслу (позу держит тело первой ступени, а лицо OpenPose не "
            "кодирует). Пайплайн с ControlNet потребует условий, которых нет")

    return {"frames": len(crops), "side": side, "denoise": denoise,
            "steps": steps, "effective_steps": effective,
            "note": (f"{len(crops)} кропов {side}x{side} одним стеком, denoise "
                     f"{denoise}, фактических шагов {effective} из {steps} "
                     f"(diffusers берёт int(steps*strength))"
                     + ("" if effective >= 4 else
                        f". ФАКТИЧЕСКИХ ШАГОВ {effective} — мало даже для "
                        f"доводки; поднять steps"))}


def refine_call_kwargs(crops, *, face_embeds, prompt: str, negative: str = "",
                       denoise: float | None = None, steps: int | None = None,
                       guidance: float = 7.5, side: int | None = None,
                       frames: int | None = None, seed: int = 0,
                       generator=None, pipe=None) -> dict:
    """Аргументы вызова vid2vid — отдельно от самого вызова, чтобы их проверить.

    Существует потому, что «код писался против несуществующего API» — это на
    этом проекте уже случившееся, а не гипотетическое. Здесь набор ключей
    отделён от исполнения, и тест сверяет КАЖДЫЙ ключ с настоящей сигнатурой
    `AnimateDiffVideoToVideoPipeline.__call__` из установленного diffusers.

    Сверено по исходнику diffusers 0.39.0:
    `pipelines/animatediff/pipeline_animatediff_video2video.py`. Отличия от
    первой ступени, которые легко проспать:

    * длину клипа задаёт ДЛИНА `video`, аргумента `num_frames` здесь НЕТ;
    * сила доводки называется `strength`, а не `denoise`/`noise`;
    * при `enforce_inference_steps=False` (умолчание) фактических шагов
      выходит `int(num_inference_steps * strength)` — это видно в `get_timesteps`
      и это тот случай, когда умолчание меняет смысл параметра;
    * `conditioning_frames` этот пайплайн НЕ ПРИНИМАЕТ — ControlNet-версия
      живёт в отдельном классе, и это ещё одна причина снять ControlNet, а не
      «просто не передавать условия».
    """
    got = refine_preflight(crops, face_embeds=face_embeds, denoise=denoise,
                           steps=steps, side=side, frames=frames, pipe=pipe)
    if generator is None:
        try:
            import torch

            generator = torch.Generator("cpu").manual_seed(seed)
        except ImportError:                       # torch может не стоять офлайн
            generator = None
    return {"video": list(crops), "prompt": prompt,
            "negative_prompt": negative or None,
            "width": got["side"], "height": got["side"],
            "strength": got["denoise"],
            "num_inference_steps": got["steps"],
            "guidance_scale": guidance,
            "ip_adapter_image_embeds": [face_embeds],
            "generator": generator,
            "output_type": "pil"}


def refine(pipe, crops, *, face_embeds, prompt: str, negative: str = "",
           denoise: float | None = None, steps: int | None = None,
           guidance: float = 7.5, ip_adapter_scale: float = 0.8,
           side: int | None = None, frames: int | None = None, seed: int = 0):
    """Стек кропов -> стек доведённых кропов. Тонкая обёртка над vid2vid.

    Тонкая намеренно: всё, что можно проверить без карты, вынесено в
    `refine_preflight` и `refine_call_kwargs`, а здесь остаётся ровно вызов.
    Без карты эта функция не исполняется — но её предполёт и разбор аргументов
    исполняются и проверены тестами, включая сверку ключей с настоящей
    сигнатурой пайплайна.

    `ip_adapter_scale` здесь выше, чем на первой ступени (0.8 против 0.7):
    там адаптер конкурировал с ControlNet за влияние на UNet, здесь конкурента
    нет, а лицо — единственное, ради чего ступень запущена. Число ВЫБРАНО, на
    карте не проверено.
    """
    kwargs = refine_call_kwargs(
        crops, face_embeds=face_embeds, prompt=prompt, negative=negative,
        denoise=denoise, steps=steps, guidance=guidance, side=side,
        frames=frames, seed=seed, pipe=pipe)
    set_scale = getattr(pipe, "set_ip_adapter_scale", None)
    if set_scale is not None:
        set_scale(ip_adapter_scale)
    out = pipe(**kwargs)
    return out.frames[0]


def build_refiner(pipe):
    """Тот же пайплайн, переставленный на vid2vid. Веса не перезагружаются.

    `from_pipe` берёт УЖЕ ЗАГРУЖЕННЫЕ компоненты: UNet с прицепленным
    IP-Adapter и его LoRA остаётся тем же объектом, поэтому канал личности
    переезжает сам. ControlNet в число ожидаемых компонентов vid2vid-класса не
    входит и в новый пайплайн не попадает — то самое «ControlNet снят».

    НЕ ПРОВЕРЕНО НА КАРТЕ. Проверено по исходнику установленного diffusers
    0.39.0: `DiffusionPipeline.from_pipe` существует и собирает целевой класс
    из компонентов исходного. Но переживёт ли переезд ИМЕННО состояние
    IP-Adapter FaceID — утверждение про рантайм, и подтвердить его может только
    прогон: после переезда обязательно позвать `animate.active_loras(new)` и
    убедиться, что `faceid_*` на месте. Если её там нет — канал личности
    отключён, а выглядеть это будет как «доводка испортила лицо».
    """
    from diffusers import AnimateDiffVideoToVideoPipeline

    return AnimateDiffVideoToVideoPipeline.from_pipe(pipe)
