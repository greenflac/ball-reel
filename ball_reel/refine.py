"""Вторая ступень: доводка ЛИЦА поверх готовой полноростовой раскадровки.

ЗАЧЕМ ОНА ЕСТЬ. Кадрировка `full_body` фиксирована владельцем продукта:
движение тела важнее крупного лица, кадр «по пояс» ОТВЕРГНУТ. Но на 512x768
лицо занимает десятую часть высоты — семь-восемь десятков пикселей, — а
`identity_arcface.MIN_FACE_PX` = 100. То есть гейт личности на таком клипе
вернёт «НЕ ПРОВЕРЕНО», и это не придирка измерителя: лицо в 78 px и глазом
выглядит кашей, а «годный контент» — критерий приёмки демо.

ЧЕСТНОСТЬ, КОТОРУЮ НЕЛЬЗЯ ПРЯТАТЬ В КОММЕНТАРИЙ

Эта ступень НЕ ВОССТАНАВЛИВАЕТ лицо из 78 px. Восстанавливать там нечего:
кроп увеличивается в три-пять раз, и всё, чего в исходных пикселях не было,
модель ПОРОЖДАЕТ заново — обусловившись эмбеддингом с фото личности через
IP-Adapter FaceID. Отсюда прямое следствие, и оно неприятное:

* после доводки ArcFace станет ИЗМЕРИМЫМ — лицо перестанет быть кашей, и
  детектор с распознавателем получат, что им нужно;
* но полученное число СМЕЩЕНО В ОПТИМИСТИЧНУЮ СТОРОНУ, потому что мы
  обусловливаем ровно той величиной, которой судим. Судья зависит от
  судимого. Это тот же конфликт, ради разрыва которого в проекте затевается
  LoRA, и доводка его не разрывает, а усиливает.

ЧЕГО ДОВОДКА НЕ ДОКАЗЫВАЕТ, и это надо произносить вслух рядом с числом:

1. что базовая генерация умеет держать личность. Она её не держала — лицо
   пришло из второго прохода, обусловленного фотографией;
2. что низкая косинусная дистанция после доводки — свидетельство сходства с
   человеком. Она свидетельствует о том, что IP-Adapter отработал: эмбеддинг
   на входе и эмбеддинг на выходе считает одна и та же модель ArcFace;
3. что лицо на видео — то же самое лицо, что на старт-кадре первой ступени.
   Оно другое: доводка его перерисовала;
4. что зритель узнает человека. Это отдельный вопрос, и на него отвечает
   человек, а не косинус.

Что доводка ДОКАЗЫВАЕТ: что на выходе есть лицо разрешения, достаточного для
любого измерителя, и что оно согласовано с телом и позой первой ступени.
Честный протокол на демо — показывать число ArcFace ВМЕСТЕ с пометкой, что
клип прошёл доводку с обусловливанием тем же эмбеддингом; отдельная,
не смещённая проверка личности — это LoRA-ветка, а не эта.

АРХИТЕКТУРА (решена до кода, здесь только реализована)

1. ОДИН ФИКСИРОВАННЫЙ БОКС на всю последовательность (`union_box`), а не
   покадровый. Покадровый бокс дёргается вслед за детектором, и модуль
   движения AnimateDiff начинает бороться с дрожью субъекта вместо того,
   чтобы держать временную связность. Фиксированный бокс превращает кропы в
   стабильную «камеру», внутри которой лицо двигается само.
2. Кропы масштабируются в КВАДРАТ стороной `REFINE_SIDE` и идут ОДНИМ СТЕКОМ
   из 16 кадров через vid2vid. По одному кадру — мерцание; это главная
   причина, по которой стек обязателен, и `refine` отказывается работать с
   числом кадров, отличным от окна модуля движения.
   Квадрат — не эстетика: несквадратный кроп, растянутый в 512x512,
   деформирует лицо. На этом проекте такая ошибка уже ловилась — landscape-
   кадр на portrait-холст растянул фигуру в 2.7 раза.
3. ControlNet на этой ступени СНЯТ: поза уже зафиксирована телом первой
   ступени, а скелет лица OpenPose не кодирует — подавать его сюда значит
   тратить память на условие, которое ничего не обусловливает. IP-Adapter
   FaceID остаётся: он и есть канал личности, и без него доводка нарисует
   постороннего человека (см. отказ в `refine_preflight`).
4. Низкий denoise: доводим, а не перерисовываем. Высокий уводит лицо от того,
   что уже согласовано с телом, — см. `REFINE_DENOISE_MAX`.
5. Вклейка обратно по мягкой маске (`feather_mask`, `paste_back`), затем кадр
   апскейлится x2 — это НЕ этот модуль, апскейл живёт в `upscale.py`.
   Отсюда интерфейс: `refine` возвращает кадры ТОГО ЖЕ размера, что получил,
   и ничего не знает про апскейлер; `refine_plan` умеет посчитать, что будет
   после апскейла, но множитель принимает аргументом, а не выдумывает.

ПОЧЕМУ ЭТО ВООБЩЕ ПОМОГАЕТ, ЕСЛИ ПИКСЕЛЕЙ НЕ ПРИБАВЛЯЕТСЯ

Доводка не меняет РАЗМЕР лица в кадре: вклейка возвращает патч ровно в тот же
бокс. Пиксели лицу добавляет апскейл (x2: 78 -> 156, выше бара 100). Доводка
меняет СОДЕРЖИМОЕ этих пикселей: без неё апскейлер увеличит кашу и получится
крупная каша, на которой детектор либо не найдёт лица, либо найдёт и выдаст
дистанцию, надутую мелким кропом (`identity_arcface.MIN_FACE_PX` ровно про
это). Порядок обязателен: сначала доводка, потом апскейл.

РАСХОЖДЕНИЕ В ДОЛЕ ЛИЦА — НАЗЫВАЕМ ОБА ЧИСЛА, А НЕ ВЫБИРАЕМ ТИХО

* `animate.FULL_BODY_FACE_SHARE` = 0.094 — «замерено на живом клипе 1080x1920:
  лицо 181 px» (`gpu_keyframes`, тот же комментарий). На высоте 768 это 72 px;
* постановка задачи на эту ступень говорит «0.102, то есть 78 px на 768»;
* 78 px как замер в репозитории есть, но он с ДРУГОГО холста: `gpu_keyframes`
  пишет «на 464x832 лицо вышло 78 px», а 78/832 = 0.0938 — то есть та же
  доля 0.094, а не 0.102. Похоже, 0.102 получена делением 78 px на 768;
* самое мелкое ИЗМЕРЕННОЕ по реальным условиям — 0.074 (широкая стойка
  растягивает габарит, см. `run_local.identity_forecast`), это 57 px на 768.

Здесь не выбирается ни одно из трёх: доля не копируется в этот модуль вовсе,
а импортируется из `animate`, и `refine_plan` принимает измеренное число
аргументом. Вывод при этом устойчив ко всем трём: 57, 72 и 78 px после
апскейла x2 дают 114, 144 и 156 px — все выше бара 100. Ступень оправдана и
по самому пессимистичному замеру.

ЧТО ЗДЕСЬ ИЗМЕРЯЕТСЯ, А ЧТО СЧИТАЕТСЯ. Всё про память — РАСЧЁТ, не замер:
карты в среде разработки нет (`vram_delta` повторяет эту пометку в своём
ответе, чтобы её нельзя было потерять при копировании числа в отчёт).
Геометрия — арифметика, она проверяема тестом целиком.
"""

from __future__ import annotations

#: Сторона квадратного кропа, который уходит в vid2vid. ВЫБРАНА: 512 — то
#: разрешение, на котором обучена SD1.5 и на котором работает первая ступень,
#: то есть UNet видит привычный масштаб деталей. Больше не имеет смысла:
#: исходных пикселей в кропе всё равно меньше, а активации растут.
REFINE_SIDE = 512

#: Во сколько раз VAE сжимает сторону. ИЗМЕРЕНО по конфигу SD1.5 VAE: три
#: понижающих блока, 2**3 = 8. Отсюда и латент 64x64 при стороне 512, и все
#: пороги «сколько исходных пикселей приходится на ячейку латента» ниже.
VAE_SCALE = 8

#: Ниже этой стороны кроп доводить нечем: при стороне 64 на каждую ячейку
#: латента 64x64 приходится один исходный пиксель, и «доводка» становится
#: генерацией из ничего. ВЫБРАН, опорный факт — VAE_SCALE и REFINE_SIDE:
#: REFINE_SIDE // VAE_SCALE и есть сторона латента.
MIN_CROP_PX = REFINE_SIDE // VAE_SCALE

#: Увеличение, начиная с которого ступень честнее называть порождением, чем
#: доводкой. ВЫБРАН, опорный факт тот же: при увеличении 4 на ячейку латента
#: приходится 2x2 = 4 исходных пикселя, при 8 — один. Не отказ, а пометка:
#: порождение бывает единственным доступным вариантом, но называть его
#: доводкой нельзя.
HEAVY_UPSAMPLE = 4.0

#: Запас вокруг объединённого бокса лица, в долях его стороны на каждую
#: сторону. ВЫБРАН = 0.25 (голова) + 0.09 (кольцо пера), опорные факты:
#:  * детектор отдаёт рамку ЛИЦА, а не головы: волосы, подбородок и шея
#:    остаются снаружи, и кроп по самой рамке заставляет модель дорисовывать
#:    линию волос прямо на шве вклейки. Полная голова примерно в 1.5 раза
#:    выше рамки лица — это и есть 0.25 на сторону;
#:  * внешнее кольцо кропа шириной FEATHER/2 от стороны частично прозрачно
#:    после вклейки (см. `feather_mask`), и лицу в этом кольце делать нечего.
#: Дрожь лица между кадрами этим запасом НЕ покрывается — её покрывает само
#: объединение боксов по всем кадрам.
UNION_MARGIN = 0.35


