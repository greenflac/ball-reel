def feather_mask(box, side: int, *, falloff: float | None = None):
    """Мягкая маска вклейки для квадратного бокса, растеризованная в side x side.

    Жёсткий край читается как наклейка мгновенно, даже когда цвет подобран
    идеально (то же наблюдение, что и в `marks`, оттуда же и ширина края).
    Поэтому маска равна 1 в середине, 0 РОВНО НА КРАЮ и меняется плавно между —
    на краю ноль означает, что вклейка не выходит за бокс ни на пиксель: за его
    пределами кадр остаётся исходным по построению.

    `box` не декоративен: из него берётся форма, и НЕквадратный бокс здесь
    отвергается. Растеризовать квадратную маску на прямоугольный бокс значит
    вклеить лицо со сдвигом относительно того, где оно нарисовано.
    """
    import numpy as np

    falloff = FEATHER if falloff is None else falloff
    if not 0.0 <= falloff <= 1.0:
        raise ValueError(f"перо задаётся долей стороны, 0..1: {falloff}")
    x0, y0, x1, y1 = (int(round(float(v))) for v in box)
    bw, bh = x1 - x0, y1 - y0
    if bw <= 0 or bh <= 0:
        raise ValueError(f"вырожденный бокс {box}")
    if bw != bh:
        raise ValueError(
            f"бокс {bw}x{bh} не квадратный: маска стороной {side} легла бы со "
            f"сдвигом относительно патча. Приводить к квадрату должен "
            f"union_box, а не эта функция")
    if side <= 0:
        raise ValueError(f"сторона маски должна быть положительной: {side}")

    # Расстояние до ближайшего края в долях полустороны: 0 на краю, 1 в центре.
    t = (np.arange(side, dtype="float64") + 0.5) / side      # 0..1 по стороне
    edge = np.minimum(t, 1.0 - t) * 2.0                      # 0 на краях, 1 в центре
    if falloff <= 0:
        # Ноль — это ЖЁСТКИЙ край, и он остаётся доступным намеренно: маска
        # тогда честно единица везде, кроме самой рамки. Полезно как контроль
        # («видно ли шов»), но по умолчанию так не вклеивают.
        prof = (edge > 0).astype("float64")
    else:
        prof = np.clip(edge / falloff, 0.0, 1.0)
    mask = np.minimum(prof[:, None], prof[None, :])
    # Рамка строго нулевая: «маска не выходит за бокс» должно быть проверяемо
    # утверждением, а не рассуждением о том, как ведёт себя clip.
    mask[0, :] = mask[-1, :] = mask[:, 0] = mask[:, -1] = 0.0
    return mask


def paste_back(frame, patch, box, mask):
    """Кадр + патч лица -> кадр с вклеенным лицом. Возвращает КОПИЮ.

    Чистая арифметика над numpy: ни PIL, ни весов, ни карты. Всё, что могло
    сломаться в геометрии, ломается здесь громко (несовпадение форм — это
    ValueError с обоими числами), а не тихо сдвигом на несколько пикселей,
    который на 16 кадрах читается как дрожь.

    Тип кадра сохраняется: uint8 на входе — uint8 на выходе. Смешение считается
    в float, иначе округление на каждом кадре складывается в полосу на шве.
    """
    import numpy as np

    frame = np.asarray(frame)
    patch = np.asarray(patch)
    mask = np.asarray(mask, dtype="float64")
    if frame.ndim < 2:
        raise ValueError(f"кадр должен быть двумерным как минимум: {frame.shape}")
    h, w = frame.shape[:2]
    x0, y0, x1, y1 = (int(round(float(v))) for v in box)
    if x0 < 0 or y0 < 0 or x1 > w or y1 > h:
        raise ValueError(
            f"бокс {(x0, y0, x1, y1)} выходит за кадр {w}x{h}: обрезать его "
            f"здесь значило бы вклеить лицо не туда, куда его нарисовали")
    bh, bw = y1 - y0, x1 - x0
    if patch.shape[:2] != (bh, bw):
        raise ValueError(
            f"патч {patch.shape[1]}x{patch.shape[0]} не совпал с боксом "
            f"{bw}x{bh}: масштабировать патч должен вызывающий, осознанно")
    if mask.shape[:2] != (bh, bw):
        raise ValueError(
            f"маска {mask.shape[1]}x{mask.shape[0]} не совпала с боксом "
            f"{bw}x{bh}")
    if mask.min() < 0.0 or mask.max() > 1.0:
        raise ValueError("маска обязана лежать в 0..1")

    out = frame.copy()
    alpha = mask[..., None] if frame.ndim == 3 else mask
    region = out[y0:y1, x0:x1].astype("float64")
    blended = region * (1.0 - alpha) + patch.astype("float64") * alpha
    if np.issubdtype(out.dtype, np.integer):
        info = np.iinfo(out.dtype)
        blended = np.clip(np.round(blended), info.min, info.max)
    out[y0:y1, x0:x1] = blended.astype(out.dtype)
    return out


def crop_series(frames, box, *, side: int | None = None) -> list:
    """Кадры + фиксированный бокс -> список квадратных кропов стороной `side`.

    Бокс ОДИН на всю последовательность — в этом весь смысл ступени: кропы
    получаются стабильной «камерой», внутри которой лицо двигается само, и
    модуль движения занимается временной связностью, а не борьбой с дрожью
    детектора.
    """
    from PIL import Image

    side = REFINE_SIDE if side is None else side
    x0, y0, x1, y1 = (int(round(float(v))) for v in box)
    if x1 - x0 != y1 - y0:
        raise ValueError(
            f"бокс {x1 - x0}x{y1 - y0} не квадратный: масштабирование в "
            f"{side}x{side} деформировало бы лицо (эта ошибка на проекте уже "
            f"растягивала фигуру в 2.7 раза)")
    out = []
    for f in frames:
        im = f if hasattr(f, "crop") else Image.fromarray(f)
        out.append(im.crop((x0, y0, x1, y1)).resize((side, side),
                                                    Image.LANCZOS))
    return out


def paste_series(frames, patches, box, *, falloff: float | None = None) -> list:
    """Вклеить доведённые кропы обратно во все кадры. Возвращает новые кадры.

    Маска строится ОДИН раз на всю последовательность — ровно потому же, почему
    один раз строится бокс: меняющаяся от кадра к кадру граница вклейки читается
    как мерцание по контуру лица.
    """
    import numpy as np
    from PIL import Image

    frames, patches = list(frames), list(patches)
    if len(frames) != len(patches):
        raise ValueError(f"кадров {len(frames)}, патчей {len(patches)}")
    x0, y0, x1, y1 = (int(round(float(v))) for v in box)
    side = x1 - x0
    mask = feather_mask((x0, y0, x1, y1), side, falloff=falloff)
    out = []
    for frame, patch in zip(frames, patches):
        pil_in = hasattr(frame, "crop")
        pim = patch if hasattr(patch, "resize") else Image.fromarray(
            np.asarray(patch))
        if pim.size != (side, side):
            pim = pim.resize((side, side), Image.LANCZOS)
        got = paste_back(np.asarray(frame), np.asarray(pim),
                         (x0, y0, x1, y1), mask)
        out.append(Image.fromarray(got) if pil_in else got)
    return out


