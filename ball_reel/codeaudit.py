def _mutate_source(text: str, name: str, value) -> str:
    """Подменить объявление константы В ИСХОДНИКЕ.

    Именно в исходнике, а не через setattr на импортированном модуле. Половина
    порогов здесь используется как значение по умолчанию (`max_wobble: float =
    LIMB_WOBBLE_MAX`), а такие связываются один раз в момент определения
    функции — подмена атрибута модуля после импорта на них не действует.
    Харнесс, который этого не учитывает, объявляет мутанта выжившим там, где на
    самом деле он до кода не доехал, и посылает искать несуществующую дыру
    в тестах. Проверено на LIMB_WOBBLE_MAX.
    """
    import re

    pattern = re.compile(rf"^{re.escape(name)}\s*(:[^=\n]+)?=.*$", re.MULTILINE)
    if not pattern.search(text):
        return ""
    return pattern.sub(f"{name} = {value!r}", text, count=1)


def _skipped(stderr: str) -> int:
    """Сколько тестов пропущено, по итоговой строке unittest.

    ИЩЕТ С КОНЦА, а не берёт последнюю строку, и это не придирка. Итог unittest
    (`OK (skipped=4)`) — НЕ последнее, что попадает в stderr: после него
    печатают свои сообщения mediapipe, absl и TensorFlow Lite, а в одном из
    прогонов ещё и traceback из `PoseLandmarker.__del__` при сборке мусора.

    Чем это стоило: аудит читал у ДЕРЕВА ноль пропусков (итог был не последней
    строкой) и четыре у КОПИИ (там хвост оказался другим), объявлял копию
    слабее дерева и ОСТАНАВЛИВАЛСЯ — то есть полный мутационный прогон не
    доходил до мутаций вообще. Самопроверка, ложно срабатывающая, выключает
    аудит так же надёжно, как сломанная.
    """
    for line in reversed((stderr or "").strip().splitlines()):
        s = line.strip()
        if not (s.startswith("OK") or s.startswith("FAILED")):
            continue
        if "skipped=" not in s:
            return 0          # итог найден, пропусков в нём нет
        try:
            return int(s.split("skipped=")[1].split(")")[0].split(",")[0])
        except (ValueError, IndexError):
            return 0
    return 0


def run_tests() -> tuple:
    """-> (всё зелено, строка «Ran N tests», сколько пропущено).

    Число пропусков возвращается НЕ для отчёта: им пользуется
    `copy_is_as_strong_as_the_tree`, и без него самопроверка гоняла бы весь
    набор ВТОРОЙ раз только чтобы узнать то, что здесь уже посчитано. На 1074
    тестах это лишние три минуты в прогоне, который и так упирался в свой
    таймаут.
    """
    r = subprocess.run([sys.executable, "-m", "unittest", "discover",
                        "-s", "ball_reel/tests", "-p", "test_*.py"],
                       capture_output=True, text=True)
    tail = (r.stderr or "").strip().splitlines()
    count = next((ln for ln in tail if ln.startswith("Ran ")), "?")
    return r.returncode == 0, count, _skipped(r.stderr)


def run_coverage() -> tuple:
    """Покрытие по несущим модулям. Возвращает (ok, {модуль: процент})."""
    dev = subprocess.DEVNULL
    subprocess.run([sys.executable, "-m", "coverage", "run",
                    "--source=ball_reel", "--omit=*/tests/*",
                    "-m", "unittest", "discover", "-s", "ball_reel/tests",
                    "-p", "test_*.py"], stdout=dev, stderr=dev)
    r = subprocess.run([sys.executable, "-m", "coverage", "report",
                        "--skip-empty"], capture_output=True, text=True)
    per: dict = {}
    for line in r.stdout.splitlines():
        parts = line.split()
        if len(parts) >= 4 and parts[-1].endswith("%"):
            name = Path(parts[0]).stem
            if name in CORE_MODULES:
                per[name] = int(parts[-1].rstrip("%"))
    low = {k: v for k, v in per.items() if v < MIN_CORE_COVERAGE}
    return (not low), per


#: Что линкуется в копию пакета рядом с ним. Пакет копируется, а ДАННЫЕ лежат
#: в корне репозитория, и без них тесты, работающие на настоящих кадрах, молча
#: пропускаются — то есть во время каждой мутации не сторожат ничего.
#: ИЗМЕРЕНО: копия пропускала 8 тестов против 1 в дереве. Семь замолчавших — это
#: ровно те, что бегут по живым данным (`kit/driving`, `marktest_ref.png`), то
#: есть самые ценные. Мутация, которую сторожил только такой тест, объявлялась
#: ВЫЖИВШЕЙ, и на её поиск уходило время.
DATA_LINKS = ("kit", "demo", "evidence", "marktest")

#: Проверки, которые в копии для мутаций НЕ МОГУТ работать по устройству, а не
#: из-за недостающих данных. Список закрытый и требует объяснения: попасть сюда
#: — это заявление «мутация этот тест не затрагивает», и оно должно стоить
#: осознанной строки, а не быть способом заглушить самопроверку.
#:
#: Разница существенная. Обычный лишний пропуск в копии означает, что сторож
#: молчит во время каждой мутации, — это дефект, и чинится он данными. А эти
#: проверяют не поведение кода, а СОСТАВ РЕПОЗИТОРИЯ, и в копии, где нет
#: индекса git, проверять им нечего ни при какой мутации.
TREE_ONLY_SKIPS = {
    "both_kits_are_whole_in_the_git_index":
        "читает индекс git: в копии индекса нет по устройству, а сам дефект "
        "(файл на диске есть, в индексе нет) мутацией не порождается",
}


def _stage_copy(tmp: Path) -> Path:
    """Копия пакета плюс ссылки на данные. Возвращает путь к копии пакета."""
    import shutil

    dst = tmp / "ball_reel"
    shutil.copytree("ball_reel", dst,
                    ignore=shutil.ignore_patterns("__pycache__", "fixtures"))
    # fixtures нужны офлайн-тестам, но копировать их дорого — линкуем.
    (dst / "fixtures").symlink_to(Path("ball_reel/fixtures").resolve())
    for name in DATA_LINKS:
        src = Path(name)
        if src.exists():
            (tmp / name).symlink_to(src.resolve())
    # Корневые картинки эксперимента с приметами лежат россыпью, а не в папке.
    for png in Path(".").glob("*.png"):
        (tmp / png.name).symlink_to(png.resolve())
    return dst


def copy_is_as_strong_as_the_tree(here: int | None = None) -> tuple:
    """Молчит ли в копии то, что в дереве говорит. -> (одинаково, примечание).

    САМОПРОВЕРКА АУДИТА, и она обязательна. Мутации гоняются не в рабочем
    дереве, а в копии, и всё, чего в копии не хватает, превращает тест в
    пропуск. Пропущенный тест убить мутанта не может — значит аудит тихо
    слабеет, продолжая печатать «покрытие 100%».

    Направление ошибки безопасное (лишние ВЫЖИВШИЕ, а не лишние убитые), но
    цена всё равно есть: время на разбор мнимого выжившего и завышенное
    представление о том, что именно сторожат тесты.
    """
    import tempfile

    def count(cwd):
        r = subprocess.run(
            [sys.executable, "-m", "unittest", "discover",
             "-s", "ball_reel/tests", "-p", "test_*.py"],
            cwd=cwd, capture_output=True, text=True)
        return _skipped(r.stderr)

    # Число по дереву передаётся снаружи, если его уже посчитал `run_tests`:
    # гонять весь набор второй раз ради одного числа — три минуты на пустом
    # месте в прогоне, который и так упирался в таймаут.
    here = count(None) if here is None else here
    with tempfile.TemporaryDirectory() as tmp:
        _stage_copy(Path(tmp))
        there = count(tmp) - len(TREE_ONLY_SKIPS)
    if there <= here:
        return True, f"в копии пропущено {there}, в дереве {here} — не слабее"
    return False, (
        f"в копии пропущено {there} тестов против {here} в дереве: "
        f"{there - here} сторож(а) молчат во время КАЖДОЙ мутации. Обычная "
        f"причина — данные, лежащие в корне репозитория и не попавшие в копию; "
        f"добавить их имя в DATA_LINKS. Если же проверка НЕ МОЖЕТ работать в "
        f"копии по устройству (читает индекс git, требует сети) — её место в "
        f"TREE_ONLY_SKIPS, с объяснением, почему мутация её не затрагивает")


def run_mutation(module: str, name: str, value) -> tuple:
    """Прогнать тесты на копии пакета с испорченной константой.

    Возвращает (убит, примечание). «Убит» = хотя бы один тест покраснел, то
    есть порог действительно кем-то сторожится.

    `-f` (failfast) — не оптимизация ради оптимизации, а условие того, что
    аудит вообще запускают. ИЗМЕРЕНО: убитый мутант с полным прогоном стоит
    16.2 с, с failfast — 0.3 с. Информации при этом не теряется НИСКОЛЬКО:
    «убит» означает «покраснел хотя бы один тест», и первого достаточно.
    Полную цену платят только ВЫЖИВШИЕ мутанты — то есть ровно те, ради
    которых аудит и существует.

    Без этого 88 мутаций по 921 тесту не влезали в собственный таймаут: прогон
    требовал от часа до двух с половиной, и аудит переставали запускать. Аудит,
    который не запускают, не сторожит ничего.
    """
    import tempfile

    rel = Path(module.replace(".", "/") + ".py")
    if not rel.exists():
        return False, f"нет файла {rel}"
    with tempfile.TemporaryDirectory() as tmp:
        _stage_copy(Path(tmp))
        target = Path(tmp) / rel
        mutated = _mutate_source(target.read_text(), name, value)
        if not mutated:
            return False, f"объявление {name} не найдено в {rel}"
        target.write_text(mutated)
        r = subprocess.run(
            [sys.executable, "-m", "unittest", "discover",
             "-s", "ball_reel/tests", "-p", "test_*.py", "-f"],
            cwd=tmp, capture_output=True, text=True)
        return r.returncode != 0, ""


def main(argv: list) -> int:
    import argparse

    ap = argparse.ArgumentParser(
        prog="ball_reel.codeaudit",
        description="тесты + покрытие + мутационная проверка порогов")
    ap.add_argument("--quick", action="store_true", help="без мутаций")
    args = ap.parse_args(argv)

    print("=" * 72)
    ok_tests, count, skipped_here = run_tests()
    print(f"{'PASS' if ok_tests else 'FAIL'}  тесты          {count}")
    if not ok_tests:
        print("\nОСТАНОВЛЕНО: аудит на красных тестах бессмысленен.")
        return 1

    ok_cov, per = run_coverage()
    worst = sorted(per.items(), key=lambda kv: kv[1])
    detail = ", ".join(f"{k} {v}%" for k, v in worst[:4])
    print(f"{'PASS' if ok_cov else 'FAIL'}  покрытие ядра  "
          f"порог {MIN_CORE_COVERAGE}%; худшие: {detail}")

    if args.quick:
        print("=" * 72)
        print("мутации пропущены (--quick)")
        return 0 if (ok_tests and ok_cov) else 1

    print("-" * 72)
    # САМОПРОВЕРКА ДО МУТАЦИЙ. Мутации гоняются в копии пакета, и всё, чего в
    # копии не хватает, превращает тест в пропуск — а пропущенный тест мутанта
    # не убьёт. Спрашивать об этом надо ДО часа работы, а не после.
    same, why = copy_is_as_strong_as_the_tree(skipped_here)
    print(f"{'PASS' if same else 'FAIL'}  копия для мутаций  {why}")
    if not same:
        print("\nОСТАНОВЛЕНО: аудит слабее собственного дерева, и его числа "
              "завышают то, что на самом деле сторожат тесты.")
        return 1

    print("мутации: ломаем порог — тесты ОБЯЗАНЫ покраснеть")
    survived = []
    for module, name, value, meaning in MUTATIONS:
        killed, note = run_mutation(module, name, value)
        short = f"{module.split('.')[-1]}.{name}"
        print(f"  {'убита ' if killed else 'ВЫЖИЛА'}  {short:<38} "
              f"{note or meaning}")
        if not killed:
            survived.append((short, note or meaning))

    print("=" * 72)
    rate = (len(MUTATIONS) - len(survived)) / len(MUTATIONS)
    print(f"мутационное покрытие: {rate:.0%} "
          f"({len(MUTATIONS) - len(survived)}/{len(MUTATIONS)})")
    if survived:
        print("\nВЫЖИВШИЕ — здесь мы думаем, что защищены, но это не так:")
        for short, meaning in survived:
            print(f"  {short}: {meaning}")
        print("\nЭто не обязательно баг кода. Это либо недостающий тест, либо "
              "порог, который никуда не подключён. Разбирать поштучно.")
    ok = ok_tests and ok_cov and not survived
    print(f"\n{'АУДИТ ПРОЙДЕН' if ok else 'АУДИТ НЕ ПРОЙДЕН'}")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
