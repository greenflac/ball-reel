def default_seamless_paths(root=".") -> list:
    """Пути из `SEAMLESS_SOURCES`, прорежённые: соседние кадры почти совпадают."""
    from pathlib import Path

    root = Path(root)
    out = []
    for pat in SEAMLESS_SOURCES:
        found = sorted(root.glob(pat))
        out.extend(found[::12] if len(found) > 24 else found[::6] if len(found) > 6
                   else found)
    return out


