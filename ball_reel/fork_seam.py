    if not paths:
        print("не смогли: кадров не найдено — запускать из корня репозитория")
        return 2
    got = seamless_cloud(paths)
    print(f"кадров {len(paths)}, {got['note']}")
    return 0 if got["outcome"] == PASS else 2


