"""Шовная ось форка: ВНУТРИ маски против СНАРУЖИ, на ОДНОМ кадре.

ЗАЧЕМ. Без неё гипотеза о LoRA темплейта неопровержима: «тело стало другим» и
«тело стало выглядеть вклеенным» — разные исходы, и различить их общим
впечатлением нельзя. В режиме Mix внутри маски пиксели порождены моделью, а
снаружи скопированы из драйвинга; если порождённое отличается по фактуре, шов
виден, и никакая правильность формы этого не искупает.

ПОЧЕМУ ИМЕННО НА ОДНОМ КАДРЕ, И ЭТО ГЛАВНОЕ РЕШЕНИЕ МОДУЛЯ. Сравнение
«наш кадр против кадра драйвинга» имеет три посторонних объяснения сразу: другой
свет, другое сжатие, другой момент движения. Сравнение внутри и снаружи ОДНОГО
кадра снимает все три разом — свет тот же, кодек тот же, момент тот же.
Остаётся ровно то, что мы хотим мерить: отличается ли порождённое от
скопированного.

`style.py` НЕ ИСПОЛЬЗУЕТСЯ — ни исполнителем, ни прибором. Решение владельца,
основание проверено: у того модуля ось `detail` срабатывает только когда кадр
СЛИШКОМ детален (обратной ветки нет), а ось `noise` измеряется и не применяется
никогда. На фактуре он умеет только вычитать. Поэтому ось здесь написана с нуля
и со своей калибровкой.

---

КАЛИБРОВКА: ПОРОГ СТАВИТСЯ ВНУТРЬ ИЗМЕРЕННОГО РАЗРЫВА, И НИКАК ИНАЧЕ.

Порог, взятый из головы, на такой оси особенно вреден: он выглядит строгим и
пропускает настоящий шов. Поэтому `bar_from_clouds` принимает два ОБЛАКА
значений — заведомо бесшовные кадры и заведомо шовные, — находит между ними
разрыв и ставит порог в его середину. Если облака ПЕРЕКРЫВАЮТСЯ, порога нет:
функция возвращает «не смогли», а не компромиссное число. Порог вне разрыва —
украшение, и хуже отсутствия, потому что выглядит калибровкой.

НЕПРОВЕРЕНО (Ц4): облака на НАШИХ кадрах ещё не сняты — для этого нужен живой
выход Wan-Animate, а генерации в спринте нет. Модуль умеет считать ось и умеет
калиброваться; калибровочные числа появятся с первым выходом. До тех пор
`verdict` без явной планки честно отвечает «не смогли проверить».
"""

from __future__ import annotations

from .fork_identity import FAIL, PASS, UNMEASURED

#: Минимум пикселей с каждой стороны шва, чтобы статистика что-то значила.
#: ВЫБРАНО: на сотне пикселей медиана градиента пляшет сильнее измеряемого.
MIN_SIDE_PX = 500

#: Ширина кольца вдоль границы маски, px. Мерить надо У ШВА, а не по всей
#: площади: фон вдалеке от персонажа отличается от него законно — там другое
#: содержимое, — и включив его, мы намеряли бы разницу сюжетов, а не шва.
#: ВЫБРАНО 24: заметно больше блока сжатия (8..16) и меньше блока маски (32).
RING_PX = 24


def _gray(image):
    """Кадр -> яркость в 0..1. Одно место, где это решается (Е1)."""
    import numpy as np
    from PIL import Image
    from pathlib import Path

    if isinstance(image, (str, Path)):
        with Image.open(image) as im:
            arr = np.asarray(im.convert("RGB"), dtype="float64")
    elif hasattr(image, "convert"):
        arr = np.asarray(image.convert("RGB"), dtype="float64")
    else:
        arr = np.asarray(image, dtype="float64")
        if arr.ndim == 2:
            arr = arr[:, :, None].repeat(3, axis=2)
    if arr.max() > 1.0:
        arr = arr / 255.0
    # Веса яркости, а не среднее по каналам: зелёный несёт большую часть
    # воспринимаемой детали, и среднее размывает как раз то, что мерим.
    return arr[:, :, 0] * 0.299 + arr[:, :, 1] * 0.587 + arr[:, :, 2] * 0.114


def detail(gray, mask) -> float | None:
    """Мера ФАКТУРЫ: медиана модуля градиента внутри маски.

    Медиана, а не среднее: одна яркая кромка (край одежды, блик) утаскивает
    среднее и делает гладкую область «детальной». Медиана описывает основную
    массу пикселей, а её мы и сравниваем.
    """
    import numpy as np

    m = np.asarray(mask, dtype=bool)
    if m.sum() < MIN_SIDE_PX:
        return None
    gy, gx = np.gradient(np.asarray(gray, dtype="float64"))
    mag = np.hypot(gx, gy)
    return float(np.median(mag[m]))


def ring(mask, width: int = RING_PX) -> tuple:
    """Два кольца вдоль границы маски: внутреннее и внешнее.

    Возвращает `(внутри, снаружи)` — булевы маски одинакового устройства.
    Именно кольца, а не «вся маска против всего фона»: вдалеке от границы
    содержимое отличается законно, и разница сюжетов забила бы разницу шва.
    """
    import numpy as np

    from . import fork_mask

    m = np.asarray(mask, dtype=bool)
    grown = fork_mask.dilate(m, width)
    shrunk = ~fork_mask.dilate(~m, width)
    return (m & ~shrunk), (grown & ~m)


def seam(image, mask, *, width: int = RING_PX) -> dict:
    """Насколько фактура ВНУТРИ маски отличается от фактуры СНАРУЖИ.

    Возвращает отношение, а не разность: фактура кадра целиком зависит от
    сюжета и сжатия, и абсолютная разность несравнима между кадрами. Отношение
    безразмерно, и 1.0 означает «шва не видно по этой оси».
    """
    import numpy as np

    g = _gray(image)
    m = np.asarray(mask, dtype=bool)
    if m.shape != g.shape:
        return {"outcome": UNMEASURED, "ratio": None,
                "note": f"маска {m.shape} не по кадру {g.shape}"}

    inside, outside = ring(m, width)
    d_in, d_out = detail(g, inside), detail(g, outside)
    if d_in is None or d_out is None:
        return {"outcome": UNMEASURED, "ratio": None,
                "inside_px": int(inside.sum()), "outside_px": int(outside.sum()),
                "note": (f"у шва мало пикселей: внутри {int(inside.sum())}, "
                         f"снаружи {int(outside.sum())}, нужно по "
                         f"{MIN_SIDE_PX}. Это НЕ «шва нет».")}
    if d_out == 0:
        return {"outcome": UNMEASURED, "ratio": None,
                "note": ("снаружи нулевая фактура — сравнивать не с чем "
                         "(залитый фон)")}
    ratio = round(d_in / d_out, 4)
    return {"outcome": None, "ratio": ratio,
            "inside": round(d_in, 6), "outside": round(d_out, 6),
            "inside_px": int(inside.sum()), "outside_px": int(outside.sum()),
            "note": (f"фактура у шва: внутри {d_in:.6f}, снаружи {d_out:.6f}, "
                     f"отношение {ratio} (1.0 — шва по этой оси не видно)")}


def bar_from_clouds(seamless, seamed) -> dict:
    """Порог ИЗ РАЗРЫВА между двумя облаками. Перекрылись — порога нет.

    `seamless` — отношения на заведомо бесшовных кадрах, `seamed` — на заведомо
    шовных. Порог кладётся В СЕРЕДИНУ разрыва.

    ПОЧЕМУ ПЕРЕКРЫТИЕ — ЭТО ОТКАЗ, А НЕ КОМПРОМИСС. Если облака налезают друг
    на друга, никакой порог не разделит их без ошибок, и число, поставленное
    «примерно посередине», создаёт видимость калибровки там, где ось просто не
    различает случаи. Честный ответ — «эта ось на этом материале не работает»,
    и он дороже любого числа.

    Ось двусторонняя: шов бывает и когда внутри ГЛАЖЕ (модель размыла), и
    когда ДЕТАЛЬНЕЕ (модель дорисовала фактуру). Поэтому разрыв ищется по
    отклонению от единицы, а не по самому отношению.
    """
    a = sorted(abs(v - 1.0) for v in seamless)
    b = sorted(abs(v - 1.0) for v in seamed)
    if len(a) < 3 or len(b) < 3:
        return {"outcome": UNMEASURED, "bar": None,
                "note": (f"облака малы: бесшовных {len(a)}, шовных {len(b)}, "
                         f"нужно хотя бы по 3. По двум точкам разрыва нет.")}
    lo, hi = max(a), min(b)
    if hi <= lo:
        return {"outcome": UNMEASURED, "bar": None,
                "gap": round(hi - lo, 6),
                "note": (f"облака ПЕРЕКРЫЛИСЬ: бесшовные доходят до {lo:.4f}, "
                         f"шовные начинаются с {hi:.4f}. Разрыва нет, значит "
                         f"нет и порога — ось на этом материале не различает "
                         f"случаи. Число «примерно посередине» было бы "
                         f"украшением.")}
    return {"outcome": PASS, "bar": round((lo + hi) / 2, 4),
            "gap": round(hi - lo, 6), "seamless_max": round(lo, 4),
            "seamed_min": round(hi, 4),
            "note": (f"порог {((lo + hi) / 2):.4f} поставлен ВНУТРЬ разрыва "
                     f"[{lo:.4f}, {hi:.4f}] шириной {hi - lo:.4f}; "
                     f"бесшовных {len(a)}, шовных {len(b)}")}


def verdict(measured: dict, bar: dict) -> dict:
    """Виден ли шов. Без откалиброванной планки — «не смогли», а не «годно»."""
    if measured.get("ratio") is None:
        return {"outcome": UNMEASURED,
                "note": f"ось не измерена: {measured.get('note', '')}"}
    if bar.get("bar") is None:
        return {"outcome": UNMEASURED,
                "note": (f"планка не откалибрована: {bar.get('note', '')}. "
                         f"Отношение {measured['ratio']} само по себе ничего "
                         f"не значит — неизвестно, где проходит граница.")}
    off = abs(measured["ratio"] - 1.0)
    seen = off > bar["bar"]
    return {"outcome": FAIL if seen else PASS,
            "off": round(off, 4), "bar": bar["bar"],
            "note": (f"отклонение фактуры от единицы {off:.4f} при планке "
                     f"{bar['bar']}: "
                     f"{'ШОВ ВИДЕН' if seen else 'шва по этой оси не видно'}"
                     + (f" (внутри {'глаже' if measured['ratio'] < 1 else 'детальнее'})"
                        if seen else ""))}
