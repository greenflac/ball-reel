#: любое отклонение отношения от 1.0 здесь — собственный шум оси, а не шов.
SEAMLESS_SOURCES = ("chain_frames/*.png", "veoprobe/f_1080p/*.png",
                    "demo/kit/driving/*.jpg", "demo/hero.png")


def arbitrary_masks(h: int, w: int) -> dict:
    """Три ПРОИЗВОЛЬНЫХ положения маски на бесшовном кадре.

    Произвольных намеренно: шва нет нигде, значит место маски не должно менять
    ответ — а оно меняет, и насколько именно, показывает разброс по этим трём.
    Настоящая маска персонажа сюда не годится: она пришла бы из `fork_mask`, и
    тогда облако мерило бы ещё и качество сегментации.
    """
    import numpy as np

    out = {}
    m = np.zeros((h, w), dtype=bool)
    m[int(h * .30):int(h * .80), int(w * .35):int(w * .65)] = True
    out["center_box"] = m
    m = np.zeros((h, w), dtype=bool)
    m[int(h * .10):int(h * .55), int(w * .55):int(w * .90)] = True
    out["offset_box"] = m
    yy, xx = np.ogrid[:h, :w]
    out["ellipse"] = (((yy - h * .5) / (h * .28)) ** 2 +
                      ((xx - w * .5) / (w * .20)) ** 2) <= 1.0
    return out


