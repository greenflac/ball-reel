def bridge_frames(seam) -> int | None:
    """Сколько кадров моста стоит стык величиной `seam` типичных шагов.

    РЕШЕНИЕ ВЛАДЕЛЬЦА, ИЗ КОТОРОГО ВСЁ ЭТО СЛЕДУЕТ: идеальной петли в реальном
    драйвинге не бывает, подгонка нужна ВСЕГДА. Значит между концом и началом
    петли всё равно вставляется мост из промежуточных кадров, и вопрос не «годен
    ли стык», а «во сколько кадров он обойдётся».

    ПОЧЕМУ ПРОСТО ОКРУГЛЕНИЕ ВВЕРХ, А НЕ КОЭФФИЦИЕНТ. Наша мера стыка УЖЕ в
    нужной единице: «стык 3.48 типичных шага» буквально значит «не хватает
    примерно 3.5 кадров обычного движения этого клипа». Мост в 4 кадра проводит
    переход с нормальной для клипа скоростью; мост в 3 заставил бы его идти
    быстрее обычного движения, то есть дал бы рывок — ровно то, ради чего петля
    и отбиралась. Вверх, а не к ближайшему, по той же причине.

    Своей арифметики единицы здесь нет и быть не должно (Е1): приведение стыка
    к типичному шагу сделано в `score_pairs` и `pick_finalists`, сюда приходит
    уже приведённое число.

    `None` на входе — не ноль и не бесконечность: цену неизмеренного стыка эта
    функция не выдумывает, а возвращает `None`; три исхода разводит `bridge_cost`.
    """
    if seam is None:
        return None
    return int(math.ceil(float(seam)))


def bridge_cost(seams, *, max_frames=None) -> dict:
    """Цена моста по ЧЕТЫРЁМ осям сразу, с тремя исходами (Р1).

    `seams` — отображение «имя оси -> стык в типичных шагах ЭТОЙ оси или None».
    Значения приходят уже с весами: домножать их здесь значило бы завести второе
    место, где живут веса (Е1).

    ТРИ ИСХОДА, И ТРЕТИЙ НЕ СВОРАЧИВАЕТСЯ НИ В ПЕРВЫЙ, НИ ВО ВТОРОЙ:

        годно      измерены ВСЕ оси, мост не длиннее `max_frames` -> `frames`;
        не годно   мост длиннее `max_frames`. Это НЕ «годно подороже»: см.
                   `BRIDGE_MAX_FRAMES`. Сюда же попадает случай, когда планку
                   перевалила уже НИЖНЯЯ ГРАНИЦА по измеренным осям, — от
                   недостающей оси мост может только удлиниться, никогда не
                   укоротиться, поэтому такой вердикт измерения не требует;
        не смогли  хотя бы одна ось не ответила. `frames` тогда `None`, а
                   `floor` — «мост НЕ МЕНЬШЕ ЧЕМ», по одним измеренным осям.

    ЗАЧЕМ `floor` НАЗВАН ГРАНИЦЕЙ, А НЕ ЦЕНОЙ. Ровно это и было дефектом,
    который чинится: неизмеренная ось не попадала в максимум и потому
    УДЕШЕВЛЯЛА кандидата. Число по неполному набору осей — нижняя граница
    цены, и читаться оно обязано только так; ранжировать по нему кандидата
    наравне с полностью измеренным нельзя (см. `rank_loops`).
    """
    max_frames = BRIDGE_MAX_FRAMES if max_frames is None else max_frames
    measured = {k: float(v) for k, v in seams.items() if v is not None}
    missing = sorted(k for k, v in seams.items() if v is None)
    worst_axis = max(measured, key=measured.get) if measured else None
    seam = measured[worst_axis] if worst_axis is not None else None
    frames = bridge_frames(seam)
    if not measured:
        return {"outcome": UNMEASURED, "frames": None, "floor": None,
                "seam": None, "worst_axis": None, "unmeasured": missing,
                "measured": sorted(measured),
                "reason": "не измерена ни одна ось стыка"}
    if missing:
        if frames > max_frames:
            return {"outcome": FAIL, "frames": None, "floor": frames,
                    "seam": seam, "worst_axis": worst_axis,
                    "unmeasured": missing, "measured": sorted(measured),
                    "reason": (f"мост НЕ МЕНЬШЕ {frames} кадров уже по оси "
                               f"{worst_axis!r} при потолке {max_frames}; "
                               f"неизмеренная ось ({', '.join(missing)}) его "
                               f"только удлинит")}
        return {"outcome": UNMEASURED, "frames": None, "floor": frames,
                "seam": seam, "worst_axis": worst_axis, "unmeasured": missing,
                "measured": sorted(measured),
                "reason": (f"мост не меньше {frames} кадров, а точнее сказать "
                           f"нечем: не измерены оси {', '.join(missing)}")}
    if frames > max_frames:
        return {"outcome": FAIL, "frames": frames, "floor": frames,
                "seam": seam, "worst_axis": worst_axis, "unmeasured": [],
                "measured": sorted(measured),
                "reason": (f"мост {frames} кадров при потолке {max_frames}: "
                           f"хуже всех ось {worst_axis!r} ({seam:.2f} шага)")}
    return {"outcome": PASS, "frames": frames, "floor": frames, "seam": seam,
            "worst_axis": worst_axis, "unmeasured": [],
            "measured": sorted(measured), "reason": ""}


def rank_loops(loops) -> list:
    """Порядок карточек: ДВЕ ОЧЕРЕДИ, сначала полностью измеренные.

    ЧТО ЭТО ЧИНИТ, ИЗМЕРЕНО НА БОЕВОМ РОЛИКЕ (`assets/driving_yogaball.mp4`,
    362 кадра, голова подана из `head_scan`; прогон `rank_repro.py`):

        петля 114..162  max(поза 0.988, поток 0.910, пиксели 1.447,
                            ГОЛОВА 3.283) = 3.283, выигрыш 3.13x
        петля 309..357  max(поза 1.479, поток 2.141, пиксели 1.935,
                            головы НЕТ)   = 2.141, выигрыш 4.79x

    Вторая выглядела ЛУЧШЕ первой ровно потому, что лица не видно на кадре 309
    и ось головы не отработала: неизмеренная ось не попадала в максимум и
    работала как ноль. Её настоящий стык головы, померенный по соседним
    измеримым краям той же петли, — 11.74 типичных шага (306..357, 308..357 и
    310..357 дают то же число, 311..357 -> 10.67). Владелец увидел этот стык
    ГЛАЗАМИ на гифке и назвал его «явный стык на голове».

    ПРАВИЛО. Кандидат с неизмеренной осью НЕ РАНЖИРУЕТСЯ ВЫШЕ кандидата, у
    которого измерены все. Внутри своей очереди — по цене моста, при равной
    цене — по худшей оси, при равной оси — по номеру первого кадра.

    ПОЧЕМУ ИМЕННО ДВЕ ОЧЕРЕДИ, А НЕ ДВЕ ДРУГИЕ ВОЗМОЖНОСТИ:

    (а) ДОМЕР ПО БЛИЖАЙШЕМУ ИЗМЕРИМОМУ КРАЮ (сдвинуть i или j на 1-3 кадра).
        Отвергнут не потому, что не работает, — на этом ролике он как раз
        работает: четыре соседних края дают 11.74, 11.74, 11.74 и 10.67, то
        есть разброс 9%. Отвергнут потому, что это ИЗМЕРЕНИЕ ДРУГОЙ ПАРЫ,
        выданное за измерение этой (Е2: верь свидетельству — свидетельство
        здесь про кадр 306, а не про 309), и потому, что у него самого есть
        третий исход: когда соседние края тоже неизмеримы, вопрос возвращается
        сюда же. Домер стоит поверх двух очередей, если понадобится, и очередей
        не отменяет.
    (б) ДВЕ ОЧЕРЕДИ — взято. Оно ничего не выдумывает про неизмеренную ось и
        не выбрасывает кандидата: «не смогли» остаётся отдельным состоянием,
        видимым в отчёте, и стоит ровно столько, сколько стоит, — место в
        конце списка.
    (в) ПОМЕТКА БЕЗ ИЗМЕНЕНИЯ ПОРЯДКА — это ТЕКУЩЕЕ поведение, и оно подвело:
        пометка стояла строкой ПОД таблицей, а в самой таблице непроверенная
        петля показывала выигрыш 4.79x против 3.13x у проверенной. Клиент
        читает таблицу, а не сноску.
    """
    def key(lp):
        cost = lp.get("bridge") or {}
        measured = cost.get("outcome") == PASS
        price = cost.get("frames") if measured else cost.get("floor")
        return (0 if measured else 1,
                math.inf if price is None else price,
                math.inf if cost.get("seam") is None else cost["seam"],
                lp.get("i", 0))
    return sorted(loops, key=key)


def overlap(a, b) -> float:
    """Какую долю более КОРОТКОЙ из двух петель они делят.

    Долю от короткой, а не объединения: петля 41 кадра, целиком лежащая внутри
    петли 300 кадров, — это то же самое движение, и IoU в 0.14 сказал бы, что
    они разные.
    """
    inter = min(a["j"], b["j"]) - max(a["i"], b["i"]) + 1
    if inter <= 0:
        return 0.0
    return inter / min(a["frames"], b["frames"])


def select(cands, *, overlap_max=None, top=None) -> dict:
    """Принять несколько РАЗНЫХ петель, а не десяток сдвинутых на кадр.

    Кандидаты приходят отсортованными по стыку; принимается лучший, затем
    следующий, который существенно не перекрывается с уже принятыми.

    # DEBT(2026-08-20): ЗДЕСЬ ЖИВЁТ ТА ЖЕ ФОРМА ДЕФЕКТА, что чинилась в
    # `pick_finalists`, — порядок берётся по `score`, а измерены ли все оси у
    # этого `score`, функция не спрашивает. Сейчас это безвредно: конвейер
    # `find_loops` её не зовёт (единственные вызовы — из тестов), и цену моста
    # считает `pick_finalists`. Не тронуто намеренно: менять договор функции,
    # которую никто не вызывает, — это менять то, чего нельзя наблюдать (Ц8).
    # Настоящий вопрос к ней другой: нужна ли она вообще (Б4).
    """
    overlap_max = OVERLAP_MAX if overlap_max is None else overlap_max
    top = TOP_LOOPS if top is None else top
    kept, dropped = [], 0
    for c in cands:
        if len(kept) >= top:
            break
        if any(overlap(c, k) > overlap_max for k in kept):
            dropped += 1
            continue
        kept.append(c)
    return {"kept": kept, "dropped_overlap": dropped,
            "considered": len(cands)}


def loop_signature(state_at, i, j, *, phases=None) -> list | None:
    """Чем описывается петля при сверке «одно ли это движение».

    Не диапазоном кадров и не одной позой, а НЕСКОЛЬКИМИ ПОЗАМИ ПО ФАЗЕ цикла.
    Диапазон кадров — не движение: кадры 58..106 и 308..356 боевого ролика не
    пересекаются вовсе, а упражнение в них одно и то же.

    Возвращает список приведённых поз или None, если хоть одной из них нет:
    судить о совпадении по половине подписи нельзя (Р1).
    """
    phases = DUP_PHASES if phases is None else phases
    # ПЛОТНОСТЬ ВЫБОРКИ ОДНА НА ВСЕ ПЕТЛИ, а не «столько-то точек на петлю».
    # Найдено прогоном: при фиксированном ЧИСЛЕ точек петля из двух периодов
    # описывается вдвое реже, чем из одного, и мера Хаусдорфа объявляет одно и
    # то же движение разным (12.4 типичного шага при пороге 12.0). Шаг берётся
    # от самой короткой допустимой петли: `LOOP_MIN_FRAMES` кадров на `phases`
    # точек, то есть подпись любой петли — это её позы, снятые с одной частотой.
    every = max(1, round(LOOP_MIN_FRAMES / phases))
    out = []
    for frame in range(i, j, every):
        st = state_at(frame)
        if st is None:
            return None
        out.append(st)
    return out


def signature_gap(a, b):
    """Расхождение двух петель как ДВИЖЕНИЙ, в длинах торса.

    Мера Хаусдорфа между двумя наборами поз: у каждой позы одной петли ищется
    ближайшая поза другой, и берётся ХУДШИЙ из этих минимумов, в обе стороны.
    Читается буквально: «петли — одно движение, если каждая поза одной находит
    себе пару в другой, и наоборот».

    ПОЧЕМУ НЕ СВЕРКА ФАЗА-В-ФАЗУ, стоявшая здесь первой редакцией. Она ломалась
    на двух вещах сразу, и обе всплыли замером, а не рассуждением:
      * то же упражнение, снятое с другой точки цикла, считалось другим;
      * то же упражнение петлёй ВДВОЕ ДЛИННЕЕ (два периода вместо одного)
        раскладывалось по другим фазам и тоже считалось другим — на фикстуре
        «одно движение в двух местах» прибор выдавал 4 карточки вместо 2.
    Хаусдорф не знает ни про фазу, ни про длину: он сравнивает МНОЖЕСТВА поз.
    На боевом ролике петля 114..162 и вдвое длинная 114..210 расходятся на 1.9
    типичного шага, то есть узнаются как одно движение.

    ХУДШИЙ, А НЕ СРЕДНИЙ, и это тот же довод, что у сведения осей максимумом:
    совпадения в части цикла недостаточно, разошедшаяся поза обязана решать.

    ЧЕГО ЭТА МЕРА НЕ РАЗЛИЧАЕТ, И ЭТО НАДО ЗНАТЬ ЗАРАНЕЕ. Внутри позы расстояние
    усредняется по двенадцати суставам, поэтому упражнение, где ТЕ ЖЕ по
    величине махи делает другая пара конечностей, читается как близкое:
    ИЗМЕРЕНО на фикстуре, вертикальные махи руками против таких же махов ногами
    — 9.8 типичных шага, то есть ниже порога, хотя человек назвал бы это
    разными упражнениями. Различает мера ПОСАДКУ и РАЗМАХ (31.4 и 34.8 шага на
    тех же фикстурах). Это тот же класс, что растворение запястий в среднем, и
    закрывается он тем же — переходом на 133 точки, а не подкруткой порога.

    Возвращает None, если сравнить не удалось (Р1).
    """
    import numpy as np

    if not a or not b:
        return None
    # СЧИТАЕТСЯ ЦЕЛИКОМ NUMPY, а не двойным циклом по `pose_gap`. Это не
    # украшение: подпись длинной петли — шесть десятков поз, пар финалистов до
    # пяти, кандидатов сотни, и питоновский цикл превращал сьют из 4 секунд в
    # 70. Величина та же — среднее по общим суставам; сторожит
    # `test_the_vectorised_gap_equals_pose_gap`.
    def pack(sig):
        names = list(sig[0])
        xy = np.array([[st[n][0] for n in names] for st in sig], dtype="float64")
        vis = np.array([[st[n][1] >= pose.MIN_VISIBILITY for n in names]
                        for st in sig], dtype=bool)
        return names, xy, vis

    names_a, xy_a, vis_a = pack(a)
    names_b, xy_b, vis_b = pack(b)
    if names_a != names_b:
        return None
    dist = np.linalg.norm(xy_a[:, None, :, :] - xy_b[None, :, :, :], axis=-1)
    mask = vis_a[:, None, :] & vis_b[None, :, :]
    counts = mask.sum(axis=-1)
    if not counts.all():
        return None
    means = (dist * mask).sum(axis=-1) / counts
    forward = float(means.min(axis=1).max())
    backward = float(means.min(axis=0).max())
    return max(forward, backward)


def repeat_plan(length, *, fps=None) -> list:
    """Сколько повторов петли даёт продуктовую длину 5-10 с.

    Считается в ЧАСТОТЕ ИСТОЧНИКА: при 24 к/с четыре повтора петли в 53 кадра
    дают 8.71 с, а не 6.97 с, и пять повторов уже вылетают за потолок в 10 с.

    Склейка N повторов без дублирования стыкового кадра — N*(L-1)+1 кадров.
    Длина при этом остаётся вида 4k+1 автоматически, раз L-1 кратно 4; это
    проверяется `fork_comfy.snap_frames`, а не утверждается (Е1).
    """
    # Частоты нет — плана нет. Полоса 5-10 с задана в СЕКУНДАХ; сказать, сколько
    # повторов в неё попадёт, не зная, сколько секунд в кадре, невозможно, а
    # посчитать по своей частоте — значит выдать клиенту чужое число за его.
    if fps is None or fps <= 0:
        return []
    # Петля из одного кадра не склеивается: каждый повтор добавляет L-1 = 0
    # кадров, и «сколько повторов» не имеет ответа.
    if length < 2:
        return []
    # ВЕРХНЯЯ ГРАНИЦА ПЕРЕБОРА ВЫВЕДЕНА ИЗ ПОЛОСЫ, А НЕ ВЗЯТА ЛИТЕРАЛОМ.
    # Здесь стояло `range(1, 200)`, и на коротких петлях это врало: при L=2 и
    # 30 к/с в полосу влезает до 299 повторов, а перебор обрывался на 199 —
    # отчёт печатал «набирается ...», не набрав того, что набирается. Литерала
    # больше нет: потолок повторов — это потолок длины (`SECONDS_MAX` на
    # частоту), делённый на прирост от одного повтора.
    ceiling = int(fork_comfy.SECONDS_MAX * fps)
    out = []
    for n in range(1, (ceiling - 1) // (length - 1) + 1):
        total = n * (length - 1) + 1
        seconds = total / fps
        if seconds > fork_comfy.SECONDS_MAX:
            break
        if seconds < fork_comfy.SECONDS_MIN:
            continue
        out.append({"repeats": n, "frames": total,
                    "seconds": round(seconds, 2),
                    "snapped": fork_comfy.snap_frames(total)})
    return out


